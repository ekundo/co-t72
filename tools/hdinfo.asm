; ---------------------------------------------------------------------------
; Номер дискеты НЖМД и её метка -- в рамке панели CO.
;
; В шапке панели места нет: «Диск X  Файлов NN  Свободно NNN Кб.» занимает ровно
; сорок знаков, а панелей две -- вся строка. Зато свободна сама рамка: нижний её
; край это уголок, 38 линий и уголок. Пишем в него вывороткой -- теми же
; escape-последовательностями, какими CO рисует шапку панели, -- прижимая надпись
; к правому краю. Слева отведённую полосу добиваем самой рамкой: иначе от прошлой,
; более длинной метки остаётся хвост.
;
; Начало полосы выбрано не случайно: в той же рамке CO держит свой признак
; " >CO.PTK " (режим «ПС» -- дополнять команду для DOS перенаправлением в файл,
; флаг у него в B672). Сборка двигает его вплотную к уголку, а мы начинаем сразу
; за ним; метка обрезается так, чтобы на него не наехать никогда.
;
; Откуда что берётся:
;
;   номер -- из таблицы дискет НЖМД самой ОС (T_DrvA/T_DrvB, номер и первый
;            сектор). Её адрес у каждой сборки свой, поэтому он передаётся
;            снаружи: сборка находит таблицу по неизменному первому сектору
;            дискет 1 и 5 (2 и 188Ah). Читать таблицу, а не помнить своё,
;            важно: дискету могли назначить и командой «9» мимо CO;
;
;   метка -- с самой дискеты, из сектора за концом файловой системы (её пишет
;            HDIR /M). Читаем штатным дисковым обработчиком БСВВ -- тем самым,
;            адрес которого CO и так знает: описатель дисковой операции, в нём
;            диск, режим, дорожка, сектор и адрес буфера. Дорожка 164 -- она
;            последняя из разрешённых (БСВВ ругается с 0A5h), а БДОС туда не
;            заглядывает, там нет блоков файловой системы.
;
; Рисуется после штатной отрисовки панели, а не до: рисуя панель, CO чистит её
; поле и прихватывает три нижние строки точек нашей строки -- буквы выходили
; обрезанными снизу. А курсор в конце возвращаем туда же, куда его ставит сам
; CO, дорисовав рамку (строка 23, колонка 76).
;
; Врезано в конец отрисовки, а не в начало. Сначала перехват стоял по 091B, с
; которого отрисовка начинается, -- и надпись пропадала при листании панели:
; входов у отрисовки три (091B -- со сменой диска, 091E -- без неё, 0927 -- с
; другим построчным отрисовщиком), а листание идёт по 08CD прямо в 091E, мимо
; 091B. Сходятся все три в одном месте -- 097E, где стоит JMP на парковку
; курсора, -- и другого пути наружу у отрисовки нет. Перехватывать надо
; именно его: сама парковка (0FF3) для этого не годится, её зовут из
; четырнадцати мест по всему CO, и надпись полезла бы в помощь и просмотр.
; ---------------------------------------------------------------------------

PANEL   EQU 0B69Dh              ; номер активной панели: 1 или 2
DRVLET  EQU 03E91h              ; буквы дисков панелей
P_0FF3  EQU 00FF3h              ; CO: парковка курсора -- ею кончается отрисовка
                                ; панели, и это она затёрта по 097E
B_HEX   EQU 0F815h              ; БСВВ: вывод байта на экран 16-ричным
P_NCHR  EQU 00F75h              ; CO: напечатать A знаков, начиная с (HL)
P_LINE  EQU 00F7Fh              ; CO: напечатать A горизонталей рамки
BUF     EQU 00080h              ; штатный буфер обмена: БСВВ отдаёт одну запись
                                ; в 128 байт, а этот буфер любая программа CP/M
                                ; и так считает затираемым при чтении с диска

ROW     EQU 036h                ; нижний край рамки панели
COL     EQU 02Ch                ; и тринадцатая колонка: левее CO держит свой
                                ; признак записи " >CO.PTK " (режим «ПС», флаг у
                                ; него в B672). Его сборка сдвигает к уголку, на
                                ; колонку 2, -- см. hdinfo.py
PARKROW EQU 037h                ; куда CO уводит курсор, дорисовав рамку
PARKCOL EQU 06Ch
WIDTH   EQU 26                  ; сколько знаков рамки отдаём под надпись
LINE    EQU 08Dh                ; горизонталь рамки -- ею же и затираем
SIGNLEN EQU 4                   ; подпись сектора метки
LABLEN  EQU 32                  ; знаков в метке
LABTRK  EQU 164                 ; дорожка сектора метки
LABSEC  EQU 33                  ; и сектор в ней

        ORG ORIGIN

; Перехват конца отрисовки панели: по 097E у CO стоит переход сюда.
hook:   CALL P_0FF3             ; затёртая команда
        PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL info
        POP  H
        POP  D
        POP  B
        POP  PSW
        RET

info:   LDA  PANEL
        DCR  A
        STA  pan                ; 0 -- левая, 1 -- правая
        CALL cursor
        CALL show
        MVI  C,01Bh             ; курсор обратно на командную строку
        RST  4
        MVI  C,'Y'
        RST  4
        MVI  C,PARKROW
        RST  4
        MVI  C,PARKCOL
        RST  4
        RET

show:   CALL number             ; NZ -- дискеты нет, вся полоса остаётся рамкой
        JNZ  blank
        CALL readlab            ; длина метки -> lablen, 0 если метки нет
        MVI  A,6                ; в надписи всегда « NNNN »
        MOV  B,A
        LDA  lablen
        ORA  A
        JZ   sh1
        ADD  B                  ; ... и метка с пробелом за ней
        INR  A
        MOV  B,A
sh1:    MVI  A,WIDTH            ; слева добиваем рамкой: надпись прижата вправо
        SUB  B
        JZ   sh2
        CALL P_LINE
sh2:    CALL inv                ; номер и метку -- вывороткой, как шапку у CO
        MVI  C,' '
        RST  4
        LHLD num
        MOV  A,H
        CALL B_HEX
        MOV  A,L
        CALL B_HEX
        MVI  C,' '
        RST  4
        LDA  lablen
        ORA  A
        JZ   sh3
        LXI  H,BUF+SIGNLEN
        CALL P_NCHR             ; A знаков метки
        MVI  C,' '
        RST  4
sh3:    JMP  norm

blank:  MVI  A,WIDTH
        JMP  P_LINE

; Выворотка и обратно -- те же escape-последовательности, что у CO в шапке.
inv:    MVI  C,'b'
        JMP  esc
norm:   MVI  C,'a'
esc:    PUSH B
        MVI  C,01Bh
        RST  4
        POP  B
        RST  4
        RET

; Курсор на нижний край рамки нужной панели.
cursor: MVI  C,01Bh
        RST  4
        MVI  C,'Y'
        RST  4
        MVI  C,ROW
        RST  4
        LDA  pan
        ORA  A
        MVI  A,COL
        JZ   cu1
        ADI  40                 ; вторая панель -- на сорок колонок правее
cu1:    MOV  C,A
        RST  4
        RET

; Номер дискеты панели -> num. Z -- есть что показывать.
number: LXI  H,DRVLET
        LDA  pan
        ORA  A
        JZ   nu1
        INX  H
nu1:    MOV  A,M                ; буква диска панели
        SUI  'A'
        STA  drive              ; заодно номер диска для описателя
        CPI  2
        JNC  nu9                ; не A: и не B: -- дискет там не бывает
        LXI  H,TDRVA
        ORA  A                  ; признаки по номеру диска, а не по сравнению
        JZ   nu2
        LXI  D,5                ; записи таблицы по пять байт
        DAD  D
nu2:    MOV  E,M
        INX  H
        MOV  D,M
        XCHG
        SHLD num
        MOV  A,H
        ORA  L
        JZ   nu9                ; ноль -- на диске флоповод, а не дискета
        XRA  A                  ; Z -- есть что показывать
        RET
nu9:    MVI  A,1
        ORA  A
        RET

; Метка дискеты: читаем сектор за концом файловой системы и считаем, сколько
; знаков от неё показывать. Хвостовые пробелы отбрасываем, длинную обрезаем --
; в полосу должно влезть и « NNNN », и пробел за меткой.
readlab:XRA  A
        STA  lablen
        LXI  H,desc
        LDA  drive
        MOV  M,A
        CALL DISK
        LXI  H,BUF
        LXI  D,sign
        MVI  B,SIGNLEN
rl1:    LDAX D
        CMP  M
        RNZ                     ; подписи нет -- метки нет
        INX  H
        INX  D
        DCR  B
        JNZ  rl1
        LXI  H,BUF+SIGNLEN+LABLEN-1
        MVI  B,LABLEN
rl2:    MOV  A,M
        CPI  ' '
        JNZ  rl3
        DCX  H
        DCR  B
        JNZ  rl2
        RET                     ; метка из одних пробелов -- всё равно что нет
rl3:    MOV  A,B
        CPI  WIDTH-6
        JC   rl4
        MVI  B,WIDTH-7
rl4:    MOV  A,B
        STA  lablen
        RET

; Описатель дисковой операции БСВВ: диск, ?, режим, ?, дорожка, сектор, буфер.
desc:   DB 0, 0, 4, 0, LABTRK, LABSEC
        DW BUF
sign:   DB 'HDLB'
pan:    DB 0
drive:  DB 0
num:    DW 0
lablen: DB 0                    ; сколько знаков метки показываем
        END
