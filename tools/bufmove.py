#!/usr/bin/env python3
"""Убрать буферы CO из подэкранной области A000-DFFF.

Зачем. Окно A000-DFFF на Векторе с квазидиском -- не просто ОЗУ: при штатном
порте 10h = 23h там отображена страница первого квазидиска, а на время обмена
то же окно занимает сам квазидиск. Пока CO держит там буферы, работать со
вторым квазидиском (диск D:) нельзя: прочитанный сектор уезжает внутрь КД, а в
буфере остаются E5. Отключать первый КД на время обмена, как я пробовал в
пул-реквесте к T-72, на реальном железе нельзя -- чтение пойдёт с обоих дисков
сразу (ImproverX, MDOS_T-72#1).

Что куда. Замеры на стенде -- трассировка обращений к памяти с состоянием
банка, двенадцать сценариев от старта до запуска программы -- показали, что за
все операции CO занимает в окне ровно одну область, A000-A447: буфер чтения
CO.EXT/CO.MNU/CO.ZGR, буфер CO.PRM по A048, массив отметок в странице A1 и
обмен при запуске программы. Она переезжает целиком на 4800, со смещением
-5800h:

    A000 -> 4800   буфер обмена и чтения настроек
    A010 -> 4810   он же со смещением
    A048 -> 4848   CO.PRM, восемь записей
    A080 -> 4880   вторая запись буфера
    A100 -> 4900   ДМА пробы квазидиска
    A101 -> 4901   массив отметок (страница A1 -> 49)

Место выбрано так: образ CO кончается около 4600, буфер каталога занимает
5000-5FFF, между ними свободно. Ни одного непосредственного операнда CO туда не
указывает, и за двенадцать прогонов с отключённым дедупом в 4600-4FFF не было
ни одного обращения. Буферам отведено 4800-4FFF -- два килобайта, ровно
столько, сколько читает самый длинный из путей, а накладка с номером дискеты
(hdinfo.py) встала ниже, на 4600.

Страница отметок адресуется не только через LXI, но и арифметикой по старшему
байту -- SUI A1h, ADI A1h, MVI H,A1h, -- поэтому правятся и эти байты. Один из
них лежит внутри блока, который дизассемблер принял за данные, и найден
сканированием образа. А вот такой же MVI H,A1h по 349E трогать нельзя: это база
видеоплоскости, рядом с ней C1h, D0h и B0h -- остальные три. Стоило его
передвинуть, и панель начинала рисоваться в 4D00-4FFF; поймано на стенде.

Переезжает и мёртвая ветка пробы квазидиска -- 1C9B и 1CA8, читающие сектор с
дискеты и исполняющие его. Она отключена константой по 1C83: A = 2, два DCR,
JZ -- переход берётся всегда. Что она мертва, проверено пятью способами: во
всём образе нет ни одной ссылки внутрь 1C82-1CAA, кроме её же цикла повтора;
к константе никто не обращается; за восемь сценариев карта исполнения ни разу
не показала 1C8A и 1CA8; единственные записи в 1C83 делает загрузчик ОС, кладя
туда тот же 02, что лежит в файле; а контрольный опыт с константой 03 ветку
оживляет, и карта её ловит -- значит отрицательный результат настоящий. Читает
она сектор с дорожки 11, сектора 41 дискеты и вызывает его: на наших дискетах
там обычные данные файла, так что ветка ждёт раскладки родного дистрибутива
CO. Перенесена вместе с остальным, чтобы в окне не осталось ни одной ссылки.

Чего не трогаем:

  * 03E7 (LXI H,A000 / LXI D,DFFF) -- это не буфер, а само окно квазидиска;
  * обвязка 0420-0457, которая спаривает ОЗУ 6100-9FFF с окном A100-DFFF:
    это не буфер, а сохранение данных панели в страницу квазидиска, и смещение
    4000h там своё.

Буфер копирования. Его кусок -- целый экстент CP/M, 128 записей, 16 КБ: от
базы 6100 это 6100-A0FF, то есть хвостом на 256 байт в окне, и на файлах
примерно от 15,7 КБ это ломало бы D:. Длину трогать нельзя -- она не счётчик,
а число записей экстента из ФУБ; ведётся буфер указателем в операнде 17E7
(17E6 кладёт его в ДМА-ячейку и продвигает на 80h). Поэтому сдвинута база: на
6000, ровно на 256 байт, и кусок встаёт в 6000-9FFF впритык под границу окна.
Мест пять: три установки указателя и пара «заполнение плюс обход» у второго
входа цикла. Ниже 6000 ничего нет -- буфер каталога кончается на 5FFF.

Длина чтения настроек. Общий цикл 18C3 начинает счётчик записей с нуля и потому
читает до 128 записей, то есть 16 КБ от базы, а обрывается только по концу
файла. На стенде CO.ZGR в 16 КБ заливал A000-BBFF и сносил CO стек. Своего
счётчика этому пути дать негде: хвост под стеком занят почти целиком (1200
байт из 1216 до буфера дисковода), а выровненная по записи заглушка стоила бы
128. Поэтому путь переведён на уже имеющийся вход 18BB с той же базой и
счётчиком на шестнадцать записей -- 4800-4FFF, ровно отведённые два
килобайта. Правка в один байт, операнд JMP по 18EB.

Итог по счётчику проверен: A886h, куда цикл кладёт конечное значение, во всём
образе больше нигде не читается.
"""

import argparse
import sys

ORG = 0x100

OLD_BASE = 0xA000
NEW_BASE = 0x4800
SHIFT = OLD_BASE - NEW_BASE     # 5800h

# Места с непосредственным 16-битным операндом: адрес команды -> ожидаемый
# опкод и операнд. Список получен сканированием образа, а не листинга: часть
# кода дизассемблер принял за данные.
WORDS = [
    (0x13BA, 0x11, 0xA010),     # LXI D,A010
    (0x1434, 0x11, 0xA000),     # LXI D,A000
    (0x144B, 0x11, 0xA010),     # LXI D,A010
    (0x145B, 0x11, 0xA000),     # LXI D,A000
    (0x148E, 0x11, 0xA048),     # LXI D,A048 -- чтение CO.PRM
    (0x14CE, 0x21, 0xA048),     # LXI H,A048 -- разбор CO.PRM
    (0x1593, 0x21, 0xA000),     # LXI H,A000 -> A83E
    (0x17AC, 0x21, 0xA101),     # LXI H,A101 -- массив отметок
    (0x1836, 0x21, 0xA000),     # LXI H,A000 -> A855
    (0x187A, 0x11, 0xA000),     # LXI D,A000 -- ДМА первой записи
    (0x1888, 0x11, 0xA080),     # LXI D,A080 -- ДМА второй записи
    (0x1897, 0x21, 0xA000),     # LXI H,A000 -- забивка 1A при ошибке
    (0x18A4, 0x21, 0xA080),     # LXI H,A080 -- то же для второй записи
    (0x18BB, 0x11, 0xA000),     # LXI D,A000 -- вход на шестнадцать записей
    (0x18E8, 0x11, 0xA000),     # LXI D,A000 -- вход чтения настроек
    (0x1C6D, 0x01, 0xA100),     # LXI B,A100 -- ДМА пробы квазидиска
    (0x1C9B, 0x01, 0xA180),     # LXI B,A180 -- ДМА мёртвой ветки пробы
    (0x1CA8, 0xCD, 0xA180),     # CALL A180  -- и вызов прочитанного там же
    (0x1EAA, 0x21, 0xA101),     # LXI H,A101 -- массив отметок
    (0x31D5, 0x21, 0xA000),     # LXI H,A000 -> A855
    (0x3A56, 0x21, 0xA000),     # LXI H,A000 -> A83E
]

# Старший байт страницы отметок, собираемый арифметикой. Не всякий байт A1h
# в образе относится сюда: по 349E такой же MVI H,A1h задаёт базу видеоплоскости
# (рядом с ним C1h, D0h и B0h -- остальные три), и трогать его нельзя.
BYTES = [
    (0x17C0, 0xD6, 0xA1),       # SUI  A1h
    (0x1F1B, 0xC6, 0xA1),       # ADI  A1h
    (0x1F36, 0x26, 0xA1),       # MVI  H,A1h  -- лежит внутри блока данных
]

# Буфер копирования. Кусок там -- целый экстент, 128 записей, 16 КБ: от 6100
# это 6100-A0FF, то есть хвостом на 256 байт в окне. Сдвигаем базу на 6000 --
# ровно настолько, чтобы кусок встал в 6000-9FFF, впритык под границу.
COPY_OLD = 0x6100
COPY_NEW = 0x6000
COPY = [
    (0x15D5, 0x21),             # LXI H,6100 -> указатель по 17E7
    (0x15E0, 0x21),             # то же, повторный заход
    (0x161C, 0x21),             # то же, ветка с ФУБ по 005C
    (0x18F1, 0x11),             # LXI D,6100 -- ДМА второго входа цикла
    (0x3216, 0x21),             # LXI H,6100 -- обход заполненного буфера
]

HOOK = 0x18EB                           # JMP 18C3 у пути настроек
HOOK_OLD = bytes([0xC3, 0xC3, 0x18])    # безлимитный вход
HOOK_NEW = bytes([0xC3, 0xBB, 0x18])    # ... вместо него вход на 16 записей


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    a = p.parse_args()

    d = bytearray(open(a.infile, 'rb').read())

    for at, opcode, want in WORDS:
        off = at - ORG
        got = d[off + 1] | d[off + 2] << 8
        if d[off] != opcode or got != want:
            sys.exit('по %04X ожидался %02X %04X, а лежит %02X %04X'
                     % (at, opcode, want, d[off], got))
        new = want - SHIFT
        d[off + 1] = new & 0xFF
        d[off + 2] = new >> 8

    for at, opcode, want in BYTES:
        off = at - ORG
        if d[off] != opcode or d[off + 1] != want:
            sys.exit('по %04X ожидалось %02X %02X, а лежит %02X %02X'
                     % (at, opcode, want, d[off], d[off + 1]))
        d[off + 1] = want - (SHIFT >> 8)

    for at, opcode in COPY:
        off = at - ORG
        got = d[off + 1] | d[off + 2] << 8
        if d[off] != opcode or got != COPY_OLD:
            sys.exit('по %04X ожидался %02X %04X, а лежит %02X %04X'
                     % (at, opcode, COPY_OLD, d[off], got))
        d[off + 1] = COPY_NEW & 0xFF
        d[off + 2] = COPY_NEW >> 8

    # Чтение настроек -- на вход с ограниченным счётчиком.
    off = HOOK - ORG
    if bytes(d[off:off + 3]) != HOOK_OLD:
        sys.exit('по %04X не JMP 18C3, а %s' % (HOOK, d[off:off + 3].hex()))
    d[off:off + 3] = HOOK_NEW

    open(a.outfile, 'wb').write(bytes(d))
    print('буферы из окна: %d адресов и %d страничных байт на %04X, '
          'буфер копирования на %04X, настройки через вход 18BB'
          % (len(WORDS), len(BYTES), NEW_BASE, COPY_NEW))


if __name__ == '__main__':
    main()
