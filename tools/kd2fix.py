#!/usr/bin/env python3
"""Правка T-72: не гасить первый квазидиск при обращении ко второму.

Драйвер квазидиска перед обменом делает `XRA A / OUT 10h` -- «отключить первый
диск». Для C: это безвредно, следующей же командой туда уходит конфиг. А для D:
это гасит окно A000-DFFF, где у T-72 живёт обычное ОЗУ, и второй квазидиск тут
же занимает то же окно. Программа, чей буфер лежит в этой области (у CO он по
A000), получает вместо данных то, что осталось в буфере: читается мусор, а
запись уходит мимо диска.

Гасить не нужно: три байта меняются на NOP. В упакованном образе ОС процедуры
чтения и записи ссылаются на одно и то же место, поэтому правка одна на обе.

Работает и с ПЗУ (.rom), и с квазидиском (.edd): в первом случае правится файл
целиком, во втором -- запись внутри образа, с пересчётом её контрольной суммы
(две одинаковые копии по 0x3F000 + номер записи * 2).
"""

import argparse
import sys

OLD = b'\xaf\xd3\x10'      # XRA A / OUT 10h
NEW = b'\x00\x00\x00'      # NOP NOP NOP
ROM_AT = 0x1F15            # os-t72hx.rom: проверено разбором распакованной ОС
EDD_AT = 0x38895           # тот же код в OS.COM на квазидиске
CSUM = 0x3F000


def rec_of(off):
    """Номер 128-байтной записи квазидиска по смещению в файле."""
    if off >= 0x39F80:
        return int((0x3EF80 - (off & ~0x7F)) / 0x80)
    return 32 + int((0x39F80 - (off & ~0x7F)) / 0x80)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    args = p.parse_args()

    d = bytearray(open(args.infile, 'rb').read())
    at = EDD_AT if len(d) == 0x40000 else ROM_AT
    if d[at:at + 3] != OLD:
        sys.exit('по %05X не %s, а %s -- незнакомая сборка ОС'
                 % (at, OLD.hex(), bytes(d[at:at + 3]).hex()))
    d[at:at + 3] = NEW

    if len(d) == 0x40000:
        r = rec_of(at)
        base = at & ~0x7F
        s = sum(d[base:base + 128]) & 0xFF
        d[CSUM + r * 2] = d[CSUM + r * 2 + 1] = s
        print('квазидиск: правка по %05X, запись %d, контрольная сумма %02X' % (at, r, s))
    else:
        print('ПЗУ: правка по %05X' % at)
    open(args.outfile, 'wb').write(bytes(d))


if __name__ == '__main__':
    main()
