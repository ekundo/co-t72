; ---------------------------------------------------------------------------
; HDIR.COM -- каталоги «дискет» НЖМД и поиск файла по всему винчестеру.
;
;   HDIR              каталоги всех дискет, на которых что-то есть
;   HDIR 5            каталог дискеты 5
;   HDIR 5-1F 40      дискеты 5..1F и дискета 40
;   HDIR *.COM        поиск по всем дискетам
;   HDIR 10-20 DIZ*   поиск на дискетах 10..20
;   HDIR /N           без остановок на каждой странице
;   HDIR ?            подсказка
;
; Номера дискет 16-ричные -- такие же, как в команде «9» и в СС+7 у CO.
; Номер от шаблона отличается на глаз: если в слове есть «.», «*» или «?» --
; это шаблон, иначе номер. Шаблон обычный, как в МикроДОС: «*» добивает поле
; вопросами, «?» -- любой знак. Без точки расширение считается любым.
;
; При выводе в файл (`HDIR *.COM >SPISOK.TXT`) остановки снимаются сами.
;
; Русский вариант: код общий, здесь только выбор сообщений. Английский -- в
; hdir-en.asm.
;
;   python3 asm8080.py hdir.asm -o HDIR.COM
; ---------------------------------------------------------------------------

