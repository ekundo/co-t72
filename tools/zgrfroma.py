#!/usr/bin/env python3
"""Перенос файлов по CO.ZGR -- только при запуске с дискеты A:.

    ./zgrfroma.py CO.COM out.com

Зачем. При старте CO смотрит, с какого диска её запустили: первый знак
командной строки ПКК (DF15). Не «C» -- значит запуск с дискеты, и CO
переносит на C: файлы из списка CO.ZGR, спрашивая про каждый, что уже есть.

Беда в том, что «не C» -- это и B:. А каталог диска B: CO держит копией в ОЗУ
по 4000-4FFF, и там же лежит её пусковой код: заставка, проба оборудования,
проверка CO.ZGR, переносчик накладок. Перенос по CO.ZGR читает каталог
стартового диска -- и, если стартовали с B:, ОС кладёт его ровно поверх
работающего кода. Снято на стенде: при ВК на CO.COM с панели B: записи в
4400-4FFF идут из обменных подпрограмм ОС (E414, E3CA), CO показывает заставку
и виснет синим экраном. С A: того же не случается: её каталог ложится с 5000.

Чинится проверкой: перенос осмыслен только при запуске с A:. Так это и в
описании -- «при запуске оболочки с диска A:», -- и байт на это есть:

    3E9B  CPI 43h ('C') / JZ 3F2E   -- было: «с C: -- ничего не переносим»
    3E9B  CPI 41h ('A') / JNZ 3F2E  -- стало: «переносим только с A:»
"""

import argparse
import sys

ORG = 0x100
AT = 0x3E9B
OLD = bytes([0xFE, 0x43, 0xCA, 0x2E, 0x3F])     # CPI 'C' / JZ 3F2E
NEW = bytes([0xFE, 0x41, 0xC2, 0x2E, 0x3F])     # CPI 'A' / JNZ 3F2E


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    a = p.parse_args()

    d = bytearray(open(a.infile, 'rb').read())
    off = AT - ORG
    if bytes(d[off:off + len(OLD)]) != OLD:
        sys.exit('по %04X не проверка стартового диска, а %s -- это не тот CO'
                 % (AT, d[off:off + len(OLD)].hex()))
    d[off:off + len(NEW)] = NEW
    open(a.outfile, 'wb').write(bytes(d))
    print('перенос по CO.ZGR: только при запуске с A: (правка по %04X)' % AT)


if __name__ == '__main__':
    main()
