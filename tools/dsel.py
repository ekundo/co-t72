#!/usr/bin/env python3
"""Диск D: в CO -- второй квазидиск.

CO знает три диска: A:, B: и квазидиск C:. Каталоги он читает через БДОС, так
что четвёртый диск ему по силам.

Меню выбора диска по клавише 7 у CO собрано из блока строк, за которым сразу
идёт код -- четвёртую строку дописать некуда, а пункты B: и D: включаются
независимо, так что порядок строк меняется. Поэтому меню целиком переехало в
хвост: список собирается в буфере под текущие настройки, буквы лежат в такой же
таблице рядом.

Запись на D: -- разметка диска, а не порт
-----------------------------------------
Порт переключать не надо вовсе. Второй квазидиск сидит на порту 11h, но в CO
`OUT 11h` не нужен: свои прямые обращения к квазидиску (`OUT 10h` по 03B9 03DA
03FA 040C 0D9A 0DEA 1CED 1CF2 348F 34B4) CO делает только на ветке 'C', а на
D: он идёт через дисковый вызов БСВВ -- и там ОС сама выбирает порт по номеру
диска, ровно такой же самомодификацией операнда:

    L_E2C4: MOV C,M / ... / JNC L_KD        ; диск >= 2 -- это квазидиск
    L_KD:   LDA L_E98A / ADI 0Eh / STA L_E352+1   ; диск 2 -> 10h, диск 3 -> 11h

(Source/_E200h.asm в MDOS_T-72). Диск C: у CO -- номер 2, D: -- номер 3, так
что запись на D: через ОС попадает на нужный порт без единой правки в CO.

Ломали копирование две проверки буквы, которые решают не «куда писать», а «как
устроен диск»:

    1DE6  MOV A,M / CPI 'C' / MVI A,40h / JZ 1DF0   сколько записей в каталоге
    1EC2  LDA A849h / CPI 'C'                       ширина номера блока в записи

Квазидиск маленький, номера блоков в нём влезают в байт (16 штук на запись);
дискета на 390 блоков требует слова (8 штук на запись). Для D: CO брал
дискетный вариант и читал каталог второго квазидиска парами байт. Из пары
(блок, блок) получался адрес A1xx + старший байт, и CO рассыпал 5Ah по всей
памяти от A100 до D500 -- вместе со своим стеком у BC00 и перенесённым туда
хвостом. Карта исполненных адресов (EMU80_COV_*) показывала это как срыв в
буфер копирования: последний осмысленный адрес 2A09, дальше сплошной прогон
5A96..63C0 -- байты самого ARC.COM, исполняемые как код.

Обе проверки заменены на месте вызовом общей: 'C'-43h = 0, 'D'-43h = 1, младший
бит отбрасывается -- Z для обеих букв, 'A' и 'B' дают FEh. Трамплин не нужен:
CALL вместе с загрузкой буквы короче исходного CPI с загрузкой.

Проверено на стенде с двумя квазидисками (out/co-t72.edd как C:, образ с
9 файлами как D:):
  * панель открывает D:, читает каталог и показывает его верно;
  * копия A:ARC.COM на D: проходит: было 9 файлов, стало 10, ARC.COM на месте
    и после перечитывания панели;
  * C: не задет: копия на C: работает как раньше, панель гоняется
    D: -> C: -> D: -> C: без ошибок чтения.

Что показала проверка на новой T-72 (15.09.2026):

  * панель D: открывается, каталог второго квазидиска читается;
  * копирование идёт, три файла доходят целыми;
  * на четвёртом -- ошибка БСВВ на записи каталога: D=22 (БДОС «создать
    файл»), ST=02 (не сошлась контрольная сумма сектора), T=0 S=2.

Окно A000-DFFF тут ни при чём, хотя сначала показалось обратное. В обмене с
квазидиском БСВВ гасит первый КД (XRA A / OUT 10h) и шлёт конфиг на порт
выбранного диска -- 10h или 11h. Конфиг считается по дорожке, и в выпущенных
ромах это ANI 0Ch / ORI 010h: взведён только бит 4 (стековый режим), бит 5
(подмена окна A000-DFFF) не взведён. На гитхабе в исходниках там ORI 033h, но
собранные ромы -- с 010h, проверено по всем четырём.

Отсюда: во время ЛЮБОГО обмена с квазидиском, хоть C:, хоть D:, окно показывает
экран, а не ОЗУ. Никакой разницы между первым и вторым КД нет, и буферы CO
ради D: переносить не нужно. Обмен и так идёт через 4100 и 6100 -- ниже A000.

Что проверять дальше: сам образ второго квазидиска. Три файла записались, то
есть карта на месте и запись работает; ошибка пришла на секторе 2 нулевой
дорожки -- это вторая запись каталога, входы 4..7. Первая (входы 0..3) прошла.
И CO ещё до копирования говорил «файл уже есть» на заведомо пустом диске, то
есть каталог читался не пустым. Похоже, образ подготовлен не тем, чем надо:
контрольные суммы секторов считает сама ОС, и правильно разметить квазидиск
может только её команда «8 D: F» (P_E5D0, второй КД она поддерживает). Значит
сначала формат средствами ОС, потом копирование.

Разобранные тупики -- не проверять заново
-----------------------------------------
* Переключать порт квазидиска в CO не нужно и нечем помочь: на D: ни одна из
  десяти команд `OUT 10h` не исполняется. Ставить порт по букве в одном месте
  (3E9B) вредно -- он «залипает» и ломает чтение C:.
* Внутрь процедуры записи 03DE зайти вызовом нельзя: она прячет SP в 00F0,
  подключает страницу и ставит стек на данные командой SPHL. RET возвращаться
  некуда.
* Подмена CALL 03DE у вызывающих (2A17, 2E4E, 3AB9, 3F58) разваливает экран.
* Восемь мест с `CPI 43h` (CHECKS_OFF) уводить на ветку C: не надо: из них
  разметку задают только 1DE7 и 1EC5 (они и переписаны здесь по-другому),
  0B5F и 0B6E выбирают строку заголовка панели, 0262 и 027A ломают чтение
  каталога, а 3E9B увёл бы запись на прямой доступ к первому квазидиску.

Доступность D: пока зашита в самом коде ('Y' по адресу метки dflag). Настройку в
параметрах и её хранение ещё предстоит сделать: в CO.PRM для флага годится
только хвост файла за пределами читаемого старым CO, а буква панели там
упакована в два бита (1=A, 2=B, 3=C) -- под D: остаётся свободный бит 6.

Тем же измерением проверен и второй способ: те же сравнения можно переписать не
подпрограммой, а заменой JZ на JNC (три байта: 1DEB, 1ECC, 3E9D) -- «не меньше
C:» вместо «равно C:». Работает так же; здесь оставлен вариант с подпрограммой,
он не зависит от того, какая буква у диска следующая по алфавиту.
"""

