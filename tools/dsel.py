#!/usr/bin/env python3
"""Диск D: в CO -- второй квазидиск.

CO знает три диска: A:, B: и квазидиск C:. Каталоги он читает через БДОС, так
что четвёртый диск ему по силам -- упирается всё в две вещи.

Первая: восемь мест, где буква сравнивается с 'C' и это значит «квазидиск,
физических операций не надо». Для D: ответ такой же, поэтому каждое такое место
уводится трамплином в хвост, где проверяются обе буквы. Вместо сравнения ставим
JMP -- он не трогает стек, так что RET в трамплине работает ровно как RZ на
прежнем месте.

Вторая: меню выбора диска по клавише 7. У CO оно собрано из блока строк, за
которым сразу идёт код -- четвёртую строку дописать некуда, а пункты B: и D:
включаются независимо, так что порядок строк меняется. Поэтому меню целиком
переехало в хвост: список собирается в буфере под текущие настройки, буквы
лежат в такой же таблице рядом.

Что сделано и проверено на стенде с двумя квазидисками:
  * панель открывает D:, читает каталог и показывает его верно;
  * меню собирается под настройки: B: и D: появляются каждый по своему признаку.

Что ещё не работает: копирование НА D:. Причина найдена картой исполненных
адресов (стенд Emu80, EMU80_COV_*): при копировании на C: срабатывают восемь
команд `OUT 10h` -- CO пишет на квазидиск сам, минуя ОС, прямо в порт. При
копировании на D: не срабатывает ни одна: второй квазидиск сидит на порту 11h,
а такой команды в CO нет вовсе (`OUT 11h` в образе не встречается ни разу).
Каталог при этом читается через БДОС, поэтому панель D: работает.

Параметризация порта написана (build_ports: правит операнд всех десяти OUT на
10h или 11h), место под неё освобождено -- hddsel больше не держит свои 128 байт
под запись, а пользуется штатным буфером обмена по 0080. Но запись на D: от
этого не заработала, и причина теперь другая: порт ставится по букве диска в
одном из сравнений и остаётся таким до следующего, а операции чередуются -- CO
читает каталог C: тем же прямым доступом, и с оставшимся 11h чтение ломается.

Трасса самой операции (стенд, EMU80_TRACE_*) показала, как устроена запись на
квазидиск: с 03DE CO готовит адреса, запрещает прерывания, прячет SP в 00F0,
подключает страницу (03F9), ставит стек на данные командой SPHL и переносит их
чередой PUSH, а на выходе (040B) возвращает память и стек. То есть внутри стек
-- рабочий инструмент, а не то, чем можно пользоваться.

Отсюда единственный путь: править операнды двух OUT в самой процедуре, а делать
это до входа в неё -- у вызывающих. Вызовы записи приходят из 2A17, 2E4E, 3AB9 и
3F58. Попытка подменить их на свой переходник (build_ports/kdwrite: сохранить
PSW и HL, поставить операнды по букве из B673, прыгнуть в 03DE) разваливает
экран в кашу с первого же обращения к диску -- значит либо 03DE зовут не только
эти четверо, либо переходник ломает что-то ещё в состоянии вызывающего. Код
оставлен, подмена выключена; разбираться дальше нужно с трассой вокруг самих
вызывающих, а не вокруг записи.

Следующая попытка -- переключать порт прямо в обвязке обращения -- разбилась о
другое: `XRA A / OUT 10h` и `MVI A,23h / OUT 10h` по длине точно совпадают с
CALL, но зайти туда вызовом нельзя. После OUT 10h страница квазидиска
подменяет часть адресного пространства вместе со стеком, и RET возвращается уже
не туда -- CO не доживает до первой панели, МикроДОС отвечает «Неверное имя».
Оригинальный код между переключениями стека не касается вовсе, и это не
случайность.

Значит остаётся либо JMP-трамплин на каждое из восьми мест со своим адресом
возврата (около 19 байт на место), либо самомодификация операнда с обновлением
в тот момент, когда CO запоминает букву диска (3E9B). Первое дороже по месту,
второе уже пробовалось и до записи не довело -- разбираться дальше нужно с
трассировкой самой операции копирования, а не по буквам.

Восемь мест с
`CPI 43h` тут ни при чём -- проверено по одному: с ними копирование ломается так
же, а два из них (0262 и 027A, выбор диска для чтения каталога) вдобавок
разваливают панели. Список сохранён в CHECKS_OFF как разобранный тупик.

    OUT 10h: 03B9 03DA 03FA 040C 0D9A 0DEA 1CED 1CF2 348F 34B4

Доступность D: пока зашита в самом коде ('Y' по адресу метки dflag). Настройку в
параметрах и её хранение ещё предстоит сделать: в CO.PRM для флага годится
только хвост файла за пределами читаемого старым CO, а буква панели там
упакована в два бита (1=A, 2=B, 3=C) -- под D: остаётся свободный бит 6.
"""

import argparse
import sys

ORG = 0x100

# точки входа CO
SEL_PANEL = 0x0E4D     # HL += 1, если активна вторая панель
MENU = 0x0CF1          # выбор из горизонтального меню: HL -- строки, D -- сколько, E -- текущий
REDRAW = 0x0FE0        # перерисовать панели
REREAD = 0x28AE        # хвост «7-Диск»: записать букву из B и перечитать панель
PANEL_DRV = 0x3E91     # буквы дисков панелей
DISK_B = 0x3E97        # настройка «Диск B доступен» -- 'Y' или 'N'

MENU_ENTRY = 0x2870    # начало обработчика «7-Диск»
MENU_END = 0x28AE      # общий хвост, его оставляем на месте
MENU_REF = 0x0600      # запись «клавиша 7 -> обработчик» в таблице клавиш

# Места, где 'C' означает «это квазидиск». Для каждого: адрес, сколько байт
# занимает проверка вместе с тем, что к ней прицеплено, и как её пересобрать.
#   'ret'  -- CPI 'C' / RZ
#   'jz'   -- CPI 'C' / JZ target
#   'jz+a' -- CPI 'C' / MVI A,n / JZ target        (MVI выполняется всегда)
#   'jz+ah'-- CPI 'C' / MVI A,n / LXI H,nn / JZ target
CHECKS_OFF = [
    (0x0262, 'ret', 3),
    (0x027A, 'ret', 3),
    (0x0B5F, 'jz', 5),
    (0x0B6E, 'jz', 5),
    (0x1DE7, 'jz+a', 7),
    (0x1EC5, 'jz+ah', 10),
    (0x3E9B, 'jz', 5),
]
# Разобранный тупик, см. шапку: ни по одному, ни все вместе эти места
# копирование на D: не чинят, а 0262 и 027A ещё и ломают чтение каталога.
# Порт переключаем в одном месте -- там, где CO запоминает букву текущего диска
# (3E9B: STA B673h). Семь трамплинов сразу не помещаются: хвост упирается в стек.
CHECKS = []

# Прямые обращения к квазидиску: XRA A / OUT 10h -- подключить страницу диска,
# MVI A,23h / OUT 10h -- вернуть память. Второй квазидиск сидит на порту 11h,
# косвенного OUT у 8080 нет, поэтому операнд правим на месте.
# Обвязка у всех обращений одинаковая: XRA A / OUT 10h -- подключить страницу
# квазидиска, MVI A,23h / OUT 10h -- вернуть основную память. Обе меняем на вызов
# подпрограммы, которая смотрит текущий диск и выбирает порт: у первого квазидиска
# он 10h, у второго 11h. Размер сходится байт в байт -- 3 и 4.
BANK_ON = [0x03B8, 0x03F9, 0x0D99, 0x348E]
BANK_OFF = [0x03D8, 0x040A, 0x0DE8, 0x34B2]
DRIVE = 0xB673         # букву текущего диска CO кладёт сюда (3E9B: STA B673h)

WRITE = 0x03DE         # запись сектора на квазидиск
WRITE_CALLERS = [0x2A17, 0x2E4E, 0x3AB9, 0x3F58]
WRITE_PORTS = [0x03FA, 0x040C]     # операнды OUT внутри записи


class Asm:
    def __init__(self, org):
        self.org, self.code, self.labels, self.fixups = org, bytearray(), {}, []

    def label(self, name):
        self.labels[name] = self.org + len(self.code)

    def here(self):
        return self.org + len(self.code)

    def db(self, *b):
        self.code += bytes(b)

    def word(self, op, value):
        self.code += bytes([op, value & 0xFF, value >> 8])

    def ref(self, op, name):
        self.code += bytes([op])
        self.fixups.append((len(self.code), name))
        self.code += b'\0\0'

    def bytes(self):
        out = bytearray(self.code)
        for at, name in self.fixups:
            if name not in self.labels:
                sys.exit('нет метки %s' % name)
            out[at] = self.labels[name] & 0xFF
            out[at + 1] = self.labels[name] >> 8
        return bytes(out)


def build_ports(at):
    """Порт квазидиска перед записью -- и сразу переход в саму запись.

    Внутрь процедуры записи не зайти ни вызовом, ни ничем: она прячет SP в 00F0,
    ставит стек на данные командой SPHL и гонит их чередой PUSH. Поэтому порт
    выставляем до входа, у вызывающих: подменяем их CALL на свой, правим два
    операнда OUT по букве текущего диска и прыгаем в запись -- её RET вернётся
    к вызывающему сам.
    """
    a = Asm(at)
    a.label('kdwrite')
    a.db(0xF5, 0xE5)                               # PUSH PSW / PUSH H
    a.db(0x3E, 0x10)                               # MVI A,10h -- порт первого квазидиска
    a.word(0x3A_00 >> 8 | 0x3A, DRIVE) if False else None
    a.word(0x21, DRIVE); a.db(0x7E)                # LXI H,drive / MOV A,M
    a.db(0xFE, 0x44)                               # CPI 'D'
    a.db(0x3E, 0x10)                               # MVI A,10h (флаги не трогает)
    a.ref(0xC2, 'wput')
    a.db(0x3E, 0x11)                               # MVI A,11h
    a.label('wput')
    for port in WRITE_PORTS:
        a.word(0x21, port); a.db(0x77)             # LXI H,операнд / MOV M,A
    a.db(0xE1, 0xF1)                               # POP H / POP PSW
    a.word(0xC3, WRITE)
    return a.bytes(), a.labels


def build(at, image, ports_labels, flag_addr=None):
    """Собрать хвост: трамплины проверок и меню выбора диска."""
    a = Asm(at)
    a.labels.update(ports_labels)
    trampolines = {}

    # Данные держим в начале хвоста: конец резидента вплотную подходит к стеку
    # CO на BC00, и всё, что окажется под ним, стек рано или поздно затрёт.
    a.ref(0xC3, 'start')
    a.label('dflag'); a.db(0x59)         # 'Y' -- пока настройка не заведена
    a.label('letters'); a.code += bytes(6)
    a.label('strbuf'); a.code += bytes(24)
    a.label('start')

    # ---------------- трамплины «C: или D:» ----------------
    for addr, kind, size in CHECKS:
        off = addr - ORG
        assert image[off:off + 2] == b'\xfe\x43', hex(addr)
        back = addr + size
        trampolines[addr] = a.here()
        # Для D: только переключаем порт и идём дальше обычным путём: увести его
        # в ветку C: нельзя -- проверено, панели начинают сыпать ошибками диска.
        if kind == 'ret':
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.db(0xC8)   # 'C' -- порт 10h и назад
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')               # 'D' -- порт 11h
            a.word(0xC3, back)
        elif kind == 'jz':
            target = image[off + 3] | image[off + 4] << 8
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.word(0xCA, target)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
        elif kind == 'jz+a':
            val = image[off + 3]
            target = image[off + 5] | image[off + 6] << 8
            name = 'q%04x' % addr
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.ref(0xCA, name)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
            a.label(name)
            a.db(0x3E, val); a.word(0xC3, target)
        elif kind == 'jz+ah':
            val = image[off + 3]
            hl = image[off + 5] | image[off + 6] << 8
            target = image[off + 8] | image[off + 9] << 8
            name = 'q%04x' % addr
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.ref(0xCA, name)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
            a.label(name)
            a.db(0x3E, val); a.word(0x21, hl); a.word(0xC3, target)

    # ---------------- меню выбора диска ----------------
    # Собираем список пунктов под текущие настройки: A: и C: есть всегда, B: и
    # D: -- по своим признакам. Строки складываем в буфер, буквы -- в таблицу
    # рядом, чтобы по номеру пункта сразу получить букву.
    menu = a.here()
    a.ref(0x21, 'strbuf')
    a.db(0x36, 0x00)                     # первая строка пустая -- это заголовок
    a.db(0x23)                           # HL -> первый пункт
    a.ref(0x11, 'letters')               # DE -> таблица букв
    a.db(0x0E, 0x02)                     # C -- сколько пунктов набрали

    a.db(0x3E, 0x41); a.ref(0xCD, 'add')          # "A"
    a.db(0x3E, 0x43); a.ref(0xCD, 'add')          # "C"
    a.word(0x3A, DISK_B); a.db(0xFE, 0x59)        # диск B доступен?
    a.ref(0xC2, 'noB')
    a.db(0x3E, 0x42); a.ref(0xCD, 'add'); a.db(0x0C)
    a.label('noB')
    if flag_addr is None:
        a.ref(0x3A, 'dflag')
    else:
        a.word(0x3A, flag_addr)
    a.db(0xFE, 0x59)                              # диск D доступен?
    a.ref(0xC2, 'noD')
    a.db(0x3E, 0x44); a.ref(0xCD, 'add'); a.db(0x0C)
    a.label('noD')

    # текущий пункт: ищем букву активной панели в таблице букв
    a.word(0x21, PANEL_DRV); a.word(0xCD, SEL_PANEL); a.db(0x7E)   # A -- буква панели
    a.ref(0x21, 'letters')
    a.db(0x1E, 0x01)                     # E -- номер пункта
    a.db(0x41)                           # MOV B,C -- сколько всего пунктов
    a.label('find')
    a.db(0xBE); a.ref(0xCA, 'found')     # CMP M / JZ
    a.db(0x23, 0x1C)                     # INX H / INR E
    a.db(0x05); a.ref(0xC2, 'find')      # DCR B / JNZ
    a.db(0x1E, 0x01)                     # не нашли -- встанем на первый пункт
    a.label('found')

    a.db(0x79, 0x57)                     # MOV A,C / MOV D,A -- пунктов
    a.db(0x14)                           # INR D -- и заголовок
    a.ref(0x21, 'strbuf')
    a.word(0xCD, MENU)
    a.db(0xFE, 0x1B); a.word(0xCA, REDRAW)        # АР2 -- ничего не меняем
    a.db(0x3D)                                    # номер пункта с нуля
    a.ref(0x21, 'letters')
    a.db(0x5F, 0x16, 0x00, 0x19)                  # HL += A
    a.db(0x46)                                    # B -- выбранная буква
    a.word(0xC3, REREAD)

    # add: положить строку «"X"» в буфер по HL и букву из A в таблицу по DE
    a.label('add')
    a.db(0xF5)                                    # PUSH PSW
    a.db(0x36, 0x22, 0x23)                        # '"'
    a.db(0x77, 0x23)                              # буква
    a.db(0x36, 0x22, 0x23)                        # '"'
    a.db(0x36, 0x00, 0x23)                        # конец строки
    a.db(0xF1)                                    # POP PSW
    a.db(0x12, 0x13)                              # STAX D / INX D
    a.db(0xC9)

    return a.bytes(), trampolines, menu


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    p.add_argument('--flag', help='адрес байта «диск D доступен» (Y/N); по умолчанию свой')
    p.add_argument('--only', help='включить только эту проверку (адрес), для разбора по одной')
    args = p.parse_args()

    if args.only:
        global CHECKS
        CHECKS = [c for c in CHECKS_OFF if c[0] == int(args.only, 16)]
    d = bytearray(open(args.infile, 'rb').read())
    if len(d) % 128:
        sys.exit('образ не выровнен по записи: %d байт' % len(d))
    at = 0xB700 + (len(d) - 0x4000)
    ports_code, ports_labels = build_ports(MENU_ENTRY + 3)   # первые три байта -- переход в меню
    code, tramp, menu = build(at, d, ports_labels, int(args.flag, 16) if args.flag else None)

    for addr, kind, size in CHECKS:
        off = addr - ORG
        d[off:off + size] = bytes([0xC3, tramp[addr] & 0xFF, tramp[addr] >> 8]) + b'\x00' * (size - 3)
    # Меню целиком уезжает в хвост, общий хвост на 28AE остаётся на месте, а в
    # освободившиеся байты ложится переключатель порта.
    if len(ports_code) > MENU_END - MENU_ENTRY - 3:
        sys.exit('переключатель порта не влезает: %d байт при %d свободных'
                 % (len(ports_code), MENU_END - MENU_ENTRY - 3))
    # Подмена вызовов записи пока выключена -- см. шапку.
    d[MENU_ENTRY - ORG:MENU_ENTRY - ORG + 3] = bytes([0xC3, menu & 0xFF, menu >> 8])
    d[MENU_ENTRY - ORG + 3:MENU_ENTRY - ORG + 3 + len(ports_code)] = ports_code
    d[MENU_ENTRY - ORG + 3 + len(ports_code):MENU_END - ORG] = \
        b'\x00' * (MENU_END - MENU_ENTRY - 3 - len(ports_code))

    d += code
    while len(d) % 128:
        d += b'\0'
    open(args.outfile, 'wb').write(bytes(d))
    print('диск D: код по %04X, меню %04X, трамплинов %d' % (at, menu, len(tramp)))


if __name__ == '__main__':
    main()
