# Буква диска панели в CO.PRM хранится упакованной: при записи (1422 и 1431) CO
# берёт от неё два младших бита и складывает с флагами панели, при чтении (14EE
# и 1501) делает обратное -- ANI 03h / ADI 40h. Слотов ровно четыре: 1 -- A:,
# 2 -- B:, 3 -- C:, а ноль не занят никем и разворачивается в 40h, «@».
#
# Диску D: в этой кодировке место есть: 44h и 03h дают тот самый ноль, то есть
# запись и так укладывает его правильно. Чинить надо только чтение -- иначе
# панель, сохранённая на D:, при следующем запуске открывается на «@», и CO
# сыплет мусором.
#
# Заодно сверяем букву с составом оборудования. CO.PRM переносят с Вектора на
# Вектор, и записанный в нём диск на этой может отсутствовать вовсе -- панель
# тогда открывается с ошибкой диска. Недоступный заменяем первым доступным, а
# это всегда C:: квазидиск есть в любом Векторе, с него система и грузится.
PRM_DRV = [0x14EE, 0x1501]
PRM_DRV_WAS = bytes([0xE6, 0x03, 0xC6, 0x40])   # ANI 03h / ADI 40h

WRITE = 0x03DE         # запись сектора на квазидиск
WRITE_CALLERS = [0x2A17, 0x2E4E, 0x3AB9, 0x3F58]
WRITE_PORTS = [0x03FA, 0x040C]     # операнды OUT внутри записи


class Asm:
    def __init__(self, org):
        self.org, self.code, self.labels, self.fixups = org, bytearray(), {}, []

    def label(self, name):
        self.labels[name] = self.org + len(self.code)

    def here(self):
        return self.org + len(self.code)

    def db(self, *b):
        self.code += bytes(b)

    def word(self, op, value):
        self.code += bytes([op, value & 0xFF, value >> 8])

    def ref(self, op, name):
        self.code += bytes([op])
        self.fixups.append((len(self.code), name))
        self.code += b'\0\0'

    def bytes(self):
        out = bytearray(self.code)
        for at, name in self.fixups:
            if name not in self.labels:
                sys.exit('нет метки %s' % name)
            out[at] = self.labels[name] & 0xFF
            out[at + 1] = self.labels[name] >> 8
        return bytes(out)


def build_ports(at):
    """Порт квазидиска перед записью -- и сразу переход в саму запись.

    Внутрь процедуры записи не зайти ни вызовом, ни ничем: она прячет SP в 00F0,
    ставит стек на данные командой SPHL и гонит их чередой PUSH. Поэтому порт
    выставляем до входа, у вызывающих: подменяем их CALL на свой, правим два
    операнда OUT по букве текущего диска и прыгаем в запись -- её RET вернётся
    к вызывающему сам.
    """
    a = Asm(at)
    a.label('kdwrite')
    a.db(0xF5, 0xE5)                               # PUSH PSW / PUSH H
    a.db(0x3E, 0x10)                               # MVI A,10h -- порт первого квазидиска
    a.word(0x3A_00 >> 8 | 0x3A, DRIVE) if False else None
    a.word(0x21, DRIVE); a.db(0x7E)                # LXI H,drive / MOV A,M
    a.db(0xFE, 0x44)                               # CPI 'D'
    a.db(0x3E, 0x10)                               # MVI A,10h (флаги не трогает)
    a.ref(0xC2, 'wput')
    a.db(0x3E, 0x11)                               # MVI A,11h
    a.label('wput')
    for port in WRITE_PORTS:
        a.word(0x21, port); a.db(0x77)             # LXI H,операнд / MOV M,A
    a.db(0xE1, 0xF1)                               # POP H / POP PSW
    a.word(0xC3, WRITE)
    return a.bytes(), a.labels


def build(at, image, ports_labels, flag_addr=None):
    """Собрать хвост: трамплины проверок и меню выбора диска."""
    a = Asm(at)
    a.labels.update(ports_labels)
    trampolines = {}

    # Данные держим в начале хвоста: конец резидента вплотную подходит к стеку
    # CO на BC00, и всё, что окажется под ним, стек рано или поздно затрёт.
    a.ref(0xC3, 'start')
    # Признак «второй квазидиск есть» выставляет пусковая проба (hdprobe.py):
    # спрашивать систему прямо из меню нельзя -- вызов БСВВ «выбрать диск»
    # меняет выбранный диск за спиной БДОС, и следующее чтение каталога уходит
    # не на тот диск. При старте это безобидно, при работе -- нет.
    a.label('dflag'); a.db(0x4E)         # 'N' до пробы
    # A: и B: -- дисководы либо дискеты НЖМД. Если в Векторе нет ни того, ни
    # другого (сборка без драйверов флоповодов и НЖМД не отвечает), показывать их
    # незачем: панель на них открывается с ошибкой диска. Признак ставит та же
    # пусковая проба; до неё считаем, что они есть -- так ведут себя старые сборки,
    # у которых таблицы нет и спросить не у кого.
    a.label('aflag'); a.db(0x59)
    a.label('letters'); a.code += bytes(6)
    a.label('strbuf'); a.code += bytes(24)
    a.label('start')

    # ---------------- «квазидисковая» разметка для D: ----------------
    # Две проверки буквы решают не «куда писать», а «как устроен диск»: сколько
    # записей в каталоге (40h против 80h) и какой ширины номера блоков в записи
    # (байт против слова). Квазидиск в T-72 маленький, номера блоков в него
    # влезают в байт; дискета на 390 блоков требует слова. Второй квазидиск --
    # такой же, как первый, поэтому обе проверки должны отвечать на D: так же,
    # как на C:.
    #
    # Проверка возвращает Z для обеих букв: 'C'-43h = 0, 'D'-43h = 1, и младший
    # бит отбрасывается; 'A' и 'B' дают FEh и FFh -- после отбрасывания FEh.
    a.label('cdm')                       # буква лежит по HL
    a.db(0x7E, 0xD6, 0x43, 0xE6, 0xFE, 0xC9)
    a.label('cdl')                       # буква лежит в A849h
    a.word(0x3A, DIRDRV); a.db(0xD6, 0x43, 0xE6, 0xFE, 0xC9)

    # Третья проверка той же породы, по 027A. Подпрограмма по 0273/027A -- это
    # работа с каталогом дискеты: она держит его копию в памяти по 4000 (диск B:)
    # или 5000 и сбрасывает обратно на диск залпом из 32 секторов по 128 байт --
    # 4 КБ, ровно каталог дискеты на 128 записей. Для квазидиска она не нужна и
    # сразу выходит по 'C'. Диску D: буква не совпадала, CO шёл дискетной веткой
    # и писал эти 4 КБ нулей на D: -- на свежем диске они ложились на дорожки
    # 8..11, то есть в середину только что скопированного файла.
    #
    # Править надо сам вход 027A: на него приходят и со стороны (0B56, 2251) с
    # уже загруженной буквой. Три байта "CPI 'C' / RZ" меняем на вызов: для C: и
    # D: подпрограмма снимает адрес возврата и выходит из вызывающей, для прочих
    # букв возвращается как ни в чём не бывало, сохранив букву в A.
    a.label('cdrz')
    a.db(0xF5, 0xD6, 0x43, 0xE6, 0xFE)   # PUSH PSW / SUI 'C' / ANI 0FEh
    a.ref(0xC2, 'cdrz1')                 # JNZ -- не квазидиск
    a.db(0xF1, 0xE1, 0xC9)               # POP PSW / POP H / RET -- выход из вызывающей
    a.label('cdrz1')
    a.db(0xF1, 0xC9)                     # POP PSW / RET

    # ---------------- трамплины «C: или D:» ----------------
    for addr, kind, size in CHECKS:
        off = addr - ORG
        assert image[off:off + 2] == b'\xfe\x43', hex(addr)
        back = addr + size
        trampolines[addr] = a.here()
        # Для D: только переключаем порт и идём дальше обычным путём: увести его
        # в ветку C: нельзя -- проверено, панели начинают сыпать ошибками диска.
        if kind == 'ret':
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.db(0xC8)   # 'C' -- порт 10h и назад
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')               # 'D' -- порт 11h
            a.word(0xC3, back)
        elif kind == 'jzcd':
            # Оба квазидиска -- в одну ветку. Порт тут выставлять не нужно: его
            # по букве текущего диска правят BANK_ON/BANK_OFF и подмена записи.
            target = image[off + 3] | image[off + 4] << 8
            a.db(0xFE, 0x43); a.word(0xCA, target)
            a.db(0xFE, 0x44); a.word(0xCA, target)
            a.word(0xC3, back)
        elif kind == 'jz':
            target = image[off + 3] | image[off + 4] << 8
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.word(0xCA, target)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
        elif kind == 'jz+a':
            val = image[off + 3]
            target = image[off + 5] | image[off + 6] << 8
            name = 'q%04x' % addr
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.ref(0xCA, name)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
            a.label(name)
            a.db(0x3E, val); a.word(0xC3, target)
        elif kind == 'jz+ah':
            val = image[off + 3]
            hl = image[off + 5] | image[off + 6] << 8
            target = image[off + 8] | image[off + 9] << 8
            name = 'q%04x' % addr
            a.db(0xFE, 0x43); a.ref(0xCC, 'port10'); a.ref(0xCA, name)
            a.db(0xFE, 0x44); a.ref(0xCC, 'port11')
            a.word(0xC3, back)
            a.label(name)
            a.db(0x3E, val); a.word(0x21, hl); a.word(0xC3, target)

    # ---------------- буква панели из CO.PRM ----------------
    a.label('prmdrv')
    a.db(0xE6, 0x03)                     # ANI 03h -- номер слота
    a.db(0x5F, 0x16, 0x00)               # MOV E,A / MVI D,0
    a.ref(0x21, 'pdtab'); a.db(0x19)     # LXI H,таблица / DAD D
    a.db(0x7E, 0xC9)                     # MOV A,M / RET
    # Таблица «слот -> буква»: слот 3 это C:, слоты 1 и 2 -- A: и B:, а слот 0
    # свободен и достался D:. Заполняет её пусковая проба по составу
    # оборудования: недоступный диск заменяется первым доступным, то есть C:.
    # Здесь -- значения на случай старой сборки, у которой таблицы нет и
    # спросить не у кого: A:, B: и C: как было, D: нет.
    a.label('pdtab'); a.db(0x43, 0x41, 0x42, 0x43)

    # ---------------- меню выбора диска ----------------
    # Собираем список пунктов под текущие настройки: A: и C: есть всегда, B: и
    # D: -- по своим признакам. Строки складываем в буфер, буквы -- в таблицу
    # рядом, чтобы по номеру пункта сразу получить букву.
    menu = a.here()
    a.ref(0x21, 'strbuf')
    a.db(0x36, 0x00)                     # первая строка пустая -- это заголовок
    a.db(0x23)                           # HL -> первый пункт
    a.ref(0x11, 'letters')               # DE -> таблица букв
    a.db(0x0E, 0x01)                     # C -- сколько пунктов набрали

    # Пункты идут по алфавиту: A, B, C, D. Безусловен только C: -- квазидиск
    # есть всегда, с него система и грузится. Остальные три по признакам.
    a.ref(0x3A, 'aflag'); a.db(0xFE, 0x59)        # дисководы или НЖМД есть?
    a.ref(0xC2, 'noA')
    a.db(0x3E, 0x41); a.ref(0xCD, 'add'); a.db(0x0C)
    a.label('noA')
    a.ref(0x3A, 'aflag'); a.db(0xFE, 0x59)
    a.ref(0xC2, 'noB')
    a.word(0x3A, DISK_B); a.db(0xFE, 0x59)        # ... и своя настройка CO
    a.ref(0xC2, 'noB')
    a.db(0x3E, 0x42); a.ref(0xCD, 'add'); a.db(0x0C)
    a.label('noB')
    a.db(0x3E, 0x43); a.ref(0xCD, 'add')          # "C"
    if flag_addr is None:
        a.ref(0x3A, 'dflag')
    else:
        a.word(0x3A, flag_addr)
    a.db(0xFE, 0x59)                              # диск D доступен?
    a.ref(0xC2, 'noD')
    a.db(0x3E, 0x44); a.ref(0xCD, 'add'); a.db(0x0C)
    a.label('noD')

    # текущий пункт: ищем букву активной панели в таблице букв
    a.word(0x21, PANEL_DRV); a.word(0xCD, SEL_PANEL); a.db(0x7E)   # A -- буква панели
    a.ref(0x21, 'letters')
    a.db(0x1E, 0x01)                     # E -- номер пункта
    a.db(0x41)                           # MOV B,C -- сколько всего пунктов
    a.label('find')
    a.db(0xBE); a.ref(0xCA, 'found')     # CMP M / JZ
    a.db(0x23, 0x1C)                     # INX H / INR E
    a.db(0x05); a.ref(0xC2, 'find')      # DCR B / JNZ
    a.db(0x1E, 0x01)                     # не нашли -- встанем на первый пункт
    a.label('found')

    a.db(0x79); a.ref(0x32, 'nitems')    # MOV A,C / запомнить, сколько пунктов
    a.db(0x57)                           # MOV D,A
    a.db(0x14)                           # INR D -- и заголовок
    a.ref(0x21, 'strbuf')
    a.word(0xCD, MENU)
    a.db(0xFE, 0x1B); a.word(0xCA, REDRAW)        # АР2 -- ничего не меняем
    # Номер пункта должен быть от 1 до числа пунктов. Ноль или больше нужного
    # меню отдаёт, если выбор отменили краем: без проверки DCR A давал бы FFh,
    # а выборка по таблице букв читала бы байт ПЕРЕД ней. Такая буква уходила в
    # панель и сохранялась в CO.PRM -- после перезапуска панель открывалась на
    # несуществующем диске.
    a.db(0xB7); a.word(0xCA, REDRAW)              # ORA A / JZ -- ноль
    a.db(0x3D)                                    # номер пункта с нуля
    a.ref(0x21, 'nitems'); a.db(0xBE)             # CMP M
    a.word(0xD2, REDRAW)                          # JNC -- за краем
    a.ref(0x21, 'letters')
    a.db(0x5F, 0x16, 0x00, 0x19)                  # HL += A
    a.db(0x46)                                    # B -- выбранная буква
    a.word(0xC3, REREAD)
    a.label('nitems'); a.db(0x00)

    # add: положить строку «"X"» в буфер по HL и букву из A в таблицу по DE
    a.label('add')
    a.db(0xF5)                                    # PUSH PSW
    a.db(0x36, 0x22, 0x23)                        # '"'
    a.db(0x77, 0x23)                              # буква
    a.db(0x36, 0x22, 0x23)                        # '"'
    a.db(0x36, 0x00, 0x23)                        # конец строки
    a.db(0xF1)                                    # POP PSW
    a.db(0x12, 0x13)                              # STAX D / INX D
    a.db(0xC9)

    return a.bytes(), trampolines, menu, a.labels


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    p.add_argument('--flag', help='адрес байта «диск D доступен» (Y/N); по умолчанию свой')
    p.add_argument('--only', help='включить только эту проверку (адрес), для разбора по одной')
    args = p.parse_args()

    if args.only:
        global CHECKS
        CHECKS = [c for c in CHECKS_OFF if c[0] == int(args.only, 16)]
    d = bytearray(open(args.infile, 'rb').read())
    if len(d) % 128:
        sys.exit('образ не выровнен по записи: %d байт' % len(d))

    # Фильтр дисковых вызовов. CO перехватывает вектор БСВВ и по 0185 смотрит
    # на номер диска из описателя: двойка -- первый квазидиск -- уходит к БСВВ
    # сразу, остальное идёт по собственному пути CO, рассчитанному на
    # дисководы (свой разбор дорожек и секторов с 01C5). Второй квазидиск --
    # диск 3 -- проваливался туда же, и обмен с ним шёл мимо БСВВ.
    #
    #     0185  MOV A,M
    #     0186  CPI 02h
    #     0188  JZ <обработчик>     ->   JNC <обработчик>
    #
    # Один байт: CPI оставляет перенос, если номер меньше двух, поэтому JNC
    # пропускает к БСВВ оба квазидиска, а дисководы 0 и 1 идут как и раньше.
    if d[0x0188 - ORG] != 0xCA:
        sys.exit('по 0188 ожидался JZ, а лежит %02X' % d[0x0188 - ORG])
    d[0x0188 - ORG] = 0xD2

    at = RUNTIME + (len(d) - 0x4000)
    ports_code, ports_labels = build_ports(MENU_ENTRY + 3)   # первые три байта -- переход в меню
    code, tramp, menu, labels = build(at, d, ports_labels,
                                      int(args.flag, 16) if args.flag else None)

    only = os.environ.get('DSEL_ONLY')
    for addr, name, was, tail in GEOM:
        if only and '%04X' % addr != only:
            continue
        off = addr - ORG
        if bytes(d[off:off + len(was)]) != was:
            sys.exit('не узнаю разметочную проверку по %04X' % addr)
        new = bytes([0xCD, labels[name] & 0xFF, labels[name] >> 8]) + tail
        if len(new) > len(was):
            sys.exit('проверка по %04X не помещается: %d при %d'
                     % (addr, len(new), len(was)))
        d[off:off + len(was)] = new + b'\x00' * (len(was) - len(new))

    for addr, kind, size in CHECKS:
        off = addr - ORG
        d[off:off + size] = bytes([0xC3, tramp[addr] & 0xFF, tramp[addr] >> 8]) + b'\x00' * (size - 3)
    for addr in PRM_DRV:
        off = addr - ORG
        if bytes(d[off:off + 4]) != PRM_DRV_WAS:
            sys.exit('по %04X не ANI 03h / ADI 40h, а %s' % (addr, d[off:off + 4].hex()))
        d[off:off + 4] = bytes([0xCD, labels['prmdrv'] & 0xFF, labels['prmdrv'] >> 8, 0x00])
    # Меню целиком уезжает в хвост, общий хвост на 28AE остаётся на месте, а в
    # освободившиеся байты ложится переключатель порта.
    if len(ports_code) > MENU_END - MENU_ENTRY - 3:
        sys.exit('переключатель порта не влезает: %d байт при %d свободных'
                 % (len(ports_code), MENU_END - MENU_ENTRY - 3))
    # Подмена вызовов записи пока выключена -- см. шапку.
    d[MENU_ENTRY - ORG:MENU_ENTRY - ORG + 3] = bytes([0xC3, menu & 0xFF, menu >> 8])
    d[MENU_ENTRY - ORG + 3:MENU_ENTRY - ORG + 3 + len(ports_code)] = ports_code
    d[MENU_ENTRY - ORG + 3 + len(ports_code):MENU_END - ORG] = \
        b'\x00' * (MENU_END - MENU_ENTRY - 3 - len(ports_code))

    d += code
    while len(d) % 128:
        d += b'\0'
    open(args.outfile, 'wb').write(bytes(d))
    print('диск D: код по %04X, меню %04X, трамплинов %d' % (at, menu, len(tramp)))
    layout.note('стек', at, len(code), 'диск D:')
    print('dflag=%04X' % labels['dflag'])
    print('aflag=%04X' % labels['aflag'])
    print('pdtab=%04X' % labels['pdtab'])


if __name__ == '__main__':
    main()
