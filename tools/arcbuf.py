#!/usr/bin/env python3
"""Каталог архива .PK2 -- читать не в окно ОЗУ, а в буфер копирования.

    ./arcbuf.py CO.COM out.com

Зачем. Просмотр («3») на файле с расширением PK2 показывает не текст, а список
модулей архива. Каталог для этого CO читает с начала файла в окно, по адресу
A000, и берёт ровно десять записей CP/M -- два килобайта (18AC). А с A448 в
окне лежат накладки сборки: обмен через буфер вне окна, поиск по дискам и
кодировки просмотрщика. Архив длиннее килобайта затирает их прямо во время
чтения -- и CO виснет, не дорисовав список.

До переезда накладок в окно (он чинил зависание на диске B:) этого не было:
накладки лежали по адресу загрузки, и читать поверх них было некому.

Чинится переносом самого буфера: две тысячи байт каталога уезжают на 6100, в
буфер копирования, -- он в это время свободен, а просмотр архива копированием
не занимается. Правятся три операнда:

    18BB  LXI D,A000  -- куда читать каталог
    2A87  LXI H,9FF0  -- начало записей при подсчёте модулей
    2DF3  LXI H,9FF0  -- то же при выводе строки

Метки отмеченных модулей (9F80, 128 байт) остаются на месте: они и так ниже
A000 и в окно не попадают.
"""

import argparse
import sys

ORG = 0x100
OLD_BUF, NEW_BUF = 0xA000, 0x6100       # куда читается каталог архива
OLD_REC, NEW_REC = 0x9FF0, 0x60F0       # он же минус запись: с него идёт отсчёт

SITES = [
    (0x18BB, 0x11, OLD_BUF, NEW_BUF, 'чтение каталога архива'),
    (0x2A87, 0x21, OLD_REC, NEW_REC, 'подсчёт модулей'),
    (0x2DF3, 0x21, OLD_REC, NEW_REC, 'вывод строки списка'),
]


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    a = p.parse_args()

    d = bytearray(open(a.infile, 'rb').read())
    for at, op, old, new, what in SITES:
        i = at - ORG
        if d[i] != op or d[i + 1] != (old & 0xFF) or d[i + 2] != old >> 8:
            sys.exit('по %04X не %02X %04X (%s), а %s -- это не тот CO'
                     % (at, op, old, what, bytes(d[i:i + 3]).hex()))
        d[i + 1] = new & 0xFF
        d[i + 2] = new >> 8
    open(a.outfile, 'wb').write(bytes(d))
    print('каталог архива читается в %04X вместо %04X: правок %d'
          % (NEW_BUF, OLD_BUF, len(SITES)))


if __name__ == '__main__':
    main()
