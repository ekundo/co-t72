#!/usr/bin/env python3
"""Буферы просмотра архива .PK2 -- вон из окна ОЗУ и из видеопамяти.

    ./arcbuf.py CO.COM out.com

Зачем. Просмотр («3») на файле с расширением PK2 показывает не текст, а список
модулей архива. Каталог для этого CO читает с начала файла в окно, по адресу
A000, и берёт ровно десять записей CP/M -- два килобайта (18AC). А с A448 в
окне лежат накладки сборки: обмен через буфер вне окна, поиск по дискам и
кодировки просмотрщика. Архив длиннее килобайта затирает их прямо во время
чтения -- и CO виснет, не дорисовав список.

До переезда накладок в окно (он чинил зависание на диске B:) этого не было:
накладки лежали по адресу загрузки, и читать поверх них было некому.

Чинится переносом самого буфера: две тысячи байт каталога уезжают на 6100, в
буфер копирования, -- он в это время свободен, а просмотр архива копированием
не занимается. Правятся три операнда:

    18BB  LXI D,A000  -- куда читать каталог
    2A87  LXI H,9FF0  -- начало записей при подсчёте модулей
    2DF3  LXI H,9FF0  -- то же при выводе строки

Заодно переезжают метки отмеченных модулей. CO держит их по 9F80, сто двадцать
восемь байт, -- и это первый план видеопамяти (8000-9FFF): адрес 9F80 -- это
столбец 159, строки 128-255. Пока список открыт, метки видны на экране светлой
полосой у правого края. Уводим их на 6080, под сам каталог.

    2B7A  LXI H,9F80  -- заполнить метки «N»
    2BCD  LXI H,9F80  -- есть ли отмеченные
    2DDF  LXI H,9F80  -- метка строки при выводе
    2C5F  LXI H,9F81  -- метки уходят в задание архиватору
    2D77  MVI H,9Fh   -- страница меток при отметке по СТР
"""

import argparse
import sys

ORG = 0x100
OLD_BUF, NEW_BUF = 0xA000, 0x6100       # куда читается каталог архива
OLD_REC, NEW_REC = 0x9FF0, 0x60F0       # он же минус запись: с него идёт отсчёт
OLD_MRK, NEW_MRK = 0x9F80, 0x6080       # метки отмеченных модулей
# Младший байт у меток обязан остаться 80h: CO отсчитывает метку строки
# сложением с младшим байтом (2DDF), обход меток идёт INR L до переполнения
# (2BCD), и отметка текущей строки прибавляет 80h к номеру. С любым другим
# смещением всё это разъезжается -- проверено распаковкой, которая перестаёт
# видеть отмеченное.

SITES = [
    (0x18BB, 0x11, OLD_BUF, NEW_BUF, 'чтение каталога архива'),
    (0x2A87, 0x21, OLD_REC, NEW_REC, 'подсчёт модулей'),
    (0x2DF3, 0x21, OLD_REC, NEW_REC, 'вывод строки списка'),
    (0x2B7A, 0x21, OLD_MRK, NEW_MRK, 'сброс меток'),
    (0x2BCD, 0x21, OLD_MRK, NEW_MRK, 'есть ли отмеченные'),
    (0x2DDF, 0x21, OLD_MRK, NEW_MRK, 'метка в строке списка'),
    (0x2C5F, 0x21, OLD_MRK + 1, NEW_MRK + 1, 'метки в задание архиватору'),
]

# Здесь страница меток задана отдельным байтом (MVI H), а не адресом целиком.
PAGES = [
    (0x2D76, 'СТР -- переставить метку'),
]


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    a = p.parse_args()

    d = bytearray(open(a.infile, 'rb').read())
    for at, op, old, new, what in SITES:
        i = at - ORG
        if d[i] != op or d[i + 1] != (old & 0xFF) or d[i + 2] != old >> 8:
            sys.exit('по %04X не %02X %04X (%s), а %s -- это не тот CO'
                     % (at, op, old, what, bytes(d[i:i + 3]).hex()))
        d[i + 1] = new & 0xFF
        d[i + 2] = new >> 8
    for at, what in PAGES:
        i = at - ORG
        if d[i] != 0x26 or d[i + 1] != OLD_MRK >> 8:
            sys.exit('по %04X не MVI H,%02X (%s), а %s -- это не тот CO'
                     % (at, OLD_MRK >> 8, what, bytes(d[i:i + 2]).hex()))
        d[i + 1] = NEW_MRK >> 8
    open(a.outfile, 'wb').write(bytes(d))
    print('буферы архива: каталог в %04X вместо %04X, метки в %04X вместо %04X '
          '(правок %d)' % (NEW_BUF, OLD_BUF, NEW_MRK, OLD_MRK,
                           len(SITES) + len(PAGES)))


if __name__ == '__main__':
    main()
