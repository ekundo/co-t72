#!/usr/bin/env python3
"""Дисковый обработчик БСВВ -- из вектора E213, а не зашитый при сборке.

    ./diskvec.py CO.COM out.com [--init 0B8D5]

Зачем. CO перехватывает вектор дисковых операций (SHLD E213), ставит свой
фильтр по 0185 и пропускает вызовы дальше по адресу самого обработчика. Адрес
этот в оригинале зашит (у T-34 -- E2BD или E2C4), и до сих пор сборка правила
его на живом Векторе: скрипт снимал операнд из E213 и переписывал четыре ссылки
в теле CO. Пока БСВВ не менялась, это работало, но стоило ImproverX добавить в
T-72 пару команд, как адреса сдвинулись -- E2FF на E301 -- и прежняя сборка CO
перестала запускаться вовсе.

Теперь адрес берётся при старте из самого вектора. Пусковая подпрограмма
читает E213 и раскладывает прочитанное по четырём операндам:

    0189   JZ    -- фильтр по 0185 пропускает вызов дальше
    0206   JMP   -- то же, другой путь
    02F6   CALL
    205E   LXI H -- восстановление вектора: CO кладёт исходный адрес обратно

Накладке с номером дискеты (hdinfo.py) отдельный трамплин не нужен: она берёт
живой адрес прямо из операнда по 0189 -- туда его и кладёт эта подпрограмма.
Держать трамплин в хвосте было бы хуже: хвост упирается в стек, и лишние байты
на его верхушке -- лишний риск.

Порядок важен: читать вектор надо ДО того, как CO подменит его своим фильтром.
CO делает это по 4078, в начале своей инициализации, а пусковая цепочка
отрабатывает раньше -- стаб по 40DB зовёт её и только потом уходит на 4071.

Правка при сборке (tools/patchaddr.py) при этом остаётся: она безвредна, а
образ после неё остаётся осмысленным и без нашей подпрограммы.
"""

import argparse
import sys

ORG = 0x100
FILE_AT = 0x4100        # с этого адреса в файле лежит переносимый хвост
RUNTIME = 0xB740        # ... а работает он отсюда, см. relocstub.py
CEILING = 0xBC00        # буфер дисковода ОС -- выше хвосту нельзя
VECTOR = 0xE213         # операнд JMP по E212: дисковый обработчик БСВВ

# Операнды со ссылками на обработчик и ожидаемые перед ними команды.
SITES = [(0x0189, (0xCA, 0xD2)),  # JZ, а после dsel.py -- JNC
         (0x0206, (0xC3,)),       # JMP
         (0x02F6, (0xCD,)),       # CALL
         (0x205E, (0x21,))]       # LXI H


def main():
    p = argparse.ArgumentParser()
    p.add_argument('infile')
    p.add_argument('outfile')
    p.add_argument('--init', help='адрес подпрограммы, которую позвать следом')
    a = p.parse_args()

    d = bytearray(open(a.infile, 'rb').read())
    tail = len(d) - (FILE_AT - ORG)
    if tail < 0:
        sys.exit('хвоста нет -- запускать после fix16k.py')
    org = RUNTIME + tail

    for at, opcodes in SITES:
        if d[at - 1 - ORG] not in opcodes:
            sys.exit('по %04X ожидалась команда %s, а лежит %02X'
                     % (at - 1, '/'.join('%02X' % o for o in opcodes),
                        d[at - 1 - ORG]))

    nxt = int(a.init, 16) if a.init else 0
    body = bytearray([0x2A, VECTOR & 0xFF, VECTOR >> 8])        # LHLD E213
    for at, _ in SITES:
        body += bytes([0x22, at & 0xFF, at >> 8])               # SHLD операнд
    body += (bytes([0xC3, nxt & 0xFF, nxt >> 8]) if nxt else bytes([0xC9]))
    if org + len(body) > CEILING:
        sys.exit('хвост не помещается под стек: %04X..%04X при потолке %04X'
                 % (org, org + len(body) - 1, CEILING))

    d += body
    open(a.outfile, 'wb').write(bytes(d))
    print('дисковый обработчик из E213: %d байт по %04X' % (len(body), org))
    print('init=%04X' % org)


if __name__ == '__main__':
    main()
