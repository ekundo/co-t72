#!/usr/bin/env python3
"""Нижняя строка подсказки: подписи и просветы между ними.

Внизу экрана CO держит строку с назначением цифровых клавиш -- по строке на
каждый набор: обычный («1-Помощь 2-Меню ...») и второй, по «СС»
(«1-40/60 2-Атриб. ...»). В образе это сплошная строка до нуля, и её длина --
это и есть ширина полосы на экране.

Ширина строки консоли T-72 -- 80 знаков (`CPI 050h` в разборе «ЭСК Y»,
Source/_F600h.asm). Восьмидесятый знак печатать можно: шаг курсора вправо у
правого края просто не выполняется (`P_FB88`: `CPI 04Fh / RZ`), так что
строка не заворачивается и экран не прокручивается.

Здесь одно место, которое умеет разобрать такую строку на подписи и сложить
обратно на заданную ширину. Подпись начинается с цифры и дефиса, всё между
подписями -- просвет; просветы раскладываются поровну. Переименование
(«4-WordStar» -> «4-VDE», «7-Печать» -> «7-Hdd») идёт через ту же машинку:
длина строки после него не зависит от того, насколько подпись изменилась, --
меняются только просветы. Раньше каждый инструмент считал эту длину сам, и
подписи приходилось подбирать так, чтобы одна ровно возмещала другую.
"""

import re

WIDTH = 80                      # знаков в строке консоли T-72

LABEL = re.compile(rb'[0-9]-')  # с этого начинается подпись


def split(line):
    """Разобрать строку на подписи, без просветов."""
    starts = [m.start() for m in LABEL.finditer(line)]
    if not starts or starts[0] != 0:
        raise ValueError('строка подсказки не начинается с подписи «N-»')
    ends = starts[1:] + [len(line)]
    return [line[a:b].rstrip() for a, b in zip(starts, ends)]


def join(labels, width=WIDTH):
    """Сложить подписи обратно, разложив просветы поровну по всей ширине."""
    gaps = len(labels) - 1
    spare = width - sum(len(lab) for lab in labels)
    if gaps < 1:
        raise ValueError('в строке подсказки одна подпись')
    if spare < gaps:
        raise ValueError('подписи не умещаются в %d знаков: нужно %d'
                         % (width, sum(len(lab) for lab in labels) + gaps))
    out = bytearray(labels[0])
    for i, lab in enumerate(labels[1:], 1):
        # лишние пробелы раскидываем по строке, а не сваливаем в один конец
        out += b' ' * (spare * i // gaps - spare * (i - 1) // gaps)
        out += lab
    return bytes(out)


def relabel(line, pairs, width=WIDTH):
    """Переименовать подписи и переразложить строку на ширину экрана.

    pairs -- список («было», «стало») по-русски; сверяется подпись целиком,
    чтобы «7-Печать» не нашлось внутри чего-нибудь ещё. Возвращает новую
    строку и список подписей, которых в строке не оказалось."""
    labels = split(line)
    missing = []
    for old, new in pairs:
        o, n = old.encode('koi8-r'), new.encode('koi8-r')
        if o in labels:
            labels[labels.index(o)] = n
        else:
            missing.append(old)
    return join(labels, width), missing
