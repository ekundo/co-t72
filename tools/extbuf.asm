; ---------------------------------------------------------------------------
; CO.EXT и CO.MNU -- читать не в окно, а в буфер копирования.
;
; Списки CO читает целиком, и предела у чтения нет: 18C3 берёт до 80h записей,
; то есть шестнадцать килобайт, и кладёт их с A000. А с A448 в окне лежат
; накладки сборки -- обмен через буфер вне окна, склейка экстентов, поиск по
; дискам, кодировки просмотрщика. Значит CO.MNU или CO.EXT длиннее 448h байт
; (1096) ложится прямо на них, и первое же обращение к диску уходит в мусор.
; Мы на этом уже обожглись с каталогом архива (tools/arcbuf.py) -- там CO читал
; в то же место и всегда по два килобайта.
;
; Уводим чтение в буфер копирования, на 6100: списки разбираются построчно
; (3BA0), копированием при этом никто не занят, а до собираемого текста по
; 9100 остаётся двенадцать килобайт. Предел ставим свой -- 30h записей, шесть
; килобайт: вчетверо больше самого длинного CO.MNU, какой можно себе
; представить, и втрое меньше, чем до 9100.
;
; CO.ZGR остаётся по-старому в окне: его список разбирается, ПОКА идёт
; перенос файлов, а перенос как раз и работает через буфер копирования.
;
; Врезка одна -- по 3BD3, где все три открывателя (3BCD CO.EXT, 3BD6 CO.MNU,
; 3BDC CO.ZGR) сходятся на общий JMP 158A. Какой из файлов открывают, видно по
; HL: там адрес имени, и младший байт у всех трёх разный.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

OPENAT  EQU  01808h             ; CO: открыть файл на записи из RECNO
READON  EQU  018C5h             ; CO: читать записи подряд, счётчик в C
OLDWAY  EQU  0158Ah             ; CO: прочитать целиком в окно с A000
RECNO   EQU  0A83Eh             ; номер записи, он же указатель разбора строк
ZGRLO   EQU  030h               ; младший байт имени CO.ZGR (3E30)
BUF     EQU  06100h             ; буфер копирования -- сейчас он свободен
LIMIT   EQU  050h               ; счёт идёт до 80h: 30h записей, шесть килобайт

open:   MOV  A,L
        CPI  ZGRLO              ; CO.ZGR -- по-старому, в окно
        JZ   OLDWAY
        LXI  H,0
        SHLD RECNO
        CALL OPENAT
        LXI  D,BUF
        MVI  C,LIMIT
        CALL READON             ; читает и закрывает файл сам
        LXI  H,BUF
        SHLD RECNO              ; отсюда 3BA0 и будет брать строки
        RET
        END
