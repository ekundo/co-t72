#!/usr/bin/env python3
"""Сделать дискету загрузочной: положить систему на её системные дорожки.

    ./sysfdd.py co-t72f.fdd os-t72f.rom --base work/os-t72/os-t72.fdd

Первые восемь дорожек дискеты МикроДОС под файлы не отданы (OFF 8 в описателе
диска, см. cpmimg.py): в них лежит описатель и образ системы, который загрузчик
Вектора поднимает при загрузке с дискеты. Раскладку берём с подлинной системной
дискеты T-72: по 0000 -- описатель, с 0080 -- образ системы.

В описателе нас касаются три поля (BOOT26.asm у ImproverX):

    0000  адрес загрузки    загрузчик кладёт байт со смещения 0080 по этому
                            адресу: в L_SETB он берёт адрес и вычитает 80h
    0002  адрес запуска     куда передать управление, когда всё прочитано
    001F  контрольная сумма 66h плюс сумма байтов 00..1E; не сошлась --
                            загрузчик считает сектор незагрузочным

Оба адреса ставим в 0100h: образ системы собран с 0100h. У подлинных дискет там
нули -- старые загрузчики эти поля игнорировали и грузили с 0100h всегда, новые
читают их честно, и с нулями система уехала бы не туда.

Подменяем образ и эти три поля, остальное в описателе и всё, что лежит за
образом, переносим с подлинной дискеты как есть. Каталог и файлы (с 0A000h) не
трогаем вовсе.
"""

import argparse

SYS = 0x80              # образ системы, собранный с 0100h
ORG = 0x0100            # ... и туда же его кладёт загрузчик
CKS = 0x1F              # байт контрольной суммы описателя
CKS0 = 0x66             # с чего загрузчик начинает её считать
DATA = 8 * 5120         # с этого места каталог и файлы -- их не трогаем


def main():
    p = argparse.ArgumentParser()
    p.add_argument('image', help='дискета, которую делаем загрузочной')
    p.add_argument('system', help='образ системы (os-t72X.rom)')
    p.add_argument('--base', required=True, help='подлинная системная дискета T-72')
    a = p.parse_args()

    img = bytearray(open(a.image, 'rb').read())
    base = open(a.base, 'rb').read()
    sysimg = open(a.system, 'rb').read()

    if len(base) < DATA:
        raise SystemExit('подлинная дискета короче системных дорожек')
    if SYS + len(sysimg) > DATA:
        raise SystemExit('образ системы не влезает в системные дорожки')

    img[0:DATA] = base[0:DATA]
    img[SYS:SYS + len(sysimg)] = sysimg
    img[0:2] = bytes([ORG & 0xFF, ORG >> 8])            # адрес загрузки
    img[2:4] = bytes([ORG & 0xFF, ORG >> 8])            # адрес запуска
    img[CKS] = (CKS0 + sum(img[:CKS])) & 0xFF           # контрольная сумма
    open(a.image, 'wb').write(bytes(img))
    print('системные дорожки: система %d байт с %04X, загрузка и запуск с %04X, '
          'контрольная сумма %02X' % (len(sysimg), SYS, ORG, img[CKS]))


if __name__ == '__main__':
    main()
