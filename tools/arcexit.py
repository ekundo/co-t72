#!/usr/bin/env python3
"""Выход из списка архива: перерисовать панель, а не возвращать картинку.

    ./arcexit.py CO.COM [-o out]

Мусор на экране. Открыть архив «3-Просм», выйти «АР2» -- и половина экрана с
панелью оказывается забита случайными знаками. Данные целы: список файлов в
памяти на месте, и стоит перечитать каталог (сменить диск, скопировать файл),
как панель рисуется правильно. Испорчена только картинка -- и надолго: её же
CO кладёт обратно и при переходе на соседнюю панель.

Отчего. Картинку панелей CO держит копией в буфере копирования и оттуда
возвращает на экран (`0415`): своя четверть буфера у каждой половины экрана --
`6000-6FFF`, `7000-7FFF`, `8000-8FFF`, `9000-9FFF`. А сборка с 2.2.2 читает
каталог архива в тот же буфер, на `6100` (tools/arcbuf.py): в окне ОЗУ ему
места не осталось, там лежат накладки. Чтение затирает копию левой половины,
и выход из списка возвращает на экран уже мусор.

Вернуть каталог архива в окно нельзя: ему нужно два килобайта подряд
(`18BE`: `MVI C,70h` -- шестнадцать записей по 80h), а свободного в окне
полторы сотни байт. Держать копию картинки негде и подавно.

Поэтому выход из списка больше не возвращает картинку, а рисует панель
заново -- из списка, который никуда не девался:

    было:  CALL 2A0A / CALL 0415 / CALL 2A0A   -- сменить панель, вернуть
                                                  картинку, сменить обратно
    стало: CALL 0C7E / CALL 091E / CALL 0890   -- шапки панелей, список
                                                  панели, строка под курсором

Ровно девять байт, ничего не съезжает. Диск при этом не читается: каталог
берётся из памяти, как и было.
"""

import argparse
import sys

ORG = 0x100
AT = 0x2DC3                     # выход из списка архива по «АР2»
WAS = bytes([0xCD, 0x0A, 0x2A,  # CALL 2A0A -- сменить активную панель
             0xCD, 0x15, 0x04,  # CALL 0415 -- вернуть картинку из буфера
             0xCD, 0x0A, 0x2A])  # CALL 2A0A -- и сменить обратно
NOW = bytes([0xCD, 0x7E, 0x0C,  # CALL 0C7E -- шапки обеих панелей
             0xCD, 0x1E, 0x09,  # CALL 091E -- список панели заново
             0xCD, 0x90, 0x08])  # CALL 0890 -- строка под курсором


def main():
    p = argparse.ArgumentParser(description='выход из архива: перерисовать панель')
    p.add_argument('image', help='CO.COM (правится на месте)')
    p.add_argument('-o', '--out', help='куда записать (по умолчанию -- на место)')
    a = p.parse_args()

    d = bytearray(open(a.image, 'rb').read())
    at = AT - ORG
    if bytes(d[at:at + len(WAS)]) != WAS:
        sys.exit('по %04X не выход из списка архива, а %s -- незнакомый выпуск CO'
                 % (AT, d[at:at + len(WAS)].hex()))
    d[at:at + len(NOW)] = NOW
    open(a.out or a.image, 'wb').write(bytes(d))
    print('выход из архива по %04X: панель перерисовывается, а не '
          'возвращается картинкой' % AT)


if __name__ == '__main__':
    main()
