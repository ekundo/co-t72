; ---------------------------------------------------------------------------
; Просмотрщик: не читать назад дальше начала файла.
;
; Шаг назад по тексту (32C3) идёт задом наперёд по странице A000-A0FF, где
; лежит пара записей файла, и когда указатель уходит ниже A000, подкачивает
; предыдущую пару (334E). Проверки «а есть ли она» там нет: у начала файла
; номер записи (A83E) уходит в минус, чтение возвращает пустоту, буфер
; заполняется знаками 1Ah -- и перевода строки в нём не найти уже никогда.
; Цикл 32D3 крутится вечно, CO виснет.
;
; Само CO от этого бережётся снаружи: 318E перед откатом смотрит на номер
; верхней строки (A853) и на первой строке вместо отката перечитывает файл
; сначала (31BA), а 31C5 в том же случае просто ставит указатель на A000.
; Мимо обеих проверок идёт СТР в просмотрщике: 2EDB отматывает 13h строк
; безусловно. На файле короче страницы этого хватает, чтобы уехать за начало,
; -- и «перейти к строке» вешает CO намертво. Проверено на стенде: в снимке
; памяти A83E = F584, весь буфер в 1Ah (сценарий «просмстр»).
;
; Чиним у самого источника, а не у одного вызова: перед подкачкой предыдущей
; пары смотрим, есть ли она. Нет -- значит указатель стоит на первой записи
; файла, и ответ тот же, что у CO по 31D5: начало текста, A000.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

PREV    EQU  0334Eh             ; CO: подкачать предыдущую пару записей
RECNO   EQU  0A83Eh             ; номер первой записи пары, лежащей в буфере
POS     EQU  0A855h             ; где просмотрщик стоит в тексте
BUF     EQU  0A000h             ; буфер: записи RECNO и RECNO+1

back:   PUSH H
        LHLD RECNO
        MOV  A,H
        ORA  L
        POP  H
        JNZ  PREV               ; не первая пара -- подкачать, как было
        POP  H                  ; начало файла: выбросить возврат в 32C3
        LXI  H,BUF
        SHLD POS
        RET                     ; ... и вернуться сразу тому, кто звал 32C3
        END
