#!/bin/sh
# README.txt внутрь архива выпуска: ./relnote.sh <f|h|hx|k> <версия>
set -e
v=$1
ver=$2
case "$v" in
    f)  hw='два НГМД и два квазидиска' ;;
    h)  hw='НЖМД и два квазидиска, без НГМД' ;;
    hx) hw='всё оборудование' ;;
    k)  hw='только квазидиски' ;;
    *)  echo "неизвестная сборка: $v" >&2; exit 1 ;;
esac

cat <<EOF
CO $ver под MDOS T-72 -- сборка для os-t72$v.rom ($hw)

  v06x --rom os-t72$v.rom --fdd co-t72$v.fdd --edd co-t72$v.edd

CO.COM во всех архивах один и тот же: зашитых адресов ОС в нём не осталось, всё
нужное он спрашивает у системы при старте. Сборки различаются только образом
системы и готовыми образами дискеты и квазидиска.

На T-72 старше 15.09.2026 работает тот же файл, только по-старому: диск D: не
предлагается, СС+7 остаётся выбором дискеты НЖМД, а номер и метка дискеты в
рамке панели не показываются -- там нет таблицы, откуда их брать.

Состав оборудования CO спрашивает у системы при старте: дисков, которых на Векторе
нет, в меню "7-Диск" он не предлагает, а панель, записанную в CO.PRM на диск,
которого здесь нет, открывает на C:.

Диск D: -- второй квазидиск, если он в Векторе есть.

Рядом с архивом два готовых образа, оба с автозапуском CO. co-t72$v.fdd --
загрузочный образ дискеты: на её системных дорожках та же сборка T-72, что и в
os-t72$v.rom, а в каталоге тот же комплект CO. co-t72$v.edd -- квазидиск с
системой, CO и HDIR.

os-t72$v.rom -- сборка ImproverX от 15.09.2026: образ системы, годный и для ПЗУ,
и для системных дорожек дискеты, а не сам ПЗУ.

В комплекте HDIR -- каталоги "дискет" НЖМД, поиск файла по всему винчестеру,
метки дискет, обмен и очистка. HDIR.COM -- по-русски, HDIREN.COM -- english.
Запуск без параметров печатает подсказку. На квазидиске образа обе уже лежат.

CO -- Шишатский С.М., Харьков, 1993.
MDOS T-72 -- ImproverX, GPLv3, github.com/ImproverX/MDOS_T-72
Патчи и сборка -- github.com/ekundo/co-t72
EOF
