#!/bin/sh
# README.txt внутрь архива выпуска: ./relnote.sh <f|h|hx|k> <версия>
set -e
v=$1
ver=$2
case "$v" in
    f)  hw='два НГМД и два квазидиска' ;;
    h)  hw='НЖМД и два квазидиска, без НГМД' ;;
    hx) hw='всё оборудование' ;;
    k)  hw='только квазидиски' ;;
    *)  echo "неизвестная сборка: $v" >&2; exit 1 ;;
esac

cat <<EOF
CO $ver под MDOS T-72 -- сборка для os-t72$v.rom ($hw)

  v06x --rom os-t72$v.rom --fdd co-t72$v.fdd --edd co-t72$v.edd

VDE.COM -- экранный редактор с клавишами WordStar, он же открывается по
"СС"-"4". Прежде на этой клавише стоял WordStar (WSR.COM), но он заточен под
КОИ-7 и под T-72 толком не работает; VDE переведена с Z80 на 8080 и держит
КОИ-8 -- ту же кодировку, что и вся остальная система. Клавиши -- по "^J".

Рядом с ней авторская документация: VDE266.DOC -- руководство, VDE266.QRF --
краткая справка на один экран (на квазидиске только она, руководство большое).
Обе по-английски, обе смотрятся просмотрщиком CO.

CO.COM во всех архивах один и тот же: зашитых адресов ОС в нём не осталось, всё
нужное он спрашивает у системы при старте. Сборки различаются только МикроДОС
и готовыми образами дискеты и квазидиска.

На T-72 старше 15.09.2026 работает тот же файл, только по-старому: диск D: не
предлагается, СС+7 остаётся выбором дискеты НЖМД, а номер и метка дискеты в
рамке панели не показываются -- там нет таблицы, откуда их брать.

Состав оборудования CO спрашивает у системы при старте: дисков, которых на Векторе
нет, в меню "7-Диск" он не предлагает, а панель, записанную в CO.PRM на диск,
которого здесь нет, открывает на C:.

Диск D: -- второй квазидиск, если он в Векторе есть.

Рядом с архивом два готовых образа. co-t72$v.fdd -- загрузочный образ дискеты:
на её системных дорожках та же сборка T-72, что и в os-t72$v.rom, а в каталоге
тот же комплект CO. co-t72$v.edd -- квазидиск с системой, CO и HDIR.

С квазидиска CO поднимается сам. С дискеты -- на сборках f и hx; на h и k
драйвера дисковода в системе нет, и автозапуск с дискеты она не ищет.

os-t72$v.rom -- сама МикроДОС, сборка ImproverX от 17.09.2026. Формат .rom
понимает загрузчик Вектора: это программа, стартующая без операционной системы.

В комплекте HDIR -- каталоги "дискет" НЖМД, поиск файла по всему винчестеру,
метки дискет, обмен и очистка. HDIR.COM -- по-русски, HDIREN.COM -- english.
Запуск без параметров печатает подсказку. На готовых образах лежит русская;
английская -- здесь, в архиве, и внутри DEMO.PK2.

На образах есть и архиватор ARC2.COM с показательным архивом DEMO.PK2.
Клавиша "3-Просм" на архиве открывает его каталог, "ВК" на строке внутри --
распаковывает файл; распаковку делает ARC2, поэтому он и нужен рядом.

CO -- Шишатский С.М., Харьков, 1993.
MDOS T-72 -- ImproverX, GPLv3, github.com/ImproverX/MDOS_T-72
VDE 2.67b -- Эрик Мейер, 1988; перевод с Z80 на 8080 -- здесь.
ARC2 -- ARCHIVER V1.3 (C) V.KRUPSKY, 1990.
Патчи и сборка -- github.com/ekundo/co-t72
EOF
