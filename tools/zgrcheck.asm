; ---------------------------------------------------------------------------
; Не заводить на C: пустышки из списка CO.ZGR.
;
; При первом запуске -- когда CO стартовал не с C: -- он переносит на квазидиск
; файлы, перечисленные в CO.ZGR, беря их с того диска, откуда запустился сам.
; Если файла там нет, на C: всё равно появляется запись нулевой длины: копир
; сначала заводит приёмник, а потом уже спотыкается на источнике. В штатном
; комплекте так заводятся MEDIT.COM, FORMATM.COM, OS.COM и INITIALC.SUB.
;
; Правка: перед тем как принять строку списка, проверяем, есть ли такой файл на
; текущем диске. Нет -- строка не попадает в список, и копир о ней не узнает.
;
; Куда врезано. Разбор CO.ZGR -- цикл 3EDF..3F06: 3BA0 кладёт очередную строку
; в буфер B6A8 сырым текстом, 3EE5 увеличивает счётчик записей B69B, 3EEF..3F00
; переносит имя и расширение в запись списка (ветка с точкой уходит на 3FA4 и
; возвращается тем же путём), а по 3F01 CO смотрит на первый знак строки и либо
; берёт следующую, либо заканчивает. Вот это чтение и перехвачено: к нему имя
; уже разобрано, а список ещё можно укоротить, просто откатив счётчик -- адрес
; записи считается из него же (3EE6).
;
; Диск берём не текущий, а тот, с которого CO переносит: его букву он кладёт в
; A84Ah (3EA3) ещё до разбора списка. Разница видна, когда CO запускают с одного
; диска, а текущим остаётся другой -- скажем, `C>A:CO` при пустом квазидиске.
; Тогда проверка по текущему диску не находит ничего, все строки списка
; отбрасываются, счётчик обнуляется, и CO принимается копировать пустую запись
; каталога -- имя из байтов 0E5h и вопрос «уже есть, заменять?».
;
; Открытием, а не поиском: БДОС-17 пишет найденную запись каталога в текущий
; буфер обмена, а он в этот момент занят самим CO.ZGR -- поиск затёр бы
; непрочитанные строки. Открытие (БДОС-15) трогает только наш ФУБ.
;
; Старший бит букв в CO.ZGR несёт признаки CP/M: в штатном списке так помечен
; CO.COM (буква «O» расширения с поднятым битом -- признак системного файла).
; Поэтому имя маскируется семью битами, иначе не нашлось бы ни одно помеченное.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

LINE    EQU 0B6A8h              ; буфер строки: сырой текст, длина по B6A7
COUNT   EQU 0B69Bh              ; счётчик записей списка
SRCDRV  EQU 0A84Ah              ; буква диска, С КОТОРОГО CO переносит файлы
BDOS    EQU 00005h
OPEN    EQU 00Fh                ; БДОС: открыть файл

start:  PUSH H
        PUSH D
        PUSH B
        LDA  LINE
        CPI  '.'                ; точка -- конец списка, проверять нечего
        JZ   out
        CALL build
        LXI  D,fcb
        MVI  C,OPEN
        CALL BDOS
        INR  A                  ; 0FFh -- не найден
        JNZ  out
        LXI  H,COUNT
        DCR  M                  ; строку в список не берём
out:    POP  B
        POP  D
        POP  H
        LDA  LINE               ; ради чего перехват и стоял
        RET

; Строка "ИМЯ.РАС" -> ФУБ.
build:  LXI  H,fcb
        LDA  SRCDRV             ; искать надо на диске-источнике, не на текущем
        SUI  040h               ; буква -> номер ФУБ: A: -- 1, B: -- 2 и так далее
        CPI  005h
        JC   bl0
        XRA  A                  ; не похоже на букву -- пусть будет текущий
bl0:    MOV  M,A
        INX  H
        MVI  C,11               ; восемь знаков имени и три расширения
        MVI  A,' '
bl1:    MOV  M,A
        INX  H
        DCR  C
        JNZ  bl1
        LXI  H,LINE
        LXI  D,fcb+1
        MVI  C,8
bl2:    MOV  A,M
        ANI  07Fh
        CPI  '.'
        JZ   bl4
        CPI  ' '
        RC                      ; конец строки -- расширения нет
        STAX D
        INX  H
        INX  D
        DCR  C
        JNZ  bl2
bl3:    MOV  A,M                ; имя длиннее восьми -- доходим до точки
        ANI  07Fh
        CPI  '.'
        JZ   bl4
        CPI  ' '
        RC
        INX  H
        JMP  bl3
bl4:    INX  H
        LXI  D,fcb+9
        MVI  C,3
bl5:    MOV  A,M
        ANI  07Fh
        CPI  ' '
        RC
        STAX D
        INX  H
        INX  D
        DCR  C
        JNZ  bl5
        RET

fcb:    DS 36
        END
