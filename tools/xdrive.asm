; ---------------------------------------------------------------------------
; Поиск программы по "X:" -- и на втором квазидиске.
;
; Если вместо буквы диска в командной строке стоит "X:", CO ищет программу сам
; и подставляет диск, на котором она нашлась. Порядок зашит: сначала C:, потом
; A:, потом B:, если он разрешён (об этом прямо сказано и в CO.HLP). Второго
; квазидиска в этом списке нет -- панели диск D: знают, а поиск мимо.
;
; Врезка на место установки диска A: в этом переборе: сперва пробуем D:, если
; он есть, и только потом идём дальше прежним путём. Нашли -- снимаем адрес
; возврата и выходим из перебора так же, как выходит он сам после удачи.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

DRIVE   EQU 0B673h              ; буква текущего диска у CO
FOUND   EQU 0B68Dh              ; 0 -- файл найден
SEARCH  EQU 012A7h              ; CO: поиск файла на текущем диске

start:  LDA  DFLAG              ; второй квазидиск есть? (hdprobe ставит 'Y')
        CPI  'Y'
        JNZ  seta
        MVI  A,'D'
        STA  DRIVE
        CALL SEARCH
        LDA  FOUND
        ORA  A
        JNZ  seta               ; не нашли -- дальше по прежнему списку
        POP  H                  ; нашли: снять возврат в перебор
        RET                     ; и выйти из него к вызывающему
seta:   MVI  A,'A'              ; ради чего врезка и стояла
        STA  DRIVE
        RET
        END
