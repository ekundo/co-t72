; ---------------------------------------------------------------------------
; Выход из меню пользователя -- перерисовкой панели, а не снимком экрана.
;
; Открывая меню, CO снимает картинку панелей в буфер копирования (03DE по
; 3AB9), а на выходе возвращает её оттуда на экран (0415). Снимок занимает
; буфер целиком, 6100-9FFF: половина экрана на панель, по два куска на
; каждую. Туда же сборка читает CO.MNU -- и меню само затирало свой снимок.
; Видно это было на левой панели: её куски лежат с 6100 и 8100, правой
; достаются 7000 и 9000, поэтому справа выходило чисто, а слева на экран
; возвращался мусор.
;
; Перенести чтение некуда: свободного куска на список ни в окне (там от A000
; всего 1096 байт до накладок), ни в буфере нет. Зато снимок и не нужен. Меню
; рисуется только в поле активной панели и в её верхней рамке -- ровно то же
; делают каталог архива и список дискет НЖМД, и закрываются они перерисовкой
; (2DC3). Делаем так же: шапки обеих панелей, список активной, строка под
; курсором, парковка. Командную строку и полосу подсказок меню не трогает,
; поэтому их и перерисовывать нечего -- а вот 0415 как раз их-то и портил,
; возвращая на них половину испорченного снимка.
;
; Панель тут не та, в которой стоит курсор: меню CO рисует в соседней, чтобы
; отмеченный файл остался на виду. Номер панели в B69D -- это панель курсора,
; поэтому список перерисовываем, переключив его на время (2A0A) и вернув назад.
; Шапки (0C7E) рисуются обе разом и переключения не требуют -- больше того, его
; и нельзя: заодно с шапкой 0C7E ставит текущий диск ОС по букве своей панели,
; и с переключённым B69D в командной строке оказывался чужой диск.
;
; Врезок две -- 3A36 (клавиша «0») и 3A3B (АР2): обе вели на 0415.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

FLIP    EQU  02A0Ah             ; CO: переключить номер панели в B69D
HEADS   EQU  00C7Eh             ; CO: шапки обеих панелей
LIST    EQU  0091Eh             ; CO: список панели из B69D заново
CURLIN  EQU  00890h             ; CO: строка под курсором
PARK    EQU  00FF3h             ; CO: курсор в командную строку

out:    CALL HEADS              ; шапки рисуются обе сразу, при своём B69D
        CALL FLIP               ; меню рисовалось в другой панели -- в неё и
        CALL LIST               ; ... возвращаем список
        CALL FLIP               ; обратно, пока никто не заметил
        CALL CURLIN
        JMP  PARK
        END
