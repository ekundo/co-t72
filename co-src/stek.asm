        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah                  ; ВРЕМЕННО: добивка

