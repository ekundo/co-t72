; «СС»-«7» -- выбор дискеты НЖМД.
; --------------------------------------------------------------------------
ORIGIN  EQU $
HDDSEL  EQU $
#include "../tools/hddsel.asm"
        .db  01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah,01Ah
