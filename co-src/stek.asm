; ==========================================================================
; НАКЛАДКИ, КОТОРЫЕ РАБОТАЮТ ПОД СТЕКОМ (B75C)
; ==========================================================================
;
; Лежат они в хвосте образа, а работают с B75C: при старте их переносит туда
; стаб по 40DB. По адресу загрузки им делать нечего -- с 4000 CO держит копию
; каталога диска B: и затирает всё это при первом же чтении чужого диска.
;
; Место под стеком выведено из листинга (tools/winholes.py): снизу его
; подпирает таблица меню пользователя (по B728), сверху -- буфер дисковода
; T-72 по BC00, ради которого стек CO и опущен. Всего 1188 байт, и это самое
; тесное место во всей сборке.
;
; PHASE говорит ассемблеру «собирать здесь, а работать там»: метки внутри
; считаются от B75C, а байты ложатся туда, куда шли -- в хвост.

STKFILE EQU $                   ; где блок лежит в файле -- отсюда его копируют
        PHASE STKLO

; --------------------------------------------------------------------------
; Диск D: -- второй квазидиск: разметка, трамплины и меню выбора диска.
; Первым идёт не случайно: в нём признаки оборудования (DFLAG, AFLAG) и
; таблица PDTAB, на которые смотрят и накладки окна, и проба оборудования.
; --------------------------------------------------------------------------
ORIGIN  EQU $
DSEL    EQU $
#include "dsel.asm"
DSELEND EQU $

; --------------------------------------------------------------------------
; Две строки экрана, которым не хватило места в своей области образа:
; приглашение командной строки и подвод курсора. Подробности -- там же, где
; сами строки подсказки (co.asm, 1135).
; --------------------------------------------------------------------------
; Уходя с панелей в командную строку, возвращаем автоматический перевод строки:
; дальше там работают ССР и чужие программы, и перевод им нужен.
SCRSTR  EQU $
CMDLINE: .db 1Bh,'[7h',0Ch,0Ah,' >',0
; Подвод курсора к строке 23 -- и тут же счётчик файлов. Печатая «Копируется
; NNN-й файл X:=>Y:», CO выводит эту строку один раз, а на каждом следующем
; файле только возвращает курсор на цифры и печатает число заново (0BE7). Число
; лежит прямо в строке, следом за подводом: три знака, которые заполняет 0E1B.
GOTO7:  .db  1Bh,'Y7-'          ; подвод курсора к строке 23
; Дальше не код, а поле, которое CO заполняет на каждом файле, -- сторож
; целости кода за ним не следит, иначе первая же запись числа выглядела бы
; правкой нашего кода.
SCREND  EQU $
GOTO7N: .ds  3                  ; счётчик файлов, три знака
        .db  0

; --------------------------------------------------------------------------
; «СС»-«7» -- выбор дискеты НЖМД.
; --------------------------------------------------------------------------
ORIGIN  EQU $
HDDSEL  EQU $
#include "hddsel.asm"

STKEND  EQU $
        DEPHASE
