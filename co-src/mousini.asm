; ---------------------------------------------------------------------------
; Есть ли мышь -- и если есть, врезать её опрос в CO (co-src/mouse.asm).
;
; Контроллер после сброса выключен. Запись 0Fh в порт D4h включает его и
; выбирает регистр 15, а тот отвечает 6Dh («m»). Без контроллера на шине FFh.
; Мыши нет -- ничего не трогаем, и CO остаётся какой была.
;
; Врезки -- в ожидание клавиши 04C1:
;   04F4  CALL F81B  -> MPOLL  опрос клавиатуры и мыши;
;   0536  CALL F803  -> MWAIT  то же при нулевом сроке гашения монитора;
;   04B6, 04ED CALL 0F9A -> MBAR  полоса подсказки при «СС»: прятать указатель;
;   0508  CALL SCRSAV -> MSCR  заставка: прятать указатель.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

MINIT:  MVI  A,00Fh
        OUT  MPORT
        IN   MPORT
        CPI  06Dh
        RNZ
        LXI  H,MPOLL
        SHLD 004F5h
        LXI  H,MWAIT
        SHLD 00537h
        LXI  H,MBAR
        SHLD 004B7h
        SHLD 004EEh
        LXI  H,MSCR
        SHLD 00509h
        RET
