; Склейка экстентов: показать в панелях файлы, кратные 16 КБ.
;
; Каталог CP/M хранит файл экстентами по 16 КБ. В записи экстента байт 15 --
; это RC, число 128-байтных записей в нём; у полного экстента RC = 80h. Размер
; файла CO считает по последнему экстенту (1A9E), а все промежуточные
; пропускает по признаку RC = 80h (1A99: CPI 80h / JZ 1A78).
;
; У файла, длина которого кратна 16 КБ, ПОЛНЫЕ ВСЕ экстенты -- и файл пропадает
; из панели целиком. Поэтому CO никогда не показывал ни самого себя (16384), ни
; ASC.COM с системной дискеты; а DBG.COM (18944) был виден.
;
; Чинится так: проверка RC снята (правка по 1A99 в листинге), а вместо LHLD
; A873 по 1AD1 зовётся этот код. Он ищет в списке строку с тем же именем и
; типом: нашлась -- выбрасывает её из списка, и новая ложится в конец. В списке
; остаётся последний экстент, то есть верный размер.
;
; Искать надо по ВСЕМУ списку, а не только в предыдущей строке: экстенты одного
; файла лежат в каталоге подряд не всегда -- при копировании поверх удалённого
; файла первый экстент занимает освободившийся слот, а второй уходит в конец
; каталога. Две одинаковые строки в списке смертельны: сортировка CO при
; равенстве всех 12 байт (1BA0 -> 1BA3) отступает на 14 байт назад и продолжает
; сравнение, залезая в соседние строки.
;
; Вход: DE -- запись каталога. Выход: HL -- куда писать строку, DE сохранён.

ROW     EQU 13                  ; строка списка: имя 8 + пробел + тип 3 + размер
FIRST   EQU 0A842h              ; начало списка панели
COUNT   EQU 0A871h              ; сколько в нём строк
LAST    EQU 0A873h              ; хвост списка -- куда ляжет следующая

        XCHG
        SHLD ent
        XCHG
        LHLD LAST
        SHLD tail
        LHLD FIRST
loop:   LDA  tail               ; дошли до хвоста -- такой строки нет
        CMP  L
        JNZ  go
        LDA  tail+1
        CMP  H
        JZ   notfnd
go:     PUSH H                  ; начало строки
        LHLD ent
        XCHG                    ; DE -- запись каталога
        POP  H
        PUSH H
        INX  D                  ; в записи каталога имя идёт со второго байта
        MVI  B,8
cmp8:   LDAX D
        CMP  M
        JNZ  next
        INX  H
        INX  D
        DCR  B
        JNZ  cmp8
        INX  H                  ; в строке между именем и типом пробел
        MVI  B,3
cmp3:   LDAX D
        CMP  M
        JNZ  next
        INX  H
        INX  D
        DCR  B
        JNZ  cmp3
; Совпало: выбросить найденную строку -- сдвинуть остаток списка на ROW назад.
        POP  H
        MOV  B,H
        MOV  C,L
        LXI  H,ROW
        DAD  B
        XCHG                    ; DE -- следующая строка, HL -- найденная
        MOV  H,B
        MOV  L,C
slide:  LDA  tail
        CMP  E
        JNZ  sl1
        LDA  tail+1
        CMP  D
        JZ   shrink
sl1:    LDAX D
        MOV  M,A
        INX  H
        INX  D
        JMP  slide
shrink: LHLD COUNT              ; список стал короче на строку
        DCX  H
        SHLD COUNT
        LHLD tail
        LXI  B,-ROW
        DAD  B
        JMP  done
next:   POP  H                  ; не совпало -- следующая строка
        LXI  B,ROW
        DAD  B
        JMP  loop
notfnd:                         ; HL уже равен хвосту
done:   PUSH H
        LHLD ent
        XCHG                    ; вернуть DE, как было
        POP  H
        RET

ent:    .db 0,0                 ; запись каталога, пока идёт поиск
tail:   .db 0,0                 ; хвост списка на момент входа
