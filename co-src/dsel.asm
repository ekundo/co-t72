; ---------------------------------------------------------------------------
; Диск D: -- второй квазидиск.
;
; CO знает три диска: A:, B: и квазидиск C:. Каталоги он читает через БДОС, так
; что четвёртый диск ему по силам.
;
; Порт переключать не надо вовсе. Второй квазидиск сидит на порту 11h, но свои
; прямые обращения к квазидиску CO делает только на ветке 'C', а на D: идёт
; через дисковый вызов БСВВ -- и там ОС сама выбирает порт по номеру диска,
; такой же самомодификацией операнда (Source/_E200h.asm в MDOS_T-72). Диск C:
; у CO -- номер 2, D: -- номер 3.
;
; Меню выбора диска по клавише «7» у CO собрано из блока строк, за которым
; сразу идёт код: четвёртую строку дописать некуда, а пункты B: и D:
; включаются независимо, так что и порядок строк меняется. Поэтому меню целиком
; переехало сюда -- список собирается в буфере под текущие настройки, буквы
; лежат в такой же таблице рядом. Врезка по 2870, хвост «7-Диск» с 28AE
; остаётся на месте.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

DIRDRV  EQU 0A849h              ; буква диска, каталог которого CO разбирает
PANELDR EQU 03E91h              ; CO: буквы дисков панелей
DISKB   EQU 03E97h              ; CO: настройка «диск B доступен» -- 'Y' или 'N'
SELPAN  EQU 00E4Dh              ; CO: HL += 1, если активна вторая панель
CMENU   EQU 00CF1h              ; CO: выбор из горизонтального меню
REDRAW  EQU 00FE0h              ; CO: перерисовать панели
REREAD  EQU 028AEh              ; CO: хвост «7-Диск» -- буква из B и перечитать

        JMP  dstart
; Данные держим в начале: конец блока вплотную подходит к стеку CO на BC00, и
; всё, что окажется под ним, стек рано или поздно затрёт.
;
; Признак «второй квазидиск есть» выставляет пусковая проба оборудования:
; спрашивать систему прямо из меню нельзя -- вызов БСВВ «выбрать диск» меняет
; выбранный диск за спиной БДОС, и следующее чтение каталога уходит не на тот
; диск. При старте это безобидно, при работе -- нет.
DFLAG:  .db  'N'                ; до пробы
; A: и B: -- дисководы либо дискеты НЖМД. Нет ни того, ни другого -- показывать
; их незачем: панель на них открывается с ошибкой диска. До пробы считаем, что
; есть: так ведут себя старые сборки, у которых таблицы оборудования нет.
AFLAG:  .db  'Y'                ; до пробы
letters: .ds 6                  ; буквы пунктов меню по номеру пункта
strbuf: .ds  24                 ; сам список пунктов, собранный под настройки

; ---------------- «квазидисковая» разметка для D: --------------------------
; Две проверки буквы решают не «куда писать», а «как устроен диск»: сколько
; записей в каталоге (40h против 80h) и какой ширины номера блоков в записи
; (байт против слова). Квазидиск маленький, номера блоков влезают в байт;
; дискета на 390 блоков требует слова. Для D: CO брал дискетный вариант, читал
; каталог парами байт и рассыпал 5Ah по всей памяти от A100 до D500 -- вместе
; со своим стеком и перенесённым туда блоком.
;
; Обе отвечают на D: так же, как на C:. Устроены одинаково: 'C'-43h = 0,
; 'D'-43h = 1, младший бит отбрасывается -- обе буквы дают Z; 'A' и 'B' дают
; FEh и FFh, после отбрасывания FEh. Врезки по 1DE6 и 1EC2: вызов вместе с
; загрузкой буквы короче исходного CPI, трамплин не нужен.
dstart:
cdm:    MOV  A,M                ; буква лежит по HL -- врезка по 1DE6
        SUI  'C'
        ANI  0FEh
        RET
cdl:    LDA  DIRDRV             ; буква лежит в A849 -- врезка по 1EC2
        SUI  'C'
        ANI  0FEh
        RET
; Третья проверка той же породы. Подпрограмма по 0273/027A -- работа с
; каталогом дискеты: она держит его копию в памяти по 4000 (диск B:) или 5000 и
; сбрасывает обратно залпом из 32 секторов по 128 байт -- ровно каталог дискеты
; на 128 записей. Для квазидиска она не нужна и сразу выходит по 'C'. Диску D:
; буква не совпадала, CO шёл дискетной веткой и писал эти 4 КБ нулей на D: -- на
; свежем диске они ложились на дорожки 8..11, в середину только что
; скопированного файла.
;
; Править надо сам вход 027A: на него приходят и со стороны (0B56, 2251) с уже
; загруженной буквой. Для C: и D: снимаем адрес возврата и выходим из
; вызывающей, для прочих букв возвращаемся как ни в чём не бывало, сохранив
; букву в A.
cdrz:   PUSH PSW
        SUI  'C'
        ANI  0FEh
        JNZ  cdrz1              ; не квазидиск
        POP  PSW
        POP  H                  ; снять возврат
        RET                     ; и выйти из вызывающей
cdrz1:  POP  PSW
        RET

; ---------------- трамплины «C: или D:» ------------------------------------
; По 0B5F и 0B6E CO выбирает не разметку, а сами подпрограммы доступа: для C:
; квазидисковые (1713 и 178F), для всего прочего -- дисководные (1701 и 179B), а
; у тех каталог на 128 входов и лежит с дорожки 8. Пока диск 3 шёл собственным
; путём CO, разницы было не видно; теперь, когда обмен идёт через БСВВ, каталог
; D: читался по-квазидисковому, а писался по-дисководному -- отсюда и
; рассогласование контрольных сумм. Уводим D: в ту же ветку, что и C:.
trkwr:  CPI  'C'
        JZ   L_0B67
        CPI  'D'
        JZ   L_0B67
        JMP  L_0B64
trkrd:  CPI  'C'
        JZ   L_0B76
        CPI  'D'
        JZ   L_0B76
        JMP  L_0B73

; ---------------- буква панели из CO.PRM -----------------------------------
; Буква хранится упакованной: при записи (1422 и 1431) CO берёт от неё два
; младших бита и складывает с флагами панели, при чтении (14EE и 1501) делает
; обратное -- ANI 03h / ADI 40h. Слотов ровно четыре: 1 -- A:, 2 -- B:, 3 -- C:,
; а ноль не занят никем и разворачивался в 40h, «@».
;
; Диску D: в этой кодировке место есть: 44h и 03h дают тот самый ноль, то есть
; запись и так укладывает его правильно. Чинить надо только чтение -- иначе
; панель, сохранённая на D:, при следующем запуске открывается на «@».
;
; Таблицу заполняет пусковая проба оборудования: CO.PRM переносят с Вектора на
; Вектор, и записанный в нём диск на этой может отсутствовать вовсе. Недоступный
; заменяется первым доступным, а это всегда C:. Здесь -- значения на случай
; старой сборки, у которой таблицы оборудования нет и спросить не у кого.
prmdrv: ANI  3                  ; номер слота
        MOV  E,A
        MVI  D,0
        LXI  H,PDTAB
        DAD  D
        MOV  A,M
        RET
PDTAB:  .db  'C','A','B','C'

; ---------------- меню выбора диска ----------------------------------------
; Собираем список пунктов под текущие настройки. Пункты идут по алфавиту;
; безусловен только C: -- квазидиск есть в любом Векторе, с него система и
; грузится. Строки складываем в буфер, буквы -- в таблицу рядом, чтобы по
; номеру пункта сразу получить букву.
MENU:   LXI  H,strbuf
        MVI  M,0                ; первая строка пустая -- это заголовок
        INX  H
        LXI  D,letters
        MVI  C,1                ; сколько пунктов набрали
        LDA  AFLAG              ; дисководы или НЖМД есть?
        CPI  'Y'
        JNZ  noA
        MVI  A,'A'
        CALL add
        INR  C
noA:    LDA  AFLAG
        CPI  'Y'
        JNZ  noB
        LDA  DISKB              ; ... и своя настройка CO
        CPI  'Y'
        JNZ  noB
        MVI  A,'B'
        CALL add
        INR  C
noB:    MVI  A,'C'
        CALL add
        LDA  DFLAG              ; второй квазидиск есть?
        CPI  'Y'
        JNZ  noD
        MVI  A,'D'
        CALL add
        INR  C
; Текущий диск панели -- на него и ставим курсор меню.
noD:    LXI  H,PANELDR
        CALL SELPAN
        MOV  A,M                ; буква активной панели
        LXI  H,letters
        MVI  E,1                ; номер пункта
        MOV  B,C                ; сколько всего пунктов
find:   CMP  M
        JZ   found
        INX  H
        INR  E
        DCR  B
        JNZ  find
        MVI  E,1                ; не нашли -- встанем на первый
found:  MOV  A,C
        STA  nitems
        MOV  D,A
        INR  D                  ; и заголовок
        LXI  H,strbuf
        CALL CMENU
        CPI  01Bh               ; АР2 -- ничего не меняем
        JZ   REDRAW
; Номер пункта должен быть от 1 до числа пунктов. Ноль или больше нужного меню
; отдаёт, если выбор отменили краем: без проверки DCR A дал бы FFh, а выборка по
; таблице букв прочла бы байт ПЕРЕД ней. Такая буква уходила в панель и
; сохранялась в CO.PRM -- после перезапуска панель открывалась на
; несуществующем диске.
        ORA  A
        JZ   REDRAW
        DCR  A                  ; номер пункта с нуля
        LXI  H,nitems
        CMP  M
        JNC  REDRAW             ; за краем
        LXI  H,letters
        MOV  E,A
        MVI  D,0
        DAD  D
        MOV  B,M                ; буква выбранного пункта
        JMP  REREAD
nitems: .db  0                  ; сколько пунктов вышло

; Положить строку «"X"» в буфер по HL, а букву из A -- в таблицу по DE.
add:    PUSH PSW
        MVI  M,'"'
        INX  H
        MOV  M,A
        INX  H
        MVI  M,'"'
        INX  H
        MVI  M,0                ; конец строки
        INX  H
        POP  PSW
        STAX D
        INX  D
        RET
