; ---------------------------------------------------------------------------
; Проба состава оборудования при старте: НЖМД и второй квазидиск.
;
; «СС»-«7» переставлен с печати файла на выбор дискеты НЖМД безусловно, а
; винчестера в Векторе может и не быть. Спросить об этом БСВВ нечем: у
; дисковода и квазидиска есть штатный «выбрать диск», у дискет НЖМД -- ничего.
;
; Единственный источник -- таблица, которую ImproverX завёл в T-72 от
; 15.09.2026: по FFCA лежит количество дискет НЖМД, ноль -- винчестера нет.
; Признака у таблицы нет, поэтому смотрим на сами значения: дисков в системе
; бывает три или четыре, верх памяти BCh или C0h, а адрес записи дискеты обязан
; указывать в область ОС. У старой сборки, где таблицы нет, по этим адресам
; просто верхушка памяти, и все три разом совпадут едва ли. Не сошлось --
; значит таблицы нет, и всё остаётся как было.
;
; Если винчестера нет, возвращаем на место и обработчик (запись в таблице
; «клавиша -> адрес»), и строку подсказки: иначе внизу осталось бы «7-Hdd» при
; работающей печати.
;
; Работает там, куда её положила загрузка, и под стек не едет: она нужна один
; раз при старте, а к первому чтению каталога в 4100 уже отработает -- тем же
; рассуждением, что и остальные пусковые (co-src/pusk.asm).
; ---------------------------------------------------------------------------
        ORG  ORIGIN

D_DISKS EQU 0FFC9h              ; таблица ОС: сколько дисков в системе
D_HDDD  EQU 0FFCAh              ; ... количество дискет НЖМД, 0 -- НЖМД нет
D_DrvA  EQU 0FFCCh              ; ... адрес записи дискеты НЖМД диска A:
D_FRAM  EQU 0FFD0h              ; ... верх памяти: BCh с флоповодами, C0h без
SELDSK  EQU 0C01Bh              ; БСВВ: выбрать диск, номер в C
CURDRV  EQU 00004h              ; БДОС: текущий диск в младшей тетраде

; Таблица состава оборудования на месте? Признака у неё нет -- см. шапку.
PROBE:  LDA  D_DISKS
        CPI  3
        JC   pdone              ; дисков меньше трёх
        CPI  5
        CMC
        JC   pdone              ; ... или больше четырёх
        LDA  D_FRAM
        CPI  0BCh
        JZ   phok
        CPI  0C0h
        JNZ  pdone
phok:   LDA  D_DrvA+1           ; старший байт адреса записи дискеты
        CPI  0E0h
        JC   pdone              ; не в области ОС
; A: и B: -- дисководы либо дискеты НЖМД. Драйверы флоповодов система отмечает
; верхней границей памяти: BCh -- есть (килобайт под буфер дисковода), C0h --
; нет. Нет ни их, ни дискет НЖМД -- и оба диска надо прятать: панель на них
; открывается с ошибкой диска.
        LDA  D_FRAM
        CPI  0BCh
        JZ   phave
        LHLD D_HDDD
        MOV  A,H
        ORA  L
        JNZ  phave
        MVI  A,'N'
        STA  AFLAG
phave:  LHLD D_HDDD             ; сколько дискет НЖМД
        MOV  A,H
        ORA  L
        JNZ  pdone              ; есть -- ничего не трогаем
; Заодно выключаем пусковое восстановление выбранной дискеты: оно открывает
; C:CO.HDD и, если файл есть, раздаёт номера дискет командой ОС «9». Без НЖМД
; раздавать нечего, а обращение к диску при пустом дисководе кончается ошибкой
; диска ещё до панелей -- на сборке k, где дисковода нет вовсе, она вылезает
; всегда. Пусковая начинается с вызова, ставим на её место RET.
        MVI  A,0C9h
        STA  HDDINIT
        LXI  H,L_06E5           ; штатная печать -- назад в таблицу клавиш
        SHLD HDSLOT
        LXI  H,PLAINBAR         ; и прежняя подсказка -- назад в строку
        LXI  D,BAR2
        MVI  C,BARLEN
ploop:  MOV  A,M
        STAX D
        INX  H
        INX  D
        DCR  C
        JNZ  ploop

; Второй квазидиск: спрашиваем у самой ОС. БСВВ «выбрать диск» с номером 3
; возвращает ноль, если диска нет; число дисков система подставляет себе при
; старте, поэтому ответ верен на любой сборке T-72, а не только на новой с
; таблицей по FFC9.
;
; Делать это надо именно при старте. Вызов «выбрать диск» кладёт номер в
; описатель дисковой операции БСВВ, то есть меняет выбранный диск за спиной
; БДОС; из работающей программы это уводит следующее чтение каталога не на тот
; диск. Выбор всё равно возвращаем -- по младшей тетраде ячейки 0004.
pdone:  MVI  C,3
        CALL SELDSK
        MOV  A,H
        ORA  L
        MVI  A,'N'
        JZ   pset
        MVI  A,'Y'
pset:   STA  DFLAG
        LDA  CURDRV
        ANI  00Fh
        MOV  C,A
        CALL SELDSK             ; вернуть выбор

; Таблица «слот CO.PRM -> буква». CO.PRM переносят с Вектора на Вектор, и
; записанный в нём диск на этой может отсутствовать вовсе -- панель тогда
; открывается с ошибкой диска. Недоступный заменяем первым доступным, а это
; всегда C:: квазидиск есть в любом Векторе, с него система и грузится.
        MVI  A,'C'
        STA  PDTAB              ; слот 0 -- D:, пока C:
        STA  PDTAB+1            ; слот 1 -- A:
        STA  PDTAB+2            ; слот 2 -- B:
        LDA  AFLAG
        CPI  'Y'                ; дисководы или НЖМД есть?
        JNZ  pnoab
        MVI  A,'A'
        STA  PDTAB+1
        MVI  A,'B'
        STA  PDTAB+2
pnoab:  LDA  DFLAG
        CPI  'Y'                ; второй квазидиск есть?
        JNZ  pnod
        MVI  A,'D'
        STA  PDTAB
pnod:   JMP  HDDINIT            ; дальше по пусковой цепочке

; Прежняя нижняя строка второго набора -- та, где на «7» печать. Её проба
; кладёт обратно, когда система говорит, что винчестера нет.
PLAINBAR: .db '1-40/60 2-Атрибуты 3-ПрК7  4-VDE 5-КсЗИ 6-Запись  7-Печать 8-Файл 9-Sid  0-Выход'
