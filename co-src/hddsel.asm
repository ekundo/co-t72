; ---------------------------------------------------------------------------
; «СС»-«7» -- выбор дискеты НЖМД вместо печати файла.
;
; Номер запоминается в файле CO.HDD. Именно в своём файле, а не в хвосте
; CO.PRM: CO пишет CO.PRM целиком своей копией и затирает там что угодно чужое.
;
; Файл всегда на C: -- на квазидиске, где лежит система и автозапуск. Брать
; «текущий на момент старта» нельзя: стоит запустить CO, когда текущим был A:,
; и номер уезжает на дискету НЖМД. Причём пишется он уже ПОСЛЕ команды 9, то
; есть на вновь выбранную дискету, -- копии расползались по винчестеру, а на C:
; оставалась прежняя, и следующий запуск восстанавливал позапрошлый номер.
;
; Защита файла от записи работает как фиксация: если у CO.HDD стоит признак
; «только чтение», номера из него применяются при старте, а новые не пишутся --
; выбранное в этом сеансе живёт до перезагрузки.
;
; И читается, и пишется файл всегда под НУЛЕВЫМ пользователем CP/M. Номер
; пользователя БДОС держит у себя (функция 20h), в ФУБ его нет, поэтому под
; ненулевым файл создавался бы с этим номером и следующий запуск под другим
; номером его бы не нашёл. Перед работой номер запоминается, ставится нулевой, а
; после -- возвращается прежний.
;
; Как это работает в CO. Второй набор цифровых клавиш -- это не отдельный режим,
; а просто СС+цифра: 0574 вычитает у кода 10h, так что «СС»-«7» приходит как
; 27h. Дальше два уровня таблиц «клавиша -> адрес»: 05DA, а по умолчанию 05AA ->
; таблица 0637. Там и лежала запись 27 -> 06E5, «7-Печать».
;
; Обработчик берёт букву диска активной панели; если это не A: и не B: -- молча
; возвращается, не спрашивая номер: назначать дискету НЖМД можно только на эти
; два диска (P_Ex01: CPI 002 / JNC -> «Неверное имя»). Иначе печатает
; приглашение, читает шестнадцатеричный номер (до четырёх цифр, ВК -- ввод,
; АР2 -- отмена), заполняет ФУБ по 005C и выполняет команду МикроДОС «9» через
; вектор БСВВ E218. Писать напрямую в таблицу T_DrvA/T_DrvB нельзя: её адрес у
; сборок разный, а мимо команды 9 потеряются сброс дискового буфера, обнуление
; прежнего назначения и пересчёт стартового сектора дискеты.
;
; Панель после смены дискеты перечитывается хвостом штатного «7-Диск»: с 28AE он
; берёт букву диска из B, кладёт её в панель и перечитывает каталог. Звать 2870
; целиком нельзя -- он сначала спросит букву.
;
; Проверить назначение до конца на v06x нельзя -- он не эмулирует НЖМД, и предел
; числа дискет там выставлен в ноль. Поэтому годится только номер 0 (это
; физический дисковод), на любом другом ОС ответит «Неверное имя» -- что само по
; себе доказывает, что команда до неё дошла.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

HPANEL  EQU 03E91h              ; CO: буквы дисков панелей
HSELPAN EQU 00E4Dh              ; CO: HL += 1, если активна вторая панель
HSELP2  EQU 00E47h              ; CO: то же для таблицы по два байта на панель
HGETKEY EQU 00D44h              ; CO: ждать клавишу, код в A
HREDRAW EQU 00FE0h              ; CO: перерисовать панели
HREREAD EQU 028AEh              ; CO: хвост «7-Диск» -- буква из B и перечитать
HLOOP   EQU 0030Fh              ; CO: вернуться в главный цикл
HKEYCOD EQU 0B693h              ; CO: код нажатой клавиши
HPANCNT EQU 0B689h              ; CO: счётчик файлов панели
HKEYTAB EQU 00637h              ; CO: вторая таблица «клавиша -> адрес»
HKEYGO  EQU 00562h              ; CO: разобрать таблицу клавиш
HNOFILE EQU 00F86h              ; CO: куда CO уходит при пустой панели
HBDOS   EQU 00005h              ; вызов БДОС напрямую: RST 1 при старте ещё не готов
HBIOS   EQU 0E218h              ; БСВВ: выполнение цифровых команд, номер в A
HFCB    EQU 0005Ch              ; рабочий ФУБ, он же вход команды 9
; Буфер обмена с диском -- штатный по 0080: своя запись на 128 байт съела бы
; восьмую часть всего места под стеком, а этот в наших операциях свободен.
HBUF    EQU 00080h
HSIGN   EQU HBUF                ; в нём подпись 'HD', за ней два слота
HSLOTL  EQU 5                   ; слот: длина номера и четыре знака
HHOME   EQU 3                   ; диск файла -- C:, квазидиск с системой
; Сюда прячется ФУБ самого CO на время команды 9 -- в хвост буфера копирования.
; Команду зовут при старте, когда CO ещё не трогала буфер, и из накладки списка,
; которая сама лежит в этом буфере и до 9F80 не доходит.
hdsave  EQU 09F80h

; ---------------- «СС»-«7» -------------------------------------------------
; Обычное нажатие открывает список дискет -- накладку, которая лежит в конце
; самой CO.COM (co-src/hdlist.asm). С «УС» остаётся прежний ввод номера: он
; нужен, когда список не построить -- не та сборка, винчестер отвечает
; ошибкой. Ввод номера, работа с CO.HDD и команда «9» тоже живут в накладке
; (co-src/hdcmd.asm): место под стеком отдано мыши. Поэтому без C:CO.COM
; клавиша теперь не делает ничего.
; Слово управляющих клавиш CO читает портом 01 (04D2) и кладёт в A801.
; Биты там ОБРАТНЫЕ: нажатой клавише соответствует ноль. Видно это по
; обработчику кода 20h (036D): «ANI 20h / JZ» уводит на выход в ДОС, то есть
; на «СС»-«0», -- значит ноль в бите 5 и есть нажатая «СС». Так же устроен и
; бит 6: по 398E при нуле в нём («УС»-«4») редактор запускается без имени
; выделенного файла, ровно как обещает справка CO.
KEYWORD EQU 0A801h              ; слово управляющих клавиш
K_US    EQU 040h                ; бит «УС»: ноль -- нажата

HDDKEY: LXI  H,HPANEL
        CALL HSELPAN
        MOV  A,M
        CPI  'A'
        JZ   hdok
        CPI  'B'
        JNZ  hdback             ; не дисковод -- молча назад
hdok:   SUI  040h               ; номер диска 1 или 2
        STA  hdrive
        CALL ovload
        JZ   hdback             ; накладки нет -- ни списка, ни ввода номера
        LDA  KEYWORD
        ANI  K_US
        JZ   HDLASK             ; «УС» нажата -- ввод номера, он тоже в накладке
        JMP  HDLRUN
hdback: CALL HREDRAW
        JMP  HLOOP

; ---------------- пропустить «СС»-«7» при пустой панели --------------------
; CO отсекает клавиши второй таблицы, если в панели нет файлов (05B1: CPI 0 /
; JZ 0F86), а выбор дискеты от файлов не зависит. Врезка по 05AA.
HDHOOK: LDA  HKEYCOD
        CPI  027h
        JZ   hdtab
        LXI  H,HPANCNT
        CALL HSELP2
        MOV  A,M
        ORA  A
        JZ   HNOFILE            ; пусто -- как было
hdtab:  LDA  HKEYCOD
        LXI  H,HKEYTAB
        JMP  HKEYGO

; CO.HDD всегда под нулевым пользователем -- см. шапку. Обе точки входа
; обёрнуты: запомнить номер, встать на нулевого, вернуть как было. A и флаги
; через PUSH PSW -- prmload отдаёт «нечего брать» именно ими.
usr0:   MVI  C,020h             ; запомнить и на 0
        MVI  E,0FFh
        CALL HBDOS
        STA  usrsav
        MVI  C,020h
        MVI  E,0
        CALL HBDOS
        RET

usrback: MVI C,020h             ; вернуть прежний
        LDA  usrsav
        MOV  E,A
        CALL HBDOS
        RET


; ---------------- накладка списка дискет -----------------------------------
; Читает её из C:CO.COM в буфер копирования и сверяет подпись. Диск тот же,
; что у CO.HDD, и по той же причине: на C: лежит система и автозапуск, и CO
; сама переносит туда свой обиход по списку CO.ZGR -- вместе с собой.
; Возврат: Z -- не вышло, накладки нет; NZ -- лежит на месте и готова.
ovload: CALL usr0               ; всё то же: нулевой пользователь CP/M
        CALL ovload0
        PUSH PSW
        CALL usrback
        POP  PSW
        RET

ovload0: MVI C,00Fh             ; открыть
        LXI  D,ovfcb
        CALL HBDOS
        INR  A
        RZ                      ; файла нет
        XRA  A
        STA  ovfcb+32           ; текущая запись -- БДОС её не спросит
        STA  ovfcb+35
        LXI  H,HDLREC           ; номер первой записи накладки в CO.COM
        SHLD ovfcb+33
        LXI  H,OVL              ; куда читаем
        MVI  B,HDLRECS
ovl1:   PUSH B
        PUSH H
        XCHG
        MVI  C,01Ah             ; адрес обмена -- очередная запись
        CALL HBDOS
        MVI  C,021h             ; чтение по номеру
        LXI  D,ovfcb
        CALL HBDOS
        POP  H
        POP  B
        ORA  A
        JNZ  ovbad              ; не дочитали
        LXI  D,128
        DAD  D
        LXI  D,ovfcb+33         ; следующая запись
        LDAX D
        INR  A
        STAX D
        JNZ  ovl2
        INX  D
        LDAX D
        INR  A
        STAX D
ovl2:   DCR  B
        JNZ  ovl1
        LXI  H,OVL              ; сошлась ли подпись
        LXI  D,ovsign
        MVI  B,4
ovl3:   LDAX D
        CMP  M
        JNZ  ovbad
        INX  H
        INX  D
        DCR  B
        JNZ  ovl3
        MVI  A,0FFh
        ORA  A
        RET
ovbad:  XRA  A
        RET

; ---------------- данные ---------------------------------------------------
; Всё, что ниже, -- буферы: в них по нашей же просьбе пишет БДОС (свой ФУБ на
; CO.HDD, сохранённый ФУБ самого CO). В раскладке они отмечены отдельно от кода,
; иначе сторож целости в check-funcs.sh принял бы это за чужую запись поверх
; нашего кода.
HDDATA  EQU  $
hdrive: .db  1
hdhome: .db  HHOME              ; диск файла -- постоянный, не «текущий»
usrsav: .db  0
ovsign: .db  'HDL1'             ; подпись накладки -- такая же в её первых байтах
ovfcb:  .db  HHOME,'CO      COM'    ; ФУБ на C:CO.COM
        .ds  24                 ; остальное БДОС заполнит сам
HDDEND  EQU  $
