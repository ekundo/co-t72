; ==========================================================================
; ПУСКОВЫЕ НАКЛАДКИ: работают один раз при старте, по адресу загрузки
; ==========================================================================
;
; Эти куски отрабатывают в пусковой цепочке -- до того, как CO прочитает хоть
; один каталог, -- и больше не нужны. Поэтому они не едут ни под стек, ни в
; окно: остаются там, куда их положил загрузчик. Позже это место (4000-4FFF)
; CO займёт копией каталога диска B:, и к тому времени здесь уже нечему
; работать.
;
; Цепочку начинает стаб по 40DB: он переносит хвост под стек и зовёт WINMOVE,
; тот -- DISKVEC, дальше проба оборудования, за ней копировщик надписи в рамке
; и пусковая дискеты НЖМД. Кончается цепочка возвратом в стаб.

; --------------------------------------------------------------------------
; Проверка, что файл из списка CO.ZGR вообще открывается: без неё CO заводила
; на C: пустышку нулевой длины для каждого имени, которого на исходном диске
; нет. Зовётся из цикла разбора CO.ZGR -- правка по 3F01.
; --------------------------------------------------------------------------
ORIGIN  EQU $
ZGRCHK  EQU $
#include "../tools/zgrcheck.asm"

; --------------------------------------------------------------------------
; Переносчик накладок в окно ОЗУ: один раз копирует их с адреса загрузки на
; A448. Сам остаётся здесь -- в окне ему делать нечего.
; --------------------------------------------------------------------------
WINMOVE: LXI  H,OKNOFILE                ; откуда -- хвост образа, как он лёг
         LXI  D,0A448h                  ; куда -- свободный кусок окна
         LXI  B,OKNOEND-0A448h          ; сколько -- длину знает листинг
wmove:   MOV  A,M
         STAX D
         INX  H
         INX  D
         DCX  B
         MOV  A,B
         ORA  C
         JNZ  wmove

; --------------------------------------------------------------------------
; Дисковый обработчик БСВВ -- единственный зашитый адрес ОС во всём CO. Берём
; его живым из вектора E213 и расставляем по четырём местам, где CO его
; называет:
;
;     0189   JZ    -- фильтр по 0185 пропускает вызов дальше
;     0206   JMP   -- то же, другой путь
;     02F6   CALL
;     205E   LXI H -- восстановление вектора: CO кладёт исходный адрес обратно
;
; Порядок важен: читать вектор надо ДО того, как CO подменит его своим
; фильтром (это она делает по 4078), а пусковая цепочка отрабатывает раньше.
; --------------------------------------------------------------------------
DISKVEC: LHLD 0E213h
         SHLD 0189h
         SHLD 0206h
         SHLD 02F6h
         SHLD 205Eh

; --------------------------------------------------------------------------
; Дальше по цепочке -- проба состава оборудования. Она лежит за тем, что едет
; под стек (co-src/proba.asm): всё, что дописано после границы переноса,
; остаётся по адресу загрузки.
; --------------------------------------------------------------------------
         JMP  PROBE

; --------------------------------------------------------------------------
; Номер дискеты НЖМД и её метка в рамке панели. Само тело работает в окне, по
; A660: под стеком места на триста с лишним байт нет, а A480-A7FF -- дыра между
; буферами CO, куда за целую сессию не пишется ни байта. Здесь копировщик,
; который при старте кладёт тело на место, и сам исходник тела -- он остаётся
; там, куда его положила загрузка, и к моменту копирования ещё цел.
;
; Дисковый обработчик берётся не адресом, а ссылкой: DISK -- это операнд по
; 0189, куда живой адрес кладёт DISKVEC выше. Так накладка переживает сдвиг
; адресов в БСВВ вместе со всем остальным.
; --------------------------------------------------------------------------
HDCOPY:  LXI  H,HDFILE                  ; откуда -- исходник тела, как он лёг
         LXI  D,HDBODY                  ; куда -- дыра в окне
         LXI  B,HDEND-HDBODY            ; сколько
hdmv:    MOV  A,M
         STAX D
         INX  H
         INX  D
         DCX  B
         MOV  A,B
         ORA  C
         JNZ  hdmv
; Следом -- пусковая дискеты НЖМД: она восстанавливает номера, сохранённые в
; C:CO.HDD. Её RET и возвращает управление стабу.
         JMP  HDDINIT

HDBODY  EQU  0A660h                     ; где тело работает -- на него и врезка
HDFILE  EQU  $                          ; исходник тела -- отсюда и копируем
DISK    EQU  0189h                      ; операнд с адресом дискового обработчика
ORIGIN  EQU  HDBODY
        PHASE HDBODY
#include "../tools/hdinfo.asm"
HDEND   EQU  $
        DEPHASE
