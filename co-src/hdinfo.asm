; ---------------------------------------------------------------------------
; Номер дискеты НЖМД и её метка -- в рамке панели CO.
;
; В шапке панели места нет: «Диск X  Файлов NN  Свободно NNN Кб.» занимает ровно
; сорок знаков, а панелей две -- вся строка. Зато свободна сама рамка: её край --
; это уголок, 38 линий и уголок. Пишем в него вывороткой -- теми же
; escape-последовательностями, какими CO рисует шапку панели, -- прижимая надпись
; к правому краю. Слева отведённую полосу добиваем самой рамкой: иначе от прошлой,
; более длинной метки остаётся хвост.
;
; Край выбран верхний, а не нижний. Снизу CO при отметке файлов печатает, сколько
; их отмечено и на сколько килобайт, -- и надпись затирал именно этот счётчик. Да
; и в той же нижней рамке живёт признак " >CO.PTK " (режим «ПС», флаг в B672).
; Сверху же не рисует ничего, поэтому метке достаётся почти вся рамка.
;
; Откуда что берётся:
;
;   номер -- из таблицы дискет НЖМД самой ОС (T_DrvA/T_DrvB, номер и первый
;            сектор). Её адрес система сообщает сама -- в таблице состава
;            оборудования по FFCC и FFCE, -- поэтому в сборке он не зашит и
;            CO.COM годится для любой сборки T-72. Читать таблицу, а не помнить
;            своё, важно: дискету могли назначить и командой «9» мимо CO;
;
;   метка -- с самой дискеты, из сектора за концом файловой системы (её пишет
;            HDIR /M). Читаем штатным дисковым обработчиком БСВВ -- тем самым,
;            адрес которого CO и так знает: описатель дисковой операции, в нём
;            диск, режим, дорожка, сектор и адрес буфера. Дорожка 164 -- она
;            последняя из разрешённых (БСВВ ругается с 0A5h), а БДОС туда не
;            заглядывает, там нет блоков файловой системы.
;
; Вертикальные разделители колонок панели -- не знаки: CO прочерчивает их прямо
; в видеопамяти (по 0D7B, с переключением банка портом 10h), сверху вниз от
; верхней рамки до нижней. Знак, напечатанный в такой колонке, стирает штрих в
; своей клетке -- и разделитель перестаёт примыкать к рамке.
;
; Поэтому там, где полоса -- просто рамка, колонки разделителей перешагиваем
; знаком «вправо» (018h), ровно как сам CO перешагивает их, печатая строки
; каталога. А под самой надписью разделитель закрываем: номер дискеты важнее, и
; рвать его штрихом пополам незачем. Где разделители стоят, видно по 3E93: 'P' --
; сорок файлов в двух колонках (клетки 19 и 20), иначе шестьдесят в трёх (13 и 26).
;
; Рисуется после штатной отрисовки панели, а не до: рисуя панель, CO чистит её
; поле и прихватывает три нижние строки точек нашей строки -- буквы выходили
; обрезанными снизу. А курсор в конце возвращаем туда же, куда его ставит сам
; CO, дорисовав рамку (строка 23, колонка 76).
;
; Врезано в конец отрисовки, а не в начало. Сначала перехват стоял по 091B, с
; которого отрисовка начинается, -- и надпись пропадала при листании панели:
; входов у отрисовки три (091B -- со сменой диска, 091E -- без неё, 0927 -- с
; другим построчным отрисовщиком), а листание идёт по 08CD прямо в 091E, мимо
; 091B. Сходятся все три в одном месте -- 097E, где стоит JMP на парковку
; курсора, -- и другого пути наружу у отрисовки нет. Перехватывать надо
; именно его: сама парковка (0FF3) для этого не годится, её зовут из
; четырнадцати мест по всему CO, и надпись полезла бы в помощь и просмотр.
; ---------------------------------------------------------------------------

PANEL   EQU 0B69Dh              ; номер активной панели: 1 или 2
DRVLET  EQU 03E91h              ; буквы дисков панелей
P_0FF3  EQU 00FF3h              ; CO: парковка курсора -- ею кончается отрисовка
                                ; панели, и это она затёрта по 097E
B_HEX   EQU 0F815h              ; БСВВ: вывод байта на экран 16-ричным
P_NCHR  EQU 00F75h              ; CO: напечатать A знаков, начиная с (HL)
PANLOOK EQU 03E93h              ; вид панелей: 'P' -- 40 файлов, иначе 60
BUF     EQU 00080h              ; штатный буфер обмена: БСВВ отдаёт одну запись
                                ; в 128 байт, а этот буфер любая программа CP/M
                                ; и так считает затираемым при чтении с диска

D_DISKS EQU 0FFC9h              ; таблица ОС: сколько дисков в системе
D_DrvA  EQU 0FFCCh              ; ... адрес записи дискеты НЖМД диска A:
D_FRAM  EQU 0FFD0h              ; ... верх памяти: BCh с флоповодами, C0h без

ROW     EQU 021h                ; ВЕРХНИЙ край рамки панели
COL     EQU 023h                ; и четвёртая колонка: два знака рамки слева
                                ; оставляем нетронутыми -- ровно столько же
                                ; остаётся справа, и полоса выходит симметричной
PARKROW EQU 037h                ; куда CO уводит курсор, дорисовав рамку
PARKCOL EQU 06Ch
WIDTH   EQU 34                  ; сколько знаков рамки отдаём под надпись: с
                                ; четвёртой колонки по тридцать седьмую, то есть
                                ; по два знака рамки с каждой стороны. Правый
                                ; край выбран по счётчику отмеченных файлов --
                                ; CO печатает его с таким же отступом
LINE    EQU 08Dh                ; горизонталь рамки -- ею же и затираем
SKIP    EQU 018h                ; знак вправо: им перешагиваем разделитель
SIGNLEN EQU 4                   ; подпись сектора метки
LABLEN  EQU 32                  ; знаков в метке
LABTRK  EQU 164                 ; дорожка сектора метки
LABSEC  EQU 33                  ; и сектор в ней

        ORG ORIGIN

; Перехват конца отрисовки панели: по 097E у CO стоит переход сюда.
hook:   CALL P_0FF3             ; затёртая команда
        PUSH PSW
        PUSH B
        PUSH D
        PUSH H
        CALL info
        POP  H
        POP  D
        POP  B
        POP  PSW
        RET

info:   LDA  PANEL
        DCR  A
        STA  pan                ; 0 -- левая, 1 -- правая
        CALL divs
        CALL cursor
        CALL show
        MVI  C,01Bh             ; курсор обратно на командную строку
        RST  4
        MVI  C,'Y'
        RST  4
        MVI  C,PARKROW
        RST  4
        MVI  C,PARKCOL
        RST  4
        RET

show:   CALL number             ; NZ -- дискеты нет, вся полоса остаётся рамкой
        JNZ  blank
        CALL readlab            ; длина метки -> lablen, 0 если метки нет
        MVI  A,6                ; в надписи всегда « NNNN »
        MOV  B,A
        LDA  lablen
        ORA  A
        JZ   sh1
        ADD  B                  ; ... и метка с пробелом за ней
        INR  A
        MOV  B,A
sh1:    CALL pad                ; слева добиваем рамкой: надпись прижата вправо
        CALL inv                ; номер и метку -- вывороткой, как шапку у CO
        MVI  C,' '
        RST  4
        LHLD num
        MOV  A,H
        CALL B_HEX
        MOV  A,L
        CALL B_HEX
        MVI  C,' '
        RST  4
        LDA  lablen
        ORA  A
        JZ   sh3
        LXI  H,BUF+SIGNLEN
        CALL P_NCHR             ; A знаков метки
        MVI  C,' '
        RST  4
sh3:    JMP  norm

blank:  MVI  B,000h
        JMP  pad

; Колонки разделителей этой панели.
divs:   LXI  H,PANLOOK
        LDA  pan
        ORA  A
        JZ   dv1
        INX  H
dv1:    MOV  A,M
        CPI  'P'                ; сорок файлов -- две колонки
        MVI  A,13
        MVI  B,26
        JNZ  dv2
        MVI  A,19
        MVI  B,20
dv2:    STA  div1
        MOV  A,B
        STA  div2
        RET

; Добить полосу слева рамкой. B -- сколько колонок займёт надпись справа, ноль --
; вся полоса остаётся рамкой. Колонку разделителя не забиваем, а перешагиваем:
; иначе от его штриха в клетке рамки ничего не останется.
pad:    MVI  A,WIDTH+COL-020h   ; с какой колонки начинается надпись
        SUB  B
        MOV  D,A
        MVI  E,COL-020h         ; E -- текущая колонка панели
pd1:    MOV  A,E
        CMP  D
        RNC                     ; дошли до надписи
        LXI  H,div1
        CMP  M
        JZ   pd2
        INX  H
        CMP  M
        JZ   pd2
        MVI  C,LINE
        JMP  pd3
pd2:    MVI  C,SKIP
pd3:    PUSH D
        RST  4
        POP  D
        INR  E
        JMP  pd1

; Выворотка и обратно -- те же escape-последовательности, что у CO в шапке.
inv:    MVI  C,'b'
        JMP  esc
norm:   MVI  C,'a'
esc:    PUSH B
        MVI  C,01Bh
        RST  4
        POP  B
        RST  4
        RET

; Курсор на нижний край рамки нужной панели.
cursor: MVI  C,01Bh
        RST  4
        MVI  C,'Y'
        RST  4
        MVI  C,ROW
        RST  4
        LDA  pan
        ORA  A
        MVI  A,COL
        JZ   cu1
        ADI  40                 ; вторая панель -- на сорок колонок правее
cu1:    MOV  C,A
        RST  4
        RET

; Есть ли в ОС таблица состава оборудования. Признака у неё нет, поэтому смотрим
; на сами значения: дисков в системе бывает три или четыре, верх памяти BCh или
; C0h, а адрес записей дискет обязан указывать в область ОС. У старой сборки, где
; таблицы нет, по этим адресам просто верхушка памяти, и все три разом совпадут
; едва ли. Z -- таблица есть.
hastab: LDA  D_DISKS
        CPI  003h
        RC
        CPI  005h
        CMC
        RC
        LDA  D_FRAM
        CPI  0BCh
        JZ   ha1
        CPI  0C0h
        RNZ
ha1:    LDA  D_DrvA+1           ; старший байт адреса записи дискеты A:
        CPI  0E0h
        RC
        XRA  A                  ; Z -- таблица на месте
        RET

; Номер дискеты панели -> num. Z -- есть что показывать.
number: LXI  H,DRVLET
        LDA  pan
        ORA  A
        JZ   nu1
        INX  H
nu1:    MOV  A,M                ; буква диска панели
        SUI  'A'
        STA  drive              ; заодно номер диска для описателя
        CPI  2
        JNC  nu9                ; не A: и не B: -- дискет там не бывает
        CALL hastab             ; таблица ОС на месте?
        JNZ  nu9
        LDA  drive              ; номер диска обратно: POP PSW вернул бы и флаги
        LXI  H,D_DrvA           ; ОС сама держит адреса записей дискет A: и B:
        ORA  A                  ; признаки по номеру диска, а не по сравнению
        JZ   nu2
        INX  H
        INX  H                  ; диск B: -- следующее слово таблицы
nu2:    MOV  E,M
        INX  H
        MOV  D,M
        XCHG                    ; HL -- запись дискеты в таблице ОС
        MOV  E,M
        INX  H
        MOV  D,M
        XCHG
        SHLD num
        MOV  A,H
        ORA  L
        JZ   nu9                ; ноль -- на диске флоповод, а не дискета
        XRA  A                  ; Z -- есть что показывать
        RET
nu9:    MVI  A,1
        ORA  A
        RET

; Метка дискеты: читаем сектор за концом файловой системы и считаем, сколько
; знаков от неё показывать. Хвостовые пробелы отбрасываем, длинную обрезаем --
; в полосу должно влезть и « NNNN », и пробел за меткой.
readlab:XRA  A
        STA  lablen
        LXI  H,desc
        LDA  drive
        MOV  M,A
        CALL viadisk            ; обработчик БСВВ, описатель в HL
        LXI  H,BUF
        LXI  D,sign
        MVI  B,SIGNLEN
rl1:    LDAX D
        CMP  M
        RNZ                     ; подписи нет -- метки нет
        INX  H
        INX  D
        DCR  B
        JNZ  rl1
        LXI  H,BUF+SIGNLEN+LABLEN-1
        MVI  B,LABLEN
rl2:    MOV  A,M
        CPI  ' '
        JNZ  rl3
        DCX  H
        DCR  B
        JNZ  rl2
        RET                     ; метка из одних пробелов -- всё равно что нет
rl3:    MOV  A,B
        CPI  WIDTH-6
        JC   rl4
        MVI  B,WIDTH-7
rl4:    MOV  A,B
        STA  lablen
        RET

; Вызов дискового обработчика по живому адресу. Адрес лежит в операнде по
; 0189 -- его кладёт туда при старте пусковая цепочка листинга, сняв с вектора
; E213. Обработчик
; ждёт описатель в HL, поэтому HL трогать нельзя: адрес уводится через DE и
; кладётся на стек, а RET уходит по нему. Возврат обработчика попадает туда,
; куда положил CALL viadisk.
viadisk:XCHG                    ; DE -- описатель
        LHLD DISK               ; HL -- адрес обработчика
        XCHG                    ; HL -- описатель обратно, DE -- адрес
        PUSH D
        RET

; Описатель дисковой операции БСВВ: диск, ?, режим, ?, дорожка, сектор, буфер.
desc:   DB 0, 0, 4, 0, LABTRK, LABSEC
        DW BUF
sign:   DB 'HDLB'
pan:    DB 0
drive:  DB 0
num:    DW 0
lablen: DB 0                    ; сколько знаков метки показываем
div1:   DB 0                    ; колонки разделителей этой панели
div2:   DB 0
        END
