; ---------------------------------------------------------------------------
; Выход из списка: вернуть нижнюю подсказку и перерисовать панель.
;
; Каталог архива и список дискет НЖМД гасят нижнюю полосу: из её цифр в этих
; списках не работает ни одна (в списке дискет остаётся одна «6-Метка», её и
; печатают вместо полосы). Вернуть полосу было некому -- сама CO печатает её
; только при нажатии АР2 (0F9A), а выход из списка идёт другой дорогой, и
; подсказка так и оставалась пустой до первого АР2.
;
; Печатаем её тем же порядком, что и CO: BAR0 подводит курсор в нижнюю строку
; и гасит автоперевод, за ним идёт сама полоса. Какая именно -- помнит B68F:
; единица -- обычная, двойка -- та, что по «СС». Переключать его тут нельзя,
; этим занята АР2.
;
; Дальше -- прежний выход: шапки обеих панелей, список активной и строка под
; курсором. Картинку из буфера копирования тут не вернуть -- в нём лежит сам
; список (см. docs/co-buffers.md).
;
; Врезка по 2DC3 -- общий выход из списков.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

BARSW   EQU  0B68Fh             ; какая полоса на экране: 1 -- обычная, 2 -- «СС»
HEADS   EQU  00C7Eh             ; CO: шапки обеих панелей
LIST    EQU  0091Eh             ; CO: список активной панели заново
CURLIN  EQU  00890h             ; CO: строка под курсором

lout:   LXI  H,BAR0
        RST  3
        LDA  BARSW
        DCR  A
        LXI  H,BAR1
        JZ   lou1
        LXI  H,BAR2
lou1:   RST  3
        CALL HEADS
        CALL LIST
        JMP  CURLIN
        END
