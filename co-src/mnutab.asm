; ---------------------------------------------------------------------------
; Таблица меню пользователя: не заполнять её дальше, чем она есть.
;
; CO держит меню из CO.MNU таблицей по B728: два байта на пункт -- знак
; клавиши и счётчик команд под ним. Размер у таблицы указан трижды и все три
; раза по-разному:
;
;   39DA  чистит 2Eh байт             -- двадцать три пункта;
;   3A46  перебирает 1Ah записей      -- двадцать шесть;
;   3A1C  заполняет, пока идут строки -- сколько угодно.
;
; Третье и есть беда. CO.MNU на тридцать пунктов записывает шестьдесят байт,
; то есть до B763, а с B75C начинается дописанный сборкой код -- первым там
; лежит обмен с диском D:. Поймано сторожем: ЗАТЁРТ_B75C_из_3A1F на сценарии
; «многопунктов».
;
; Ставим предел по краю таблицы. Двадцать шесть пунктов -- ровно столько,
; сколько CO потом перебирает; всё, что дальше, в меню и так не попало бы.
; Врезка по 3A1C, на месте "POP H / INX H / MOV M,A / INX H / PUSH H /
; JMP 39F0" -- восемь байт, нам хватает трёх.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

NEXT    EQU  039F0h             ; CO: взять из CO.MNU следующую строку
DONE    EQU  03A2Ah             ; CO: список кончился, меню собрано
KEY     EQU  0B6A8h             ; первый знак строки -- он же клавиша пункта
                                ; TABHI и TABLO -- половинки первого байта
                                ; за таблицей, их задаёт co-src/okno.asm
                                ; от края нашего кода

mput:    POP  H                  ; указатель в таблице
        INX  H                  ; сюда ляжет знак клавиши
        MOV  A,H
        CPI  TABHI              ; за краем таблицы?
        JNZ  store
        MOV  A,L
        CPI  TABLO
        JNC  full
store:  LDA  KEY                ; знак клавиши -- его затёрло сравнение
        MOV  M,A
        INX  H                  ; следующий байт -- счётчик команд, его ведёт 3A24
        PUSH H
        JMP  NEXT

full:   PUSH H                  ; места нет: считаем, что список кончился
        JMP  DONE
        END
