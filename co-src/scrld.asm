; ---------------------------------------------------------------------------
; Загрузчик заставки C:CO.SCR.
;
; Файл ложится с 0100 -- туда же, где живёт сама CO, -- поэтому дочитывать его
; некому, кроме кода вне её образа. Этот кусок и есть такой код: он в окне,
; заставка его не достанет (SCRSAV по 2422 не берёт файлы от 32 КБ, а окно
; начинается с A000). Описатель уже открыт по 005C -- тоже вне образа.
;
; Вход из SCRSV2 (co.asm, 3A89): HL=0100, на стеке адрес 0100 и под ним нуль.
; Записи читаются по одной, каждая в свой адрес, пока БДОС не скажет «конец
; файла». Последней ставится штатная область обмена 0080 -- DE к этому
; моменту ровно 0080, -- и RET уходит в саму заставку.
; ---------------------------------------------------------------------------
SCRLD:  PUSH H
        XCHG
        MVI  C,1Ah              ; БДОС-26: буфер -- очередной адрес
        RST  1
        LXI  D,005Ch
        MVI  C,14h              ; БДОС-20: следующая запись
        RST  1
        POP  H
        LXI  D,0080h
        DAD  D
        ORA  A
        JZ   SCRLD
        MVI  C,1Ah              ; буфер обратно на 0080
        RST  1
        RET
