; ==========================================================================
; НАКЛАДКИ, КОТОРЫЕ РАБОТАЮТ В ОКНЕ ОЗУ (A448)
; ==========================================================================
;
; Лежат они в хвосте образа, а работают с A200: при старте их переносит туда
; переносчик накладок. Отчего так -- по адресу загрузки их затирает каталог
; диска B:, который CO держит копией в 4000-4FFF, а под стеком места на всё
; не хватает. Свободный кусок окна выведен из листинга (tools/winholes.py):
; A200-A7FF, полтора килобайта, и заняты они здесь подряд, без дыр.
;
; PHASE говорит ассемблеру «собирать здесь, а работать там»: метки внутри
; считаются от A448, а байты ложатся туда, куда шли -- в хвост.
;
; Порядок кусков менять можно, но тогда меняются и адреса, на которые
; ссылаются врезки в самой CO; все они помечены в co.asm словом ПРАВКА.

OKNOFILE EQU $                  ; где блок лежит в файле -- отсюда его копируют
OKNOLO  EQU 0A448h              ; ... и где он работает: начало свободного куска окна
        PHASE OKNOLO

; Край таблицы меню пользователя: с STKLO начинается наш код под стеком.
; Признак «второй квазидиск есть», на который смотрит накладка «поиск по X:»,
; -- метка DFLAG в накладке диска D:, она же лежит под стеком.
TABEND  EQU STKLO
TABHI   EQU TABEND >> 8
TABLO   EQU TABEND & 255

ORIGIN  EQU $
FIX16K  EQU $                   ; склейка экстентов, зовётся по 1AD1
#include "fix16k.asm"

ORIGIN  EQU $
DMAWIN  EQU $                   ; обмен с диском через буфер вне окна
#include "dmawin.asm"

ORIGIN  EQU $
XDRIVE  EQU $                   ; поиск программы по дискам -- с диском D:
#include "xdrive.asm"

ORIGIN  EQU $
KOI     EQU $                   ; кодировки в просмотрщике
#include "koi.asm"

ORIGIN  EQU $
VIEWTOP EQU $                   ; шаг назад в тексте не уезжает за начало
#include "viewtop.asm"

ORIGIN  EQU $
EXTBUF  EQU $                   ; CO.EXT и CO.MNU читаются в буфер копирования
#include "extbuf.asm"

ORIGIN  EQU $
MNUTAB  EQU $                   ; таблица меню пользователя не растёт за край
#include "mnutab.asm"

; Номер дискеты НЖМД и её метка в рамке панели. Раньше эта накладка ехала в
; окно своим копировщиком из пусковой части -- теперь едет со всеми.
ORIGIN  EQU $
HDBODY  EQU $                   ; надпись в рамке, врезка по 097E
DISK    EQU 0189h               ; операнд с адресом дискового обработчика
#include "hdinfo.asm"
HDEND   EQU $

OKNOEND EQU $
        DEPHASE
