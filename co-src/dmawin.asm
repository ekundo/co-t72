; ---------------------------------------------------------------------------
; Обмен с диском D: через буфер вне окна A000-DFFF.
;
; Второй квазидиск сидит на порту 011h, и одновременно с первым он работать не
; может -- так устроено железо, и README самой МикроДОС T-72 говорит об этом
; прямо: при обращении к квази-диску 2 адрес буфера в описателе дисковой
; операции не должен попадать в область экрана 0A000h..0DFFFh. Драйвер на время
; пересылки гасит первый квазидиск целиком, вместе с окном ОЗУ, так что буфер в
; этом окне обменивается данными не с ОЗУ, а с видеопамятью: чтение оставляет
; буфер нетронутым и рисует сектор полосой на экране, запись кладёт на диск
; содержимое экрана.
;
; У CO в окне лежат два буфера: просмотрщик (3-Просм) читает файл прямо в
; A000-DFFF, а настройки CO.PRM пишутся и читаются с A000 и A048. Перенести их
; некуда -- под просмотр нужно 16 КБ, а ниже A000 столько нет. Поэтому обмен
; идёт через штатный буфер CP/M по 0080: читаем туда и переписываем в окно,
; пишем -- наоборот. Лишние 128 байт пересылки на запись погоды не делают.
;
; Врезок пять, все одинаковые: "CALL 17F4 / CALL 1922" (установить адрес буфера
; и прочитать запись) и та же пара с 1947 для записи. Шесть байт меняются на
; вызов сюда и три NOP.
;
; После пересылки адрес буфера в БДОС возвращается настоящим -- как его и
; оставила бы исходная пара вызовов. Иначе у БДОС остался бы 0080, и следующая
; операция, которая на этот адрес рассчитывает (поиск в каталоге кладёт запись
; именно в буфер обмена), сработала бы не туда.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

SETDMA  EQU 017F4h              ; CO: БДОС-26, адрес буфера обмена из DE
BIOSRD  EQU 0C027h              ; БСВВ: чтение сектора по установкам БДОС
BIOSWR  EQU 0C02Ah              ; БСВВ: запись сектора
DMAPTR  EQU 0DDF6h              ; поле адреса буфера в описателе БДОС
RDREC   EQU 01922h              ; CO: БДОС-20, чтение очередной записи
WRREC   EQU 01947h              ; CO: БДОС-21, запись очередной записи
SCRAP   EQU 00080h              ; штатный буфер обмена CP/M -- он ниже окна
RECLEN  EQU 128

; Чтение записи в (DE). A -- код возврата БДОС, регистры целы.
read:   PUSH H
        PUSH D
        LXI  D,SCRAP
        CALL SETDMA
        CALL RDREC
        POP  D
        POP  H
        PUSH PSW
        PUSH H
        LXI  H,SCRAP
        CALL move               ; 0080 -> буфер
        POP  H
        CALL SETDMA             ; вернуть БДОС настоящий адрес буфера
        POP  PSW
        RET

; Запись записи из (DE). A -- код возврата БДОС, регистры целы.
write:  PUSH H
        PUSH D
        XCHG                    ; HL -- буфер
        LXI  D,SCRAP
        CALL move               ; буфер -> 0080
        LXI  D,SCRAP
        CALL SETDMA
        CALL WRREC
        POP  D
        PUSH PSW
        CALL SETDMA             ; вернуть БДОС настоящий адрес буфера
        POP  PSW
        POP  H
        RET

; Быстрый путь CO мимо БДОС: он сам крутит дорожку и сектор в описателе БДОС
; (DDF4/DDF5) и зовёт секторные подпрограммы БСВВ. Адрес буфера там уже стоит --
; берём его из описателя. Буфер ниже окна -- уходим в БСВВ как были.
brd:    LHLD DMAPTR
        MOV  A,H
        CPI  0A0h
        JC   BIOSRD             ; хвостовой переход, БСВВ вернётся к вызывающему
        PUSH H
        LXI  H,SCRAP
        SHLD DMAPTR
        CALL BIOSRD
        POP  D                  ; DE -- настоящий буфер
        PUSH PSW
        PUSH D
        LXI  H,SCRAP
        CALL move               ; 0080 -> буфер
        POP  H
        SHLD DMAPTR             ; вернуть настоящий адрес
        POP  PSW
        RET

bwr:    LHLD DMAPTR
        MOV  A,H
        CPI  0A0h
        JC   BIOSWR
        PUSH H
        LXI  D,SCRAP
        CALL move               ; буфер -> 0080
        LXI  H,SCRAP
        SHLD DMAPTR
        CALL BIOSWR
        POP  H
        SHLD DMAPTR
        RET

; 128 байт (HL) -> (DE); портит A и B, HL и DE возвращает как были.
move:   PUSH H
        PUSH D
        MVI  B,RECLEN
mv1:    MOV  A,M
        STAX D
        INX  H
        INX  D
        DCR  B
        JNZ  mv1
        POP  D
        POP  H
        RET
        END
