; ---------------------------------------------------------------------------
; Кодировки в просмотрщике -- своими силами.
;
; Меню F2 у CO (Р/Л, РУС, ЛАТ, К-8) переключало набор знакогенератора командами
; T-34: байты 0Eh/0Fh и последовательности "ESC [", "ESC \". T-72 таких команд
; не знает: 0Eh и 0Fh в её таблице управляющих кодов отсутствуют вовсе, а
; "ESC [" -- начало ANSI-последовательности, не набор. Работала только "ESC \",
; и не в том смысле: у T-72 это альтернативный ГОСТ.
;
; Основной набор консоли T-72 -- КОИ-8 (снято с машины: латиница 41..7A,
; строчная кириллица C0..DF, прописная E0..FF). Значит показать файл в нужной
; кодировке можно, ничего в системе не переключая: достаточно перед выводом
; знака пересчитать код. Этим и занята накладка.
;
; Режим берётся оттуда же, откуда его брал CO, -- третий знак метки по 3E8F:
;   'S' -- РУС: файл в КОИ-7 Н2, русские буквы стоят на местах латинских,
;               коды 40..7F переводим в кириллицу КОИ-8 прибавлением 80h;
;   'L' -- Р/Л: то же, но по переключателям внутри текста -- 0Fh переводит в
;               латиницу, 0Eh обратно в русский;
;   'T' -- ЛАТ: обратный ход -- кириллицу КОИ-8 (C0..FF) показываем латиницей,
;               чтобы прочитать русский файл латинскими буквами;
;   '8' -- К-8: файл уже в КОИ-8, коды не трогаем.
;
; Врезок две. По 328D в цикле вывода знака просмотрщика (было "CPI 20h /
; CC 331F") -- туда уходит каждый байт файла. По 101B -- бывший переключатель
; набора: он слал системе те самые несуществующие команды, теперь вместо этого
; ставим основной набор ("ESC Z") и сбрасываем состояние Р/Л на русское.
; ---------------------------------------------------------------------------
        ORG  ORIGIN

CTRL    EQU  0331Fh             ; CO: обработка управляющего знака в просмотрщике
MODE    EQU  03E8Fh             ; третий знак метки режима: 'S' 'L' 'T' '8'
ESCCH   EQU  01Bh

; --- вывод знака: перекодировать или отдать управляющий по-старому
put:    CPI  00Eh               ; переключатель "дальше по-русски"
        JZ   setrus
        CPI  00Fh               ; ... и "дальше латиницей"
        JZ   setlat
        CPI  020h
        JNC  code
        JMP  CTRL               ; управляющий -- хвостом в CO, как было

setrus: PUSH PSW
        MVI  A,001h
        STA  state
        POP  PSW
        RET                     ; сам переключатель печатаем: T-72 его не видит
setlat: PUSH PSW
        XRA  A
        STA  state
        POP  PSW
        RET

code:   STA  chr
        LDA  MODE
        CPI  'S'                ; РУС
        JZ   rus
        CPI  'T'                ; ЛАТ
        JZ   lat
        CPI  'L'                ; Р/Л
        JNZ  asis               ; '8' -- К-8, файл уже в КОИ-8
        LDA  state
        ORA  A
        JZ   lat                ; сейчас латиница
rus:    LDA  chr
        CPI  040h
        RC                      ; ниже 40h -- служебные знаки, как есть
        CPI  080h
        RNC                     ; 80h и выше в КОИ-7 не бывает
        ADI  080h               ; 40..7F -> C0..FF, кириллица КОИ-8
        RET
lat:    LDA  chr                ; обратный ход: кириллицу показываем латиницей
        CPI  0C0h
        RC
        SUI  080h               ; C0..FF -> 40..7F
        RET
asis:   LDA  chr
        RET

; --- открытие просмотрщика и запуск программ: набор ставим основной
init:   MVI  A,001h
        STA  state              ; Р/Л начинается с русского
        MVI  C,ESCCH
        RST  4
        MVI  C,'Z'              ; "ESC Z" -- основной набор (КОИ-8)
        RST  4
        RET

chr:    .db 0                   ; знак, пока читаем метку режима
state:  .db 1                   ; Р/Л: 1 -- русский, 0 -- латиница
        END
