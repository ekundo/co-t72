#!/bin/sh
# Прогнать CO по его функциям и проверить каждую двумя мерками.
#
#   ./check-funcs.sh out/            [os-t72hx.rom]
#
# Первая мерка -- функция действительно отработала. Критерий объективный: у CO
# две таблицы «клавиша -> обработчик», по 05DB и 0638, и сценарий засчитывается
# только если адрес обработчика попал в карту исполнения. Без этого «тест»
# доказывал бы лишь то, что эмулятор не упал: нажатие, которое CO проглотил,
# выглядит точно так же, как отработавшее.
#
# Вторая колонка -- подэкранная область A000-DFFF: что CO успел положить туда
# за сценарий. Это справка, а не приговор: CO там и работает, увести его оттуда
# пока некуда. Колонка нужна для будущего диска D: -- по ней будет видно, какие
# функции ещё держат данные в окне. DFC9-DFFF не в счёт, это сама ОС.
#
# Клавиши шлются сканкодами SDL без модификаторов, поэтому «СС+цифра» набирается
# как Shift плюс клавиша: keytyper понимает префиксы \001 (нажать) и \002
# (отпустить).
#
# Раскладка Вектора не совпадает с хостовой, и вслепую тут не угадать. Коды
# сняты с живого Вектора -- слежением за ячейкой B693, куда CO кладёт код нажатой
# клавиши:
#
#     хостовая '='        -> 2D '-'   снять все метки
#     Shift + '='         -> 3D '='   отметить как на другой панели
#     Shift + ';'         -> 2B '+'   отметить по маске
#     хостовая '-'        -> 40 '@'
#     Shift + '/'         -> 3F '?'
#     Escape              -> АР2
#     F8                  -> СТР
#     Backspace           -> ЗБ,  Return -> ВК,  Tab -> ТАБ,  правый Alt -> ПС
#     F7                  -> стрелка влево-вверх (в просмотрщике -- на весь экран)
#
# И ещё: по справке CO часть клавиш действует только при пустой командной
# строке, поэтому сценарии, где до этого открывалось приглашение, надо
# разделять -- иначе ввод уходит в него.
#
# Винчестер тоже под проверкой: подлинный v06x его не эмулирует, но в клоне
# репозитория он дописан (порты 50h..58h, ключ --hdd -- см. tools/v06x-README.md).
# Образ для сценариев собирает tools/mkhdd.py; помечены они четвёртым словом
# «винт» и идут только на основном прогоне.
set -e

OUT=${1:?каталог сборки, например out/}
HERE=$(cd "$(dirname "$0")" && pwd)
V06X=$HERE/tools/vector06sdl/build/v06x
ROM=${2:-$HERE/t72/os-t72hx.rom}
# путь к МикроДОС -- абсолютным, и проверить, что файл есть: прогон идёт со
# сменой каталога, относительный путь тут превращается в "файла нет". Эмулятор
# в этом случае поднимает свой загрузчик, CO не стартует вовсе, а прогон
# показывает "отработало" по всем сценариям -- ровно то, чего от него не ждут.
[ -f "$ROM" ] || { echo "нет МикроДОС: $ROM" >&2; exit 1; }
ROM=$(cd "$(dirname "$ROM")" && pwd)/$(basename "$ROM")
RUN=$HERE/run
OUT=$(cd "$OUT" && pwd)
TMP=$(mktemp -d)
# KEEPTMP=1 -- не убирать рабочий каталог: в нём остаются образы дисков,
# снимки памяти и сами следы, по которым разбираются неудачные сценарии.
[ -n "${KEEPTMP:-}" ] && echo "рабочий каталог: $TMP" || trap 'rm -rf "$TMP"' EXIT
mkdir -p "$RUN"

# Куски, куда никто не должен писать: это наш дописанный код. Их адреса
# сборка записала в layout.txt, а сторож стека сидит в самом эмуляторе.
# Стека это касается и там, где лежат наши буферы («стек-буфер»): стек,
# доросший до них, так же смертелен, как и доросший до кода.
GUARD=$(python3 -c 'import sys,os; rows=[l.strip().split(",") for l in open(sys.argv[1])] if os.path.exists(sys.argv[1]) else []; print(",".join("%04X-%04X" % (int(r[1],16), int(r[1],16)+int(r[2])-1) for r in rows if len(r)>2 and r[0].split("-")[0] in ("окно","стек")))' "$OUT/layout.txt")

# Накладка «дискета НЖМД» (tools/hddsel.py) живёт по адресу, который выбирает
# сборка; её сценарий проверяется по тому же правилу, что и все, -- попал ли
# адрес обработчика в карту исполнения, -- поэтому адрес берём из layout.txt.
HDSEL=$(python3 -c 'import sys,os; rows=[l.strip().split(",",3) for l in open(sys.argv[1])] if os.path.exists(sys.argv[1]) else []; print(next((r[1] for r in rows if len(r)>3 and r[3].strip()=="дискета НЖМД"), ""))' "$OUT/layout.txt")

# Образец винчестера: две «дискеты», на первой HDIR.COM, на второй справка.
# Метка у первой -- её показывает рамка панели (tools/hdinfo.py). Собирается
# один раз, сценарии работают по копиям.
HDDIMG=$TMP/винт.hdd
python3 "$HERE/tools/mkhdd.py" create "$HDDIMG" --disks 2 >/dev/null
python3 "$HERE/tools/mkhdd.py" put "$HDDIMG" 1 "$OUT/HDIR.COM" >/dev/null
python3 "$HERE/tools/mkhdd.py" put "$HDDIMG" 2 "$OUT/CO.HLP" >/dev/null
python3 "$HERE/tools/mkhdd.py" label "$HDDIMG" 1 'ПРОВЕРКА' >/dev/null

# Второй образец -- обрезанный: каталог дискеты цел, а данные файла лежат за
# концом образа. Настоящий винчестер отвечает на такое ошибкой, и наш тоже
# (src/hdd.h). Это единственный способ показать на стенде обработчик ошибки
# чтения записи (18FB): пустой образ дискеты v06x читает как обычный.
# Длинный CO.MNU. Список CO читает целиком и без предела, в окно с A000, а с
# A448 там накладки сборки -- обмен через буфер вне окна и прочее. Файл на три
# килобайта ложится прямо на них, и первое же обращение к диску уходит в
# мусор. Сценарий «длинноеменю» держит это место под присмотром.
BIGMNU=$TMP/большое.mnu
python3 - "$BIGMNU" <<'PY2'
import sys
out = []
for i in range(60):
    out.append('%X)  пункт номер %02d' % (i % 16, i))
    out.append('C:DIR')
out.append('0) Возврат к панелям.')
d = ''.join(l + '\r\n' for l in out).encode('koi8-r')
d += b'\x1a' * (-len(d) % 128)
open(sys.argv[1], 'wb').write(d)
PY2

# CO.MNU с тремя десятками пунктов. Таблицу меню по B728 CO чистит на 2Eh
# байт, перебирает на 1Ah записей, а ЗАПОЛНЯЕТ без всякого предела (3A1C):
# два байта на пункт. Двадцать четвёртый пункт ложится уже за таблицу -- в
# наш код под стеком. Файл при этом короткий, меньше килобайта: длину списка
# проверяет «длинноеменю», а это про другое.
MANYMNU=$TMP/много.mnu
python3 - "$MANYMNU" <<'PY3'
import sys
keys = '123456789ABCDEFGHIJKLMNOPQRSTU'          # ни одного «0»: он кончает список
out = []
for k in keys:
    out.append('%s)  пункт %s' % (k, k))
    out.append('C:DIR')
out.append('0) Возврат к панелям.')
d = ''.join(l + '\r\n' for l in out).encode('koi8-r')
d += b'\x1a' * (-len(d) % 128)
open(sys.argv[1], 'wb').write(d)
PY3

HDDBAD=$TMP/винт-обрез.hdd
python3 "$HERE/tools/mkhdd.py" create "$HDDBAD" --disks 1 >/dev/null
python3 "$HERE/tools/mkhdd.py" put "$HDDBAD" 1 "$OUT/CO.HLP" >/dev/null
python3 - "$HDDBAD" <<'PY2'
import sys
# 82 сектора заголовка и общих дорожек плюс восемь каталога -- дальше обрыв
d = open(sys.argv[1], 'rb').read()[:(82 + 8) * 512]
open(sys.argv[1], 'wb').write(d)
PY2

ok=0; bad=0

# KDFIX=1 -- наложить в ОЗУ диагностическую правку драйвера квазидиска (см.
# scripts/kd2-patch.inc) до старта CO: с ней обмен с D: идёт из любого буфера.
# Нужна, чтобы отделить «буфер в окне A000-DFFF» от прочих причин.
KDPATCH=; KDCALL=
if [ -n "${KDFIX:-}" ]; then
    KDPATCH=$(cat "$HERE/scripts/kd2-patch.inc")
    KDCALL='if (frameno == 400) { kd_patch() }'
fi

# DRIVE=D -- гонять те же сценарии с панелью на втором квазидиске. Подключается
# второй --edd (копия сборочного, чтобы было с чем работать), и перед клавишами
# сценария панель переводится на D: обычным путём: 7-Диск, стрелка вправо, ВК.
# Сценарий в этом случае набирается позже: CO поднимается только к 1300-му кадру,
# а переключение надо успеть сделать после него.
#
# DRIVE=B -- то же самое с панелью на втором дисководе. Ему подключается вторая
# дискета (копия сборочной): каталог диска B: CO держит копией в ОЗУ по 4000, и
# всё, что сборка дописала по адресу загрузки, этим каталогом затирается. Без
# такого прогона это и проскочило в 2.2.2.
DRIVE=${DRIVE:-C}
SWITCH=; PROBEAT=1500; MAXFRAME=3200; EDD2=; FDD2=
if [ "$DRIVE" = "D" ]; then
    SWITCH='if (frameno == 1400) { keytyper.types([60, "7", 200, "Right", 60, "Return", 200]) }'
    PROBEAT=2100
    MAXFRAME=4200
elif [ "$DRIVE" = "B" ]; then
    SWITCH='if (frameno == 1400) { keytyper.types([60, "7", 200, "Left", 60, "Return", 200]) }'
    PROBEAT=2100
    MAXFRAME=4200
fi

probe() {   # имя, обработчик, клавиши для keytyper, [чужой]
    # Четвёртым словом «чужой» помечаются сценарии, которые доводят дело до
    # запуска программы с диска: дальше памятью распоряжается она, и сторож
    # целости нашего кода к ней не относится -- CO там уже нет, а когда
    # вернётся, загрузится заново.
    name=$1; want=$2; keys=$3; alien=${4:-}
    # «архив» -- положить на диск пару файлов .PK2 и заглушку ARC2.COM: без них
    # не увидеть ни списка архивов, ни распаковки. Просмотр («3») на файле с
    # расширением PK2 показывает все .PK2 диска списком с метками, а ВК зовёт
    # ARC2. Заглушка нужна только чтобы её нашли по имени.
    #
    # «толькоC» -- сценарий имеет смысл только на основном прогоне. Таких два
    # рода: архивные (их файлы лежат на C:) и те, что опираются на отсутствие
    # второго дисковода -- на прогонах по B: и D: он подключён.
    # Признаки сбрасываются ДО разбора: ветка «*» их не увидит, если сценарий
    # помечен, и прошлый признак утёк бы в следующий сценарий. На этом уже
    # обожглись: «сА» снимал C:INITIALC.SUB, и все винчестерные сценарии после
    # него оставались без автозапуска.
    arc=; conly=; hdd=; froma=; bigmnu=
    case "$alien" in
        архив) alien=; arc=1; conly=1 ;;
        архив-чужой) alien=чужой; arc=1; conly=1 ;;
        толькоC) alien=; arc=; conly=1 ;;
        сА) alien=; arc=; conly=1; froma=1 ;;
        винт) alien=; arc=; conly=1; hdd=1 ;;
        винт-чужой) alien=чужой; arc=; conly=1; hdd=1 ;;
        винт-битый) alien=; arc=; conly=1; hdd=2 ;;
        длинное) alien=; arc=; conly=; bigmnu=1 ;;
        многопунктов) alien=; arc=; conly=; bigmnu=2 ;;
        *) ;;
    esac
    [ -n "$conly" ] && [ "${DRIVE:-C}" != C ] && return 0
    # Распаковке нужно время: ARC2 читает архив, пишет файл, потом панель
    # перечитывается -- иначе каталог остаётся в буфере ОС и в снятом образе
    # распакованного файла не видно.
    frames=$MAXFRAME
    [ -n "$arc" ] && frames=5400
    # Винчестеру тоже нужно время: команда «9» перечитывает каталог, а HDIR
    # обходит дискеты и пишет метку.
    [ -n "$hdd" ] && frames=5400
    # Запуску с дискеты тоже: CO сперва переносит на C: файлы из CO.ZGR.
    [ -n "$froma" ] && frames=5400
    # ONLY=имя -- прогнать один сценарий (или несколько через пробел): удобно,
    # когда разбираешься с ним по следу обращений, а не смотришь общую картину.
    if [ -n "${ONLY:-}" ]; then
        hit=
        for w in $ONLY; do [ "$w" = "$name" ] && hit=1; done
        [ -z "$hit" ] && return 0
    fi
    cat > "$TMP/$name.chai" <<EOF
$KDPATCH
def framefunc(frameno) {
    $KDCALL
    $SWITCH
    if (frameno == $PROBEAT) { keytyper.types([60, $keys]) }
    keytyper.onframe()
}
add_callback("frame", framefunc)
EOF
    cp "$OUT/co-t72.edd" "$TMP/$name.edd"
    # Панели в образе -- какими их оставил хозяин рабочего диска, а сценариям
    # нужна известная пара: меню дисков закольцовано, и "вправо" от разных букв
    # ведёт в разные места. Поэтому в копию кладём эталонный CO.PRM сборки.
    [ -f "$OUT/CO.PRM" ] && python3 "$HERE/tools/kdimg.py" put \
        "$TMP/$name.edd" "$OUT/CO.PRM" CO.PRM >/dev/null
    # «сА» -- поднять CO не с квазидиска, а с дискеты. Без C:INITIALC.SUB
    # система ищет автозапуск на A:, а там INITIAL.SUB с «A:CO». Этот путь у
    # CO свой: заставка и перенос файлов из CO.ZGR на C: (3EA0).
    if [ -n "$froma" ]; then
        python3 "$HERE/tools/kdimg.py" del "$TMP/$name.edd" INITIALC.SUB \
            >/dev/null 2>&1 || true
    fi
    # «длинное» -- положить вместо CO.MNU файл на три килобайта.
    if [ -n "$bigmnu" ]; then
        [ "$bigmnu" = 2 ] && SRC=$MANYMNU || SRC=$BIGMNU
        python3 "$HERE/tools/kdimg.py" put "$TMP/$name.edd" "$SRC" CO.MNU \
            >/dev/null
    fi
    if [ -n "$arc" ]; then
        # Архивы большие: два по 49 КБ плюс сам ARC2 -- больше сотни килобайт
        # свободного места. С тех пор как на квазидиск легли редактор и
        # показательный архив, столько там не набирается. В распаковке они не
        # участвуют -- убираем их из копии, а не с самого образа: остальные
        # сценарии гоняются по тому же диску, какой уезжает в выпуск.
        for f in VDE.COM VDE266.QRF DEMO.PK2; do
            python3 "$HERE/tools/kdimg.py" del "$TMP/$name.edd" "$f" \
                >/dev/null 2>&1 || true
        done
        # Настоящий архив и настоящий ARC2 лежат в work/co/ (их туда кладут
        # руками: ARC2 -- чужая программа, в репозитории ей не место). Есть --
        # берём их, нет -- обходимся пустышками: список архивов CO покажет и по
        # ним.
        #
        # Что именно класть. ARC2.COM -- «ARCHIVER V1.3 (C) V.KRUPSKY 1990»,
        # он есть на v06x/system-disk.fdd; CO рассчитан именно на него и кормит
        # ему ответы через «<C:CO.TOK». Каталог архива CO читает сам: записи по
        # 16 байт с начала файла -- признак (бит 7 -- конец), восемь знаков
        # имени, три расширения, слово длины и слово упакованного размера.
        # Архив от ARC.COM («Archiver V2.0, Goldsoft 1991») с той же дискеты
        # не годится: записи у него те же, но перед ними шестибайтная подпись
        # «ARC2.0», и список в CO съезжает. Отрезать подпись мало -- сжатие
        # другое, ARC2 отвечает DECODING ERROR.
        if [ -f "$HERE/work/co/TEST.PK2" ] && [ -f "$HERE/work/co/ARC2.COM" ]; then
            python3 "$HERE/tools/kdimg.py" put "$TMP/$name.edd" \
                "$HERE/work/co/TEST.PK2" TEST.PK2 >/dev/null
            python3 "$HERE/tools/kdimg.py" put "$TMP/$name.edd" \
                "$HERE/work/co/ARC2.COM" ARC2.COM >/dev/null
            python3 "$HERE/tools/kdimg.py" put "$TMP/$name.edd" \
                "$HERE/work/co/TEST.PK2" TEST2.PK2 >/dev/null
            # SAVEASM.COM лежит и в архиве, и на диске; убираем его с диска,
            # чтобы распаковке было куда класть и чтобы ARC2 не спрашивал про
            # замену. Появился обратно -- значит распаковка прошла.
            python3 "$HERE/tools/kdimg.py" del "$TMP/$name.edd" \
                SAVEASM.COM >/dev/null 2>&1 || true
        else
            printf 'PK2' > "$TMP/$name.pk2"
            for f in TEST.PK2 TEST2.PK2 ARC2.COM; do
                python3 "$HERE/tools/kdimg.py" put "$TMP/$name.edd" \
                    "$TMP/$name.pk2" "$f" >/dev/null
            done
        fi
    fi
    # «винт» -- подключить винчестер. Он подключается только тем сценариям,
    # которым нужен: с ним T-72 отдаёт CO другой состав оборудования, и
    # остальные сценарии мерили бы уже не то, что раньше.
    HDD=
    if [ -n "$hdd" ]; then
        [ "$hdd" = 2 ] && cp "$HDDBAD" "$TMP/$name.hdd" || cp "$HDDIMG" "$TMP/$name.hdd"
        HDD="--hdd $TMP/$name.hdd"
    fi
    if [ "$DRIVE" = "D" ]; then
        cp "$OUT/co-t72.edd" "$TMP/$name-d.edd"
        EDD2="--edd $TMP/$name-d.edd"
    elif [ "$DRIVE" = "B" ]; then
        cp "$OUT/co-t72.fdd" "$TMP/$name-b.fdd"
        FDD2="--fdd $TMP/$name-b.fdd"
    fi
    { ( cd "$RUN" && V06X_COV_LO=0x0100 V06X_COV_HI=0xBFFF V06X_COV_FILE="$TMP/$name.cov" \
        V06X_DATA_LO=0xA000 V06X_DATA_HI=0xDFFF V06X_DATA_FILE="$TMP/$name.dat" \
        V06X_GUARD="$GUARD" V06X_RAM_SAVE="$TMP/$name.ram" V06X_LPT=1 \
        V06X_EDD_SAVE="$TMP/$name-out.edd" \
        "$V06X" --rom "$ROM" --fdd "$OUT/co-t72.fdd" $FDD2 --edd "$TMP/$name.edd" $EDD2 $HDD \
        --script "$HERE/tools/vector06sdl/scripts/robotnik.chai" \
        --script "$TMP/$name.chai" \
        --max-frame $frames --save-frame $((frames - 1)) --novideo --nosound \
        >/dev/null 2>&1 ) || true; } 2>/dev/null
    # Последний кадр -- на нём сторож экрана и смотрит, не осталось ли мусора.
    # Имя кадру даёт эмулятор: <ром>_<кадр>.png в run/out.
    mv "$RUN/out/$(basename "${ROM%.rom}")_$((frames - 1)).png" "$TMP/$name.png" \
        2>/dev/null || true
    # COVDIR -- куда складывать карты исполнения: по ним видно, какой код за
    # весь прогон ни разу не исполнялся (кандидаты в мёртвый).
    # имя с буквой диска: прогоны на C:, B: и D: идут по разным веткам кода,
    # и складывать их надо вместе, а не поверх друг друга.
    #
    # Сценарии, поднимающие чужую программу, ложатся в «чужие» -- подкаталогом,
    # чтобы в подсчёт не шли: чужая программа грузится по тем же 0100 и живёт в
