; --- SBC HL,rr там, где следом читают Z ------------------------------------
;
; Умолчание считает Z по старшему байту -- у Z80 он по всем шестнадцати. Здесь
; следом стоит проверка на ноль, поэтому после вычитания добавлен `ORA L`: A в
; этот момент держит старший байт результата, и `H|L` даёт настоящий Z. Перенос
; при этом гаснет, но ни в одном из шести мест он дальше не нужен -- проверено
; по коду до ближайшей команды, которая его перебивает.
;
; Порядок внутри тела важен: `MOV H,A` должен стоять до `ORA L`, иначе в HL
; уедет не результат вычитания.

