; --- RRD ------------------------------------------------------------------
;
; Единственное место во всём VDE, и там A перед этим обнулён (`XOR A`), а в (HL)
; лежит ширина экрана: получается просто `(HL) = (HL)/16`, о чём и говорит
; авторский комментарий. Младшая тетрада исходного байта по правилам RRD уходит
; в A, поэтому она заранее откладывается на стек -- вместе с флагами, которые
; Z80 ставит по новому A.

@vdx2.asm:1975	RRD
	MOV	A,M
	ANI	0FH
	PUSH	PSW		; младшая тетрада -- будущее A, и флаги по нему
	MOV	A,M
	RRC
	RRC
	RRC
	RRC
	ANI	0FH
	MOV	M,A		; (HL) = старшая тетрада
	POP	PSW

