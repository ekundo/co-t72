; Профиль терминала под МикроДОС T-72 -- правки к тем же строкам исходника,
; которые в оригинале правила утилита VINSTALL. Её саму переносить не пришлось:
; вся настройка -- данные по адресам 0160h-01BFh, и задать их проще при сборке.
;
; Коды консоли сверены с монитором T-72 (MDOS_T-72/Source/_F600h.asm): набор
; почти VT52 -- ESC Y с прибавкой 20h, ESC K, ESC J, ESC A/B/C/D, ESC H,
; негатив ESC b и позитив ESC a. Экран 80x25: в разборе ESC Y стоят проверки
; `CPI 050h` на столбец и `CPI 019h` на строку.

@vdx1.asm:118	DB 'Unidos Osb4 Emul'
	DB	'MicroDOS T-72   '	; ID -- ровно 16 знаков

@vdx1.asm:120	DB 80
View:	DB	80			; столбцов -- как у консоли T-72

; Автоперенос: на последнем столбце монитор T-72 сам на новую строку не уходит,
; поэтому VDE должна выдавать CRLF сама.
@vdx1.asm:121	DB 0FFh
AuWrap:	DB	0			; автопереноса нет

@vdx1.asm:122	DB 24
Lines:	DB	25			; строк на экране

; Клавиши из таблицы монитора (_F600h.asm, L_F770): ЗБ 7Fh, стрелки
; влево 08h, вверх 19h, вправо 18h, вниз 1Ah.
@vdx1.asm:123	DB 0FFh
UsrKys:	DB	7FH			; ЗБ -- забой

@vdx1.asm:124	DB 0BH,0AH,0CH,0FFH
	DB	19H,1AH,18H,08H		; стрелки вверх, вниз, вправо, влево

@vdx1.asm:126	DB 2, ESC,'T',0,0,0,0
ClL:	DB	2, ESC,'K',0,0,0,0	; гашение до конца строки

@vdx1.asm:127	DB 1, 1AH,0,0,0,0,0,0
TInit:	DB	1, 1FH,0,0,0,0,0,0	; при входе -- очистить экран

@vdx1.asm:128	DB 1, 1AH,0,0,0,0,0,0
TUInit:	DB	1, 1FH,0,0,0,0,0,0	; и при выходе тоже

@vdx1.asm:129	DB 2, ESC,'j',0,0,0,0
AltOn:	DB	2, ESC,'b',0,0,0,0	; негатив

@vdx1.asm:130	DB 2, ESC,'k',0,0,0,0
AltOff:	DB	2, ESC,'a',0,0,0,0	; позитив

; Старший бит негатива не включает -- он нужен под русские буквы.
@vdx1.asm:131	DB 0
AltBit:	DB	0

; Главная строка под КОИ-8: выше этого кода знаки на экран не идут, вместо них
; печатается '?'. Ставим 0FEh, а не 0FFh: в PutCh стоит `INC A`, и от 0FFh
; получился бы ноль -- весь текст ушёл бы в '?'.
@vdx1.asm:132	DB 7FH
Filter:	DB	0FEH			; восьмибитный вывод: КОИ-8 идёт как есть

@vdx1.asm:134	DB ESC,'=',20h,20h
PCu:	DB	ESC,'Y',20H,20H		; адресация курсора: ESC Y, строка, столбец

; Вставки и удаления строки у T-72 нет. Нулевая длина -- это для VDE не ошибка:
; CtlStr на нуле возвращает перенос, и ScrlUD уходит на полную перерисовку.
@vdx1.asm:136	DB 2, ESC,'E',0,0,0,0
InsL:	DB	0, 0,0,0,0,0,0		; вставки строки нет -- перерисовка

@vdx1.asm:137	DB 2, ESC,'R',0,0,0,0
DelL:	DB	0, 0,0,0,0,0,0		; удаления строки нет -- перерисовка
