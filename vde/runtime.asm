; Заместители команд Z80, которых у 8080 нет вовсе.
;
; Требование ко всем: снаружи они должны выглядеть ровно так же, как выглядела
; бы команда Z80 -- те же регистры на выходе и те же флаги. Блочные пересылки у
; Z80 флагов не трогают, поэтому A и признаки уходят на стек целиком; блочный
; поиск обязан вернуть Z по последнему сравнению, поэтому искомое значение
; лежит в ячейке, а A работает счётчиком.
;
; Здесь же ячейки под IX/IY и под A: индексных регистров и теневого набора у
; 8080 нет, и транслятор переводит их в память (см. z80to8080.py).

; --- LDIR: (DE) <- (HL), пока BC не ноль ----------------------------------
zLDIR:	PUSH	PSW		; LDIR не трогает ни A, ни Z/S/C
zLDIR1:	MOV	A,M
	STAX	D
	INX	H
	INX	D
	DCX	B
	MOV	A,B
	ORA	C
	JNZ	zLDIR1
	POP	PSW
	RET

; --- LDDR: то же, но сверху вниз ------------------------------------------
zLDDR:	PUSH	PSW
zLDDR1:	MOV	A,M
	STAX	D
	DCX	H
	DCX	D
	DCX	B
	MOV	A,B
	ORA	C
	JNZ	zLDDR1
	POP	PSW
	RET

; --- CPIR: искать A вперёд, пока BC не ноль -------------------------------
;
; На выходе Z стоит по последнему сравнению, а чётность -- по счётчику: у Z80
; после блочного поиска в этом разряде лежит не паритет, а признак "BC ещё не
; ноль", и VDE ветвится именно по нему (`JP PO` -- счётчик исчерпан). Десять
; мест в исходнике, и все они здесь.
;
; На неудачном выходе сравнение повторяется с предыдущим байтом: проверка
; счётчика к этому времени уже перебила признак, а вернуть надо не её.
zCPIR:	STA	ztA		; A занят под проверку счётчика
zCPIR1:	LDA	ztA
	CMP	M
	INX	H
	DCX	B
	JZ	zCPpv		; совпало -- выходим с этим Z
	MOV	A,B
	ORA	C
	JNZ	zCPIR1
	DCX	H		; не нашли: восстановить флаги последнего сравнения
	LDA	ztA
	CMP	M
	INX	H
	JMP	zCPpv

; --- CPDR: то же назад ----------------------------------------------------
zCPDR:	STA	ztA
zCPDR1:	LDA	ztA
	CMP	M
	DCX	H
	DCX	B
	JZ	zCPpv
	MOV	A,B
	ORA	C
	JNZ	zCPDR1
	INX	H
	LDA	ztA
	CMP	M
	DCX	H
	JMP	zCPpv

; --- общий выход блочного поиска ------------------------------------------
;
; Двух признаков разом -- Z по сравнению и чётности по счётчику -- обычными
; командами не выставить: любая, что тронет чётность, перебьёт и Z. Поэтому
; байт флагов правится прямо на стеке, а `POP PSW` вносит его целиком.
; Разряды байта: 7 знак, 6 ноль, 4 полуперенос, 2 чётность, 0 перенос.
zCPpv:	PUSH	PSW		; флаги сравнения и искомое значение
	SHLD	ztHL		; HL -- найденное место, его беречь
	LXI	H,0
	DAD	SP		; HL -> байт флагов на вершине стека
	MOV	A,B
	ORA	C		; счётчик исчерпан?
	MOV	A,M		; байт флагов; MOV признаков не трогает
	JZ	zCPpo
	ORI	04H		; BC не ноль -- чётность взведена (PE)
	JMP	zCPsv
zCPpo:	ANI	0FBH		; BC ноль -- сброшена (PO)
zCPsv:	MOV	M,A
	LHLD	ztHL
	POP	PSW		; флаги целиком, уже с нужной чётностью
	RET

; --- EXX: обмен BC, DE, HL с теневым набором ------------------------------
;
; Теневой набор живёт в памяти. Обмен побайтный через A, а сам A и флаги
; спрятаны на стеке: EXX у Z80 не трогает ни того, ни другого.
; Каждый байт меняется по одному образцу: старое значение регистра уходит на
; стек, из ячейки берётся теневое, а старое ложится в ячейку. Указатель не
; нужен -- адреса ячеек известны, поэтому и HL меняется наравне с остальными.
zEXX:	PUSH	PSW
	MOV	A,B
	PUSH	PSW
	LDA	zShB
	MOV	B,A
	POP	PSW
	STA	zShB
	MOV	A,C
	PUSH	PSW
	LDA	zShC
	MOV	C,A
	POP	PSW
	STA	zShC
	MOV	A,D
	PUSH	PSW
	LDA	zShD
	MOV	D,A
	POP	PSW
	STA	zShD
	MOV	A,E
	PUSH	PSW
	LDA	zShE
	MOV	E,A
	POP	PSW
	STA	zShE
	MOV	A,H
	PUSH	PSW
	LDA	zShH
	MOV	H,A
	POP	PSW
	STA	zShH
	MOV	A,L
	PUSH	PSW
	LDA	zShL
	MOV	L,A
	POP	PSW
	STA	zShL
	POP	PSW
	RET

; --- EX AF,AF': обмен A и флагов с теневой парой --------------------------
zEXAF:	PUSH	H
	PUSH	PSW		; на стеке пара A-флаги
	LHLD	zShAF
	XTHL			; на стек -- теневую пару, в HL -- текущую
	SHLD	zShAF
	POP	PSW		; A и флаги -- из теневой пары
	POP	H
	RET

; --- ячейки ---------------------------------------------------------------
zIXp:	DW	0		; IX
zIYp:	DW	0		; IY
ztA:	DB	0		; A на время обходных последовательностей
ztHL:	DW	0		; HL на время правки байта флагов
zShB:	DB	0		; теневой набор
zShC:	DB	0
zShD:	DB	0
zShE:	DB	0
zShH:	DB	0
zShL:	DB	0
zShAF:	DW	0

; --- восстановление верха экрана после прокрутки ---------------------------
;
; Зовётся из ScrlUD, когда взведён OddDel. У T-72 прокрутка сдвигает весь экран,
; включая шапку, поэтому её надо нарисовать заново; линейку чинит сама VDE.
zScrlH:	CALL	DoHdr
	JMP	RulFix

; --- прокрутка вниз аппаратным сдвигом -------------------------------------
;
; Обратного сдвига консоль T-72 не умеет: курсор вверх с нулевой строки просто
; никуда не идёт (`P_FB92`: `DCR A` / `RM`). Но сам регистр сдвига ходит в обе
; стороны -- монитор при прокрутке вверх уменьшает ячейку сдвига на десять
; (высота знакоместа), значит увеличение на те же десять двигает картинку вниз.
;
; Ячейка zFFAB -- не чужая кухня: в описании МикроДОС назначение ячеек монитора
; FFA8-FFFF объявлено сохранённым, и программы обращаются к ним напрямую.
; Вывод в порт дублирует то, что монитор и сам делает по прерыванию, -- так
; картинка сдвигается сразу, не дожидаясь следующего.
;
; Верхнюю строку знакомест после сдвига нужно нарисовать заново -- это делает
; шапка. Без шапки (и в окне) закрыть верх нечем, и прокрутка отдаётся штатной
; полной перерисовке.
zScrlD:	LDA	NoHdrF
	LXI	H,WinFlg
	ORA	M
	JNZ	SetAl		; нечем закрыть верх -- перерисовываем всё
	LDA	zFFAB		; сдвиг экрана
	ADI	10		; строку вниз
	STA	zFFAB
	OUT	3
	;
	; Сверх знакомест наверху открывается ещё полоска развёртки: строк 256, а
	; знакомест 25 по 10, и три верхние строки не принадлежат ни одному знаку.
	; Вперёд туда уезжает низ шапки -- сплошная заливка, её не видно; назад --
	; верхушки букв, и сетка знаков на глаз рассыпается на те самые три точки.
	;
	; Сами мы эти строки не погасим: экран программе не виден. T-72 держит в
	; A000-DFFF окно ОЗУ квазидиска (`OUT 10h`, 23h) и гасит его только на
	; время собственного вывода (`L_F8B9`) -- для программы там её же память.
	;
	; Зато полосу гасит сам монитор: при прокрутке вперёд (`L_FAF9`) он чистит
	; ровно десять строк развёртки от текущего сдвига вниз -- то есть именно
	; те, что сейчас наверху. Значит: сдвинуть вниз, дать монитору прокрутить
	; вперёд (курсор в последнюю строку и перевод строки -- это и есть DelL),
	; и вернуть сдвиг. Итог: строка вниз и чистый верх.
	LXI	H,DelL
	CALL	CtlStr
	LDA	zFFAB		; монитор уменьшил сдвиг -- вернуть
	ADI	10
	STA	zFFAB
	OUT	3
	CALL	DoHdr		; шапку сдвинуло вниз -- рисуем заново
	JMP	RulFix		; и линейку, если она включена

; --- меню без выворотки ----------------------------------------------------
;
; MsgDsp ставит курсор наверх и печатает сообщение вывороткой (MakAlt/UnAlt).
; Для меню выворотка во весь экран тяжеловата -- печатаем их обычным знаком,
; а шапка, подсказки и вопросы остаются как были.
zMnuDsp:
	PUSH	H
	CALL	UpLft
	POP	H
	JMP	Dspla
