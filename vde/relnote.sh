#!/bin/sh
# README.txt внутрь архива выпуска VDE: ./relnote.sh <путь к VDE.COM>
set -e
com=$1
size=$(stat -f%z "$com")

cat <<EOF
VDE 2.67b под МикроДОС T-72 (Вектор-06Ц)

Экранный редактор Эрика Мейера, 1988 -- маленький, быстрый, с клавишами
WordStar. Здесь он переведён с Z80 на 8080 и доведён до работы под T-72.

VDE.COM -- $size байт. Отдельных файлов рядом ему не нужно: вся настройка
лежит внутри самой программы. Скопируйте его на свой диск и запускайте:

  VDE имяфайла

Диск в имени указывайте явно, если он не текущий: VDE A:PISMO.TXT. Имя файла
VDE разбирает сама, а диск по умолчанию берёт текущий.


ЧТО ЗДЕСЬ ИНАЧЕ, ЧЕМ У АВТОРА

Русский текст. Файлы и набор -- в КОИ-8, основном наборе консоли T-72: их
читают CO, KOD и HDIR без перекодировки. Ради этого выключена авторская
упаковка пробелов: у VDE старший бит байта в тексте значил "за знаком идёт
пробел", а у русской буквы этот бит свой. Одно исключает другое. Потеря только
в расходе памяти -- на диск файл и раньше писался обычными байтами.

Команды понимаются и в русской раскладке: ^K-С работает так же, как ^K-S.
Переключаться ради одной буквы не нужно.

Режим W (WordStar) в восьмибитном тексте смысла не имеет -- пользуйтесь A или N.

Прокрутка идёт аппаратным сдвигом экрана в обе стороны, а не перерисовкой.

Вставка и встроенные меню включены сразу. Меню -- по ^J, подменю по ^K, ^O и ^Q.


ЧТО СТОИТ ЗНАТЬ

АР2 -- это ESC авторской документации: отмена и второй префикс. АР2 со
стрелками сдвигает экран, АР2 с цифрой запускает макрос, АР2-M его задаёт.

Сообщение об ошибке снимается АР2 или пробелом.

Стрелки работают, и вместе с ними обычный набор WordStar: ^E, ^X, ^S, ^D.

^^ (смена регистра) -- это УС и клавиша "^"; в русской раскладке на ней "Ч".
Русские буквы она тоже переключает, кроме ю, ш, э, щ, ч и ъ.

Полный список клавиш -- в файле VDE-KEYS.svg рядом и в меню по ^J.


ДОКУМЕНТАЦИЯ

Рядом лежит авторская, из выпуска VDE 2.66: VDE266.DOC -- руководство,
VDE266.QRF -- краткая справка на один экран, VINST266.DOC -- описание настройки
терминала. Всё по-английски и относится к оригиналу; чем эта сборка отличается,
сказано выше.


ОТКУДА ЭТО

Авторский исходник VDE 2.67b -- vde267sc.lbr с Walnut Creek CD. Там же лежит
выпуск vde266.lbr с руководством автора (vde266.doc) и краткой справкой.

Перевод на 8080, профиль терминала и правки под T-72:
github.com/ekundo/co-t72, каталог vde.

Готовый VDE.COM собирается из авторского исходника на месте: vde/fetch-src.sh
добывает оригинал, vde/build.sh переводит и собирает.
EOF
