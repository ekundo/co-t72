; Восьмибитный текст: КОИ-8 вместо упаковки пробелов.
;
; VDE семибитная по устройству. Старший бит байта в тексте значит у неё "за
; этим знаком идёт пробел" -- так она ужимает текст в памяти, а при вводе с
; клавиатуры и при чтении файла бит просто снимается ("strip parity", как было
; принято при семибитных линиях).
;
; Русская буква КОИ-8 попадает под то же правило: "Т" -- это байт 0D4h, и он же
; "латинское T со скрытым пробелом". Различить нельзя никак, поэтому одно
; исключает другое, и выбрано первое: набор КОИ-8 у консоли T-72 основной, в
; нём же работают CO, KOD и HDIR.
;
; Здесь выключается вся упаковка -- и те места, что бит ставят, и те, что его
; читают. Потеря только в расходе памяти: на диск в режимах A и N файл и раньше
; писался обычными байтами, а сам формат файла не меняется.
;
; Режим W (WordStar) остаётся как был: его код весь под проверкой FMode, в
; восьмибитном тексте он просто не имеет смысла.

